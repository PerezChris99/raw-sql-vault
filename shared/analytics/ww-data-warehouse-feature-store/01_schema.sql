-- Purpose: synthetic warehouse staging, star schema and ML feature metadata.
-- Engine: PostgreSQL 15+; no extensions required.
-- Rerun safety: CREATE IF NOT EXISTS; no destructive reset.
-- Data is synthetic. Currency stays on each fact and must not be summed across currencies.

CREATE SCHEMA IF NOT EXISTS analytics_demo;

CREATE TABLE IF NOT EXISTS analytics_demo.dim_dates (
    calendar_date DATE PRIMARY KEY,
    calendar_year INTEGER NOT NULL,
    calendar_month INTEGER NOT NULL CHECK (calendar_month BETWEEN 1 AND 12),
    calendar_day INTEGER NOT NULL CHECK (calendar_day BETWEEN 1 AND 31),
    calendar_quarter INTEGER NOT NULL CHECK (calendar_quarter BETWEEN 1 AND 4)
);

CREATE TABLE IF NOT EXISTS analytics_demo.dim_products (
    product_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_sku TEXT NOT NULL UNIQUE,
    product_name TEXT NOT NULL,
    valid_from DATE NOT NULL DEFAULT CURRENT_DATE,
    valid_to DATE,
    CHECK (valid_to IS NULL OR valid_to >= valid_from)
);

CREATE TABLE IF NOT EXISTS analytics_demo.dim_locations (
    location_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    locality_code TEXT NOT NULL UNIQUE,
    locality_name TEXT NOT NULL,
    locality_type TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS analytics_demo.staging_sales (
    staging_row_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id UUID NOT NULL,
    source_system TEXT,
    source_sale_id TEXT,
    sold_at TIMESTAMPTZ,
    source_sku TEXT,
    locality_code TEXT,
    amount NUMERIC(18,2),
    currency TEXT,
    received_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (batch_id, source_system, source_sale_id)
);

CREATE TABLE IF NOT EXISTS analytics_demo.fact_sales (
    fact_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    calendar_date DATE NOT NULL REFERENCES analytics_demo.dim_dates(calendar_date) ON DELETE RESTRICT,
    product_key BIGINT NOT NULL REFERENCES analytics_demo.dim_products(product_key) ON DELETE RESTRICT,
    location_key BIGINT NOT NULL REFERENCES analytics_demo.dim_locations(location_key) ON DELETE RESTRICT,
    source_system TEXT NOT NULL,
    source_sale_id TEXT NOT NULL,
    sold_at TIMESTAMPTZ NOT NULL,
    amount NUMERIC(18,2) NOT NULL CHECK (amount >= 0),
    currency CHAR(3) NOT NULL,
    batch_id UUID NOT NULL,
    loaded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (source_system, source_sale_id)
);

CREATE INDEX IF NOT EXISTS ix_fact_sales_date_product_location
    ON analytics_demo.fact_sales(calendar_date, product_key, location_key);
CREATE INDEX IF NOT EXISTS ix_fact_sales_currency_date
    ON analytics_demo.fact_sales(currency, calendar_date);

CREATE TABLE IF NOT EXISTS analytics_demo.feature_registry (
    feature_name TEXT NOT NULL,
    entity_type TEXT NOT NULL,
    value_type TEXT NOT NULL CHECK (value_type IN ('numeric', 'text')),
    description TEXT NOT NULL,
    owner_ref TEXT NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (feature_name, entity_type)
);

CREATE TABLE IF NOT EXISTS analytics_demo.feature_values (
    feature_value_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type TEXT NOT NULL,
    entity_id TEXT NOT NULL,
    feature_name TEXT NOT NULL,
    feature_timestamp TIMESTAMPTZ NOT NULL,
    source_available_at TIMESTAMPTZ NOT NULL,
    numeric_value NUMERIC,
    text_value TEXT,
    source_record_ref TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (feature_name, entity_type)
        REFERENCES analytics_demo.feature_registry(feature_name, entity_type) ON DELETE RESTRICT,
    CHECK ((numeric_value IS NOT NULL)::INTEGER + (text_value IS NOT NULL)::INTEGER = 1),
    UNIQUE (entity_type, entity_id, feature_name, feature_timestamp, source_available_at, source_record_ref)
);

CREATE INDEX IF NOT EXISTS ix_feature_values_asof
    ON analytics_demo.feature_values(entity_type, entity_id, feature_name, feature_timestamp DESC, source_available_at DESC);

COMMENT ON TABLE analytics_demo.staging_sales IS
    'Raw synthetic arrivals; a staging row is not accepted fact data until batch validation passes.';
COMMENT ON TABLE analytics_demo.fact_sales IS
    'Sales fact table; currency is explicit and revenue must be grouped by currency.';
COMMENT ON COLUMN analytics_demo.feature_values.source_available_at IS
    'Earliest time this feature value was available to a model; prevents future-information leakage.';