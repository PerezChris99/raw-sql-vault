-- Purpose: normalized synthetic marketplace schema.
-- Engine: PostgreSQL 15+; no extensions required.
-- Rerun safety: CREATE IF NOT EXISTS; no destructive reset.

CREATE SCHEMA IF NOT EXISTS shop_demo;

CREATE TABLE IF NOT EXISTS shop_demo.customers (
    customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_ref TEXT NOT NULL UNIQUE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS shop_demo.products (
    product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku TEXT NOT NULL UNIQUE,
    product_name TEXT NOT NULL,
    unit_price NUMERIC(18,2) NOT NULL CHECK (unit_price >= 0),
    currency CHAR(3) NOT NULL,
    stock_quantity BIGINT NOT NULL DEFAULT 0 CHECK (stock_quantity >= 0),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS shop_demo.orders (
    order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES shop_demo.customers(customer_id) ON DELETE RESTRICT,
    currency CHAR(3) NOT NULL,
    status TEXT NOT NULL DEFAULT 'placed'
        CHECK (status IN ('placed', 'paid', 'fulfilled', 'cancelled')),
    total_amount NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (total_amount >= 0),
    idempotency_key TEXT NOT NULL UNIQUE CHECK (length(btrim(idempotency_key)) > 0),
    request_payload JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_orders_customer_created
    ON shop_demo.orders(customer_id, created_at DESC);
CREATE INDEX IF NOT EXISTS ix_orders_status_created
    ON shop_demo.orders(status, created_at DESC);

CREATE TABLE IF NOT EXISTS shop_demo.order_items (
    order_id BIGINT NOT NULL REFERENCES shop_demo.orders(order_id) ON DELETE RESTRICT,
    product_id BIGINT NOT NULL REFERENCES shop_demo.products(product_id) ON DELETE RESTRICT,
    quantity BIGINT NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(18,2) NOT NULL CHECK (unit_price >= 0),
    line_total NUMERIC(18,2) GENERATED ALWAYS AS (quantity * unit_price) STORED,
    PRIMARY KEY (order_id, product_id)
);
CREATE INDEX IF NOT EXISTS ix_order_items_product
    ON shop_demo.order_items(product_id, order_id);

CREATE TABLE IF NOT EXISTS shop_demo.order_events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES shop_demo.orders(order_id) ON DELETE RESTRICT,
    previous_status TEXT,
    new_status TEXT NOT NULL CHECK (new_status IN ('placed', 'paid', 'fulfilled', 'cancelled')),
    actor_ref TEXT NOT NULL,
    event_note TEXT NOT NULL,
    happened_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_order_events_order_time
    ON shop_demo.order_events(order_id, happened_at DESC);

CREATE OR REPLACE FUNCTION shop_demo.fn_set_updated_at()
RETURNS TRIGGER LANGUAGE plpgsql SET search_path = pg_catalog, shop_demo
AS $function$
BEGIN
    NEW.updated_at := clock_timestamp();
    RETURN NEW;
END;
$function$;

DROP TRIGGER IF EXISTS trg_products_updated_at ON shop_demo.products;
CREATE TRIGGER trg_products_updated_at BEFORE UPDATE ON shop_demo.products
FOR EACH ROW EXECUTE FUNCTION shop_demo.fn_set_updated_at();

DROP TRIGGER IF EXISTS trg_orders_updated_at ON shop_demo.orders;
CREATE TRIGGER trg_orders_updated_at BEFORE UPDATE ON shop_demo.orders
FOR EACH ROW EXECUTE FUNCTION shop_demo.fn_set_updated_at();

COMMENT ON TABLE shop_demo.orders IS
    'Synthetic orders. Payment-card data is intentionally not stored.';
COMMENT ON TABLE shop_demo.order_events IS
    'Order status history; refund/processor events require separate production design.';