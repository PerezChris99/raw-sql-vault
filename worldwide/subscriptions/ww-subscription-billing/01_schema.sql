-- PostgreSQL 15+; no cardholder/payment credential fields are stored.
CREATE SCHEMA IF NOT EXISTS subscription_demo;
CREATE TABLE IF NOT EXISTS subscription_demo.customers(
 customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,customer_ref TEXT NOT NULL UNIQUE,
 is_active BOOLEAN NOT NULL DEFAULT TRUE,created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS subscription_demo.plans(
 plan_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,plan_code TEXT NOT NULL UNIQUE,
 plan_name TEXT NOT NULL,billing_interval TEXT NOT NULL CHECK(billing_interval IN('monthly','annual')),
 price_amount NUMERIC(18,2) NOT NULL CHECK(price_amount>0),currency CHAR(3) NOT NULL,
 is_active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS subscription_demo.subscriptions(
 subscription_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,subscription_ref TEXT NOT NULL UNIQUE,
 customer_id BIGINT NOT NULL REFERENCES subscription_demo.customers(customer_id) ON DELETE RESTRICT,
 plan_id BIGINT NOT NULL REFERENCES subscription_demo.plans(plan_id) ON DELETE RESTRICT,
 status TEXT NOT NULL DEFAULT 'trialing' CHECK(status IN('trialing','active','past_due','cancelled')),
 started_at TIMESTAMPTZ NOT NULL,current_period_start DATE NOT NULL,current_period_end DATE NOT NULL,
 cancel_at_period_end BOOLEAN NOT NULL DEFAULT FALSE,created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK(current_period_end>current_period_start)
);
CREATE TABLE IF NOT EXISTS subscription_demo.invoices(
 invoice_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,invoice_ref TEXT NOT NULL UNIQUE,
 subscription_id BIGINT NOT NULL REFERENCES subscription_demo.subscriptions(subscription_id) ON DELETE RESTRICT,
 period_start DATE NOT NULL,period_end DATE NOT NULL,amount_due NUMERIC(18,2) NOT NULL CHECK(amount_due>0),
 currency CHAR(3) NOT NULL,due_date DATE NOT NULL,
 status TEXT NOT NULL DEFAULT 'open' CHECK(status IN('open','paid','void','failed')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),paid_at TIMESTAMPTZ,
 UNIQUE(subscription_id,period_start),CHECK(period_end>period_start),
 CHECK(status<>'paid' OR paid_at IS NOT NULL)
);
CREATE TABLE IF NOT EXISTS subscription_demo.payments(
 payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,payment_ref TEXT NOT NULL UNIQUE,
 invoice_id BIGINT NOT NULL REFERENCES subscription_demo.invoices(invoice_id) ON DELETE RESTRICT,
 amount NUMERIC(18,2) NOT NULL CHECK(amount>0),currency CHAR(3) NOT NULL,
 external_reference TEXT NOT NULL,idempotency_key TEXT NOT NULL UNIQUE,
 paid_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS subscription_demo.invoice_events(
 event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,invoice_id BIGINT NOT NULL REFERENCES subscription_demo.invoices(invoice_id) ON DELETE RESTRICT,
 previous_status TEXT,new_status TEXT NOT NULL CHECK(new_status IN('open','paid','void','failed')),
 note TEXT NOT NULL,actor_ref TEXT NOT NULL,happened_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_subscription_status_period ON subscription_demo.subscriptions(status,current_period_end);
CREATE INDEX IF NOT EXISTS ix_subscription_invoice_due ON subscription_demo.invoices(status,due_date);
CREATE INDEX IF NOT EXISTS ix_subscription_payment_invoice ON subscription_demo.payments(invoice_id,paid_at DESC);
CREATE INDEX IF NOT EXISTS ix_subscription_invoice_events ON subscription_demo.invoice_events(invoice_id,happened_at DESC);
COMMENT ON TABLE subscription_demo.payments IS 'Synthetic payment settlement references only; no card/payment credential data.';