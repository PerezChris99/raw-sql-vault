-- PostgreSQL 15+; synthetic metadata only. Re-runnable; no reset.
CREATE SCHEMA IF NOT EXISTS works_demo;
CREATE TABLE IF NOT EXISTS works_demo.road_assets(
 road_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 road_code TEXT NOT NULL UNIQUE, road_name TEXT NOT NULL,
 locality_code TEXT NOT NULL, road_class TEXT NOT NULL CHECK(road_class IN('national','district','urban','community')),
 length_metres NUMERIC(12,2) NOT NULL CHECK(length_metres>0),
 is_active BOOLEAN NOT NULL DEFAULT TRUE, created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS works_demo.road_inspections(
 inspection_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 road_id BIGINT NOT NULL REFERENCES works_demo.road_assets(road_id) ON DELETE RESTRICT,
 observed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 condition_rating TEXT NOT NULL CHECK(condition_rating IN('good','fair','poor','critical')),
 safety_priority SMALLINT NOT NULL CHECK(safety_priority BETWEEN 1 AND 5),
 inspector_ref TEXT NOT NULL, observation_note TEXT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS works_demo.work_orders(
 work_order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 work_order_ref TEXT NOT NULL UNIQUE, road_id BIGINT NOT NULL REFERENCES works_demo.road_assets(road_id) ON DELETE RESTRICT,
 inspection_id BIGINT REFERENCES works_demo.road_inspections(inspection_id) ON DELETE RESTRICT,
 summary TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'planned'
 CHECK(status IN('planned','in_progress','blocked','completed','cancelled')),
 priority SMALLINT NOT NULL CHECK(priority BETWEEN 1 AND 5),
 estimated_cost_ugx NUMERIC(18,2) NOT NULL CHECK(estimated_cost_ugx>=0),
 actual_cost_ugx NUMERIC(18,2) CHECK(actual_cost_ugx IS NULL OR actual_cost_ugx>=0),
 due_date DATE, completed_at TIMESTAMPTZ, created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(), is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
 CHECK(status<>'completed' OR completed_at IS NOT NULL)
);
CREATE TABLE IF NOT EXISTS works_demo.work_order_events(
 event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 work_order_id BIGINT NOT NULL REFERENCES works_demo.work_orders(work_order_id) ON DELETE RESTRICT,
 previous_status TEXT,new_status TEXT NOT NULL CHECK(new_status IN('planned','in_progress','blocked','completed','cancelled')),
 event_note TEXT NOT NULL,actor_ref TEXT NOT NULL,happened_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_works_inspections_road_time ON works_demo.road_inspections(road_id,observed_at DESC);
CREATE INDEX IF NOT EXISTS ix_works_orders_status_due ON works_demo.work_orders(status,due_date) WHERE is_deleted=FALSE;
CREATE INDEX IF NOT EXISTS ix_works_events_history ON works_demo.work_order_events(work_order_id,happened_at DESC,event_id DESC);
CREATE OR REPLACE FUNCTION works_demo.fn_touch_updated_at() RETURNS TRIGGER LANGUAGE plpgsql SET search_path=pg_catalog,works_demo AS $$
BEGIN NEW.updated_at:=clock_timestamp(); RETURN NEW; END; $$;
DROP TRIGGER IF EXISTS trg_works_orders_updated_at ON works_demo.work_orders;
CREATE TRIGGER trg_works_orders_updated_at BEFORE UPDATE ON works_demo.work_orders FOR EACH ROW EXECUTE FUNCTION works_demo.fn_touch_updated_at();
COMMENT ON TABLE works_demo.road_assets IS 'Synthetic asset reference data; not a verified national road inventory.';
COMMENT ON TABLE works_demo.road_inspections IS 'Timestamped observations; condition ratings require an approved inspection standard in real use.';