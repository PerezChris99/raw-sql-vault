-- PostgreSQL 15+; invented water points/results only. Rerunnable, no destructive reset.
CREATE SCHEMA IF NOT EXISTS water_demo;
CREATE TABLE IF NOT EXISTS water_demo.water_points(
 point_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 point_code TEXT NOT NULL UNIQUE, point_name TEXT NOT NULL,
 locality_code TEXT NOT NULL, source_type TEXT NOT NULL CHECK(source_type IN('borehole','protected_spring','standpipe','piped_supply','rainwater','other')),
 operator_ref TEXT, is_active BOOLEAN NOT NULL DEFAULT TRUE, commissioned_on DATE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS water_demo.water_observations(
 observation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 observation_ref TEXT NOT NULL UNIQUE,
 point_id BIGINT NOT NULL REFERENCES water_demo.water_points(point_id) ON DELETE RESTRICT,
 sampled_at TIMESTAMPTZ NOT NULL, received_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 method_ref TEXT NOT NULL, standard_ref TEXT NOT NULL,
 ph_value NUMERIC(5,2), turbidity_ntu NUMERIC(10,2), ecoli_cfu_per_100ml NUMERIC(12,2),
 outcome TEXT NOT NULL CHECK(outcome IN('pending','acceptable','unacceptable','inconclusive')),
 result_note TEXT NOT NULL, reviewer_ref TEXT,
 CHECK(ph_value IS NULL OR ph_value BETWEEN 0 AND 14),
 CHECK(turbidity_ntu IS NULL OR turbidity_ntu>=0),
 CHECK(ecoli_cfu_per_100ml IS NULL OR ecoli_cfu_per_100ml>=0),
 CHECK(outcome='pending' OR reviewer_ref IS NOT NULL)
);
CREATE TABLE IF NOT EXISTS water_demo.maintenance_jobs(
 job_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 job_ref TEXT NOT NULL UNIQUE, point_id BIGINT NOT NULL REFERENCES water_demo.water_points(point_id) ON DELETE RESTRICT,
 observation_id BIGINT REFERENCES water_demo.water_observations(observation_id) ON DELETE RESTRICT,
 summary TEXT NOT NULL,status TEXT NOT NULL DEFAULT 'planned'
 CHECK(status IN('planned','in_progress','blocked','completed','cancelled')),
 priority SMALLINT NOT NULL CHECK(priority BETWEEN 1 AND 5),
 estimate_ugx NUMERIC(18,2) NOT NULL CHECK(estimate_ugx>=0),
 actual_ugx NUMERIC(18,2) CHECK(actual_ugx IS NULL OR actual_ugx>=0),
 due_date DATE, completed_at TIMESTAMPTZ, created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
 CHECK(status<>'completed' OR completed_at IS NOT NULL)
);
CREATE TABLE IF NOT EXISTS water_demo.maintenance_events(
 event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 job_id BIGINT NOT NULL REFERENCES water_demo.maintenance_jobs(job_id) ON DELETE RESTRICT,
 previous_status TEXT,new_status TEXT NOT NULL CHECK(new_status IN('planned','in_progress','blocked','completed','cancelled')),
 event_note TEXT NOT NULL,actor_ref TEXT NOT NULL,happened_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_water_obs_point_sampled ON water_demo.water_observations(point_id,sampled_at DESC);
CREATE INDEX IF NOT EXISTS ix_water_jobs_open_due ON water_demo.maintenance_jobs(status,due_date) WHERE is_deleted=FALSE AND status NOT IN('completed','cancelled');
CREATE INDEX IF NOT EXISTS ix_water_events_job_time ON water_demo.maintenance_events(job_id,happened_at DESC,event_id DESC);
COMMENT ON TABLE water_demo.water_observations IS 'Synthetic observation values; interpretation requires the named method/standard and authorised reviewer.';