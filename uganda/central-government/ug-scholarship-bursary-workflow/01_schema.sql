-- Purpose: human-reviewed scholarship/bursary application, appeal and disbursement workflow.
-- Engine: PostgreSQL 15+. Prerequisites: none. Rerunnable: yes; additive.
CREATE SCHEMA IF NOT EXISTS ug_bursary;

CREATE TABLE IF NOT EXISTS ug_bursary.programmes (
 programme_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 programme_code TEXT NOT NULL UNIQUE CHECK (programme_code ~ '^[A-Z0-9_-]{3,48}$'),
 programme_name TEXT NOT NULL CHECK (length(btrim(programme_name))>0),
 academic_year TEXT NOT NULL CHECK (academic_year ~ '^[0-9]{4}(/[0-9]{4})?$'),
 sponsor_ref TEXT NOT NULL CHECK (length(btrim(sponsor_ref))>0),
 opens_on DATE NOT NULL,
 closes_on DATE NOT NULL,
 award_amount NUMERIC(14,2) NOT NULL CHECK (award_amount>0),
 currency_code CHAR(3) NOT NULL DEFAULT 'UGX' CHECK (currency_code ~ '^[A-Z]{3}$'),
 programme_status TEXT NOT NULL DEFAULT 'draft' CHECK (programme_status IN ('draft','open','closed','retired')),
 CHECK (closes_on>=opens_on)
);

CREATE TABLE IF NOT EXISTS ug_bursary.applications (
 application_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 application_ref TEXT NOT NULL UNIQUE CHECK (application_ref ~ '^UGB-[A-Z0-9-]{4,40}$'),
 programme_id BIGINT NOT NULL REFERENCES ug_bursary.programmes(programme_id) ON DELETE RESTRICT,
 student_ref TEXT NOT NULL CHECK (length(btrim(student_ref)) BETWEEN 3 AND 96),
 school_ref TEXT NOT NULL CHECK (length(btrim(school_ref)) BETWEEN 3 AND 96),
 status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','submitted','under_review','awaiting_documents','approved','rejected','withdrawn')),
 submitted_at TIMESTAMPTZ,
 decision_at TIMESTAMPTZ,
 decision_evidence_ref TEXT,
 decision_reason TEXT,
 created_by TEXT NOT NULL CHECK (length(btrim(created_by))>0),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(programme_id,student_ref),
 CHECK ((status IN ('approved','rejected')) = (decision_at IS NOT NULL)),
 CHECK ((decision_at IS NULL AND decision_evidence_ref IS NULL AND decision_reason IS NULL)
    OR (decision_at IS NOT NULL AND length(btrim(COALESCE(decision_evidence_ref,'')))>0 AND length(btrim(COALESCE(decision_reason,'')))>0))
);

CREATE TABLE IF NOT EXISTS ug_bursary.application_events (
 event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 application_id BIGINT NOT NULL REFERENCES ug_bursary.applications(application_id) ON DELETE RESTRICT,
 event_type TEXT NOT NULL CHECK (event_type IN ('created','submitted','assigned_for_review','requested_documents','approved','rejected','withdrawn','appeal_filed','appeal_upheld','appeal_overturned','correction')),
 from_status TEXT,
 to_status TEXT NOT NULL CHECK (to_status IN ('draft','submitted','under_review','awaiting_documents','approved','rejected','withdrawn')),
 actor_ref TEXT NOT NULL CHECK (length(btrim(actor_ref))>0),
 reason TEXT NOT NULL CHECK (length(btrim(reason))>0),
 evidence_reference TEXT,
 occurred_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS ug_bursary.document_metadata (
 document_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 application_id BIGINT NOT NULL REFERENCES ug_bursary.applications(application_id) ON DELETE RESTRICT,
 document_type TEXT NOT NULL CHECK (length(btrim(document_type))>0),
 object_ref TEXT NOT NULL CHECK (length(btrim(object_ref))>0),
 sha256_hex TEXT NOT NULL CHECK (sha256_hex ~ '^[0-9a-f]{64}$'),
 classification TEXT NOT NULL DEFAULT 'restricted' CHECK (classification IN ('internal','restricted','highly_restricted')),
 uploaded_by TEXT NOT NULL CHECK (length(btrim(uploaded_by))>0),
 received_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(application_id,document_type,sha256_hex)
);

CREATE TABLE IF NOT EXISTS ug_bursary.appeals (
 appeal_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 appeal_ref TEXT NOT NULL UNIQUE CHECK (appeal_ref ~ '^UGBA-[A-Z0-9-]{4,40}$'),
 application_id BIGINT NOT NULL REFERENCES ug_bursary.applications(application_id) ON DELETE RESTRICT,
 filed_by_ref TEXT NOT NULL CHECK (length(btrim(filed_by_ref))>0),
 reason TEXT NOT NULL CHECK (length(btrim(reason))>0),
 evidence_reference TEXT NOT NULL CHECK (length(btrim(evidence_reference))>0),
 status TEXT NOT NULL DEFAULT 'submitted' CHECK (status IN ('submitted','under_review','closed')),
 outcome TEXT CHECK (outcome IS NULL OR outcome IN ('upheld','overturned')),
 reviewed_by TEXT,
 reviewed_at TIMESTAMPTZ,
 review_reason TEXT,
 review_evidence_reference TEXT,
 filed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK ((status='closed') = (reviewed_at IS NOT NULL)),
 CHECK ((reviewed_at IS NULL AND outcome IS NULL AND reviewed_by IS NULL AND review_reason IS NULL AND review_evidence_reference IS NULL)
    OR (reviewed_at IS NOT NULL AND outcome IS NOT NULL AND length(btrim(COALESCE(reviewed_by,'')))>0
        AND length(btrim(COALESCE(review_reason,'')))>0 AND length(btrim(COALESCE(review_evidence_reference,'')))>0))
);

CREATE TABLE IF NOT EXISTS ug_bursary.disbursements (
 disbursement_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 disbursement_ref TEXT NOT NULL UNIQUE CHECK (disbursement_ref ~ '^UGBD-[A-Z0-9-]{4,40}$'),
 idempotency_key TEXT NOT NULL UNIQUE CHECK (length(btrim(idempotency_key)) BETWEEN 8 AND 128),
 application_id BIGINT NOT NULL REFERENCES ug_bursary.applications(application_id) ON DELETE RESTRICT,
 amount NUMERIC(14,2) NOT NULL CHECK (amount>0),
 currency_code CHAR(3) NOT NULL CHECK (currency_code ~ '^[A-Z]{3}$'),
 external_payment_ref TEXT NOT NULL UNIQUE CHECK (length(btrim(external_payment_ref))>0),
 paid_at TIMESTAMPTZ NOT NULL,
 recorded_by TEXT NOT NULL CHECK (length(btrim(recorded_by))>0),
 recorded_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_bursary_application_queue ON ug_bursary.applications(status,submitted_at,application_id);
CREATE INDEX IF NOT EXISTS ix_bursary_application_programme ON ug_bursary.applications(programme_id,status);
CREATE INDEX IF NOT EXISTS ix_bursary_events_history ON ug_bursary.application_events(application_id,occurred_at DESC,event_id DESC);
CREATE INDEX IF NOT EXISTS ix_bursary_appeal_queue ON ug_bursary.appeals(status,filed_at,appeal_id);
CREATE INDEX IF NOT EXISTS ix_bursary_disbursements_app ON ug_bursary.disbursements(application_id,paid_at DESC);

COMMENT ON SCHEMA ug_bursary IS 'Synthetic scholarship/bursary workflow; no real student data or official eligibility rules.';
COMMENT ON COLUMN ug_bursary.applications.student_ref IS 'Opaque student reference only; never store names, national IDs, contact details or grades in this demo.';
COMMENT ON COLUMN ug_bursary.document_metadata.object_ref IS 'Reference to separately secured document storage; no document bytes are stored here.';
