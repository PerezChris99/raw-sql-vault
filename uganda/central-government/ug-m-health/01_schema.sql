-- Purpose: normalized synthetic facility/medicine/lot inventory schema.
-- Engine: PostgreSQL 15+.
-- Rerun safety: CREATE IF NOT EXISTS; no reset.
-- All initial data in 02_seed.sql is fictional. Do not include patient records.

CREATE SCHEMA IF NOT EXISTS medicine_demo;

CREATE TABLE IF NOT EXISTS medicine_demo.facilities (
    facility_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    facility_code TEXT NOT NULL UNIQUE,
    facility_name TEXT NOT NULL,
    facility_type TEXT NOT NULL CHECK (facility_type IN ('hospital', 'health_centre', 'clinic', 'store')),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS medicine_demo.medicine_products (
    product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_code TEXT NOT NULL UNIQUE,
    generic_name TEXT NOT NULL,
    strength TEXT NOT NULL,
    dosage_form TEXT NOT NULL,
    unit_of_issue TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (generic_name, strength, dosage_form, unit_of_issue)
);

CREATE TABLE IF NOT EXISTS medicine_demo.medicine_batches (
    batch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES medicine_demo.medicine_products(product_id) ON DELETE RESTRICT,
    batch_number TEXT NOT NULL,
    expiry_date DATE NOT NULL,
    batch_status TEXT NOT NULL DEFAULT 'active'
        CHECK (batch_status IN ('active', 'quarantined', 'recalled', 'closed')),
    received_cost NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (received_cost >= 0),
    currency CHAR(3) NOT NULL DEFAULT 'UGX',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (product_id, batch_number)
);

CREATE TABLE IF NOT EXISTS medicine_demo.stock_movements (
    movement_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    facility_id BIGINT NOT NULL REFERENCES medicine_demo.facilities(facility_id) ON DELETE RESTRICT,
    batch_id BIGINT NOT NULL REFERENCES medicine_demo.medicine_batches(batch_id) ON DELETE RESTRICT,
    quantity_delta BIGINT NOT NULL CHECK (quantity_delta <> 0),
    movement_reason TEXT NOT NULL
        CHECK (movement_reason IN ('receipt', 'issue', 'return_to_stock', 'wastage', 'adjustment')),
    idempotency_key TEXT NOT NULL UNIQUE CHECK (length(btrim(idempotency_key)) > 0),
    source_reference TEXT,
    actor_reference TEXT NOT NULL CHECK (length(btrim(actor_reference)) > 0),
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_medicine_batches_product_expiry
    ON medicine_demo.medicine_batches(product_id, expiry_date, batch_status);
CREATE INDEX IF NOT EXISTS ix_stock_movements_facility_batch_time
    ON medicine_demo.stock_movements(facility_id, batch_id, recorded_at DESC, movement_id DESC);
CREATE INDEX IF NOT EXISTS ix_stock_movements_batch
    ON medicine_demo.stock_movements(batch_id);

COMMENT ON TABLE medicine_demo.medicine_batches IS
    'Medicine batch/lot expiry and status; one row represents one product lot.';
COMMENT ON TABLE medicine_demo.stock_movements IS
    'Append-oriented signed stock ledger by facility and batch. Correct with compensating movements.';
COMMENT ON COLUMN medicine_demo.stock_movements.quantity_delta IS
    'Positive adds usable stock; negative issues or writes it off; never edit historic movements.';