-- Purpose: normalized schema for synthetic programme coordination actions.
-- Engine: PostgreSQL 15+; fresh or compatible development database.
-- Rerun safety: CREATE IF NOT EXISTS and CREATE OR REPLACE are used.
-- Destructive: no. Fixtures are in 02_seed.sql and test-only cleanup in 08_tests.sql.

CREATE SCHEMA IF NOT EXISTS opm_demo;

CREATE TABLE IF NOT EXISTS opm_demo.departments (
    department_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_code TEXT NOT NULL UNIQUE,
    department_name TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS opm_demo.programme_actions (
    action_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference_code TEXT NOT NULL UNIQUE,
    title TEXT NOT NULL CHECK (length(btrim(title)) > 0),
    description TEXT,
    sponsor_department_id BIGINT NOT NULL REFERENCES opm_demo.departments(department_id) ON DELETE RESTRICT,
    owner_department_id BIGINT NOT NULL REFERENCES opm_demo.departments(department_id) ON DELETE RESTRICT,
    due_date DATE,
    status TEXT NOT NULL DEFAULT 'planned'
        CHECK (status IN ('planned', 'in_progress', 'blocked', 'done', 'cancelled')),
    outcome_note TEXT,
    created_by_ref TEXT NOT NULL DEFAULT 'demo-system',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX IF NOT EXISTS ix_programme_actions_sponsor
    ON opm_demo.programme_actions(sponsor_department_id);
CREATE INDEX IF NOT EXISTS ix_programme_actions_owner
    ON opm_demo.programme_actions(owner_department_id);
CREATE INDEX IF NOT EXISTS ix_programme_actions_due_open
    ON opm_demo.programme_actions(due_date, status)
    WHERE is_deleted = FALSE AND status NOT IN ('done', 'cancelled');

CREATE TABLE IF NOT EXISTS opm_demo.action_events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action_id BIGINT NOT NULL REFERENCES opm_demo.programme_actions(action_id) ON DELETE RESTRICT,
    previous_status TEXT,
    new_status TEXT NOT NULL
        CHECK (new_status IN ('planned', 'in_progress', 'blocked', 'done', 'cancelled')),
    event_note TEXT NOT NULL,
    actor_ref TEXT NOT NULL,
    happened_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_action_events_action_time
    ON opm_demo.action_events(action_id, happened_at DESC);

CREATE OR REPLACE FUNCTION opm_demo.fn_set_updated_at()
RETURNS TRIGGER LANGUAGE plpgsql
SET search_path = pg_catalog, opm_demo
AS $function$
BEGIN
    NEW.updated_at := clock_timestamp();
    RETURN NEW;
END;
$function$;

DROP TRIGGER IF EXISTS trg_programme_actions_updated_at ON opm_demo.programme_actions;
CREATE TRIGGER trg_programme_actions_updated_at
BEFORE UPDATE ON opm_demo.programme_actions
FOR EACH ROW EXECUTE FUNCTION opm_demo.fn_set_updated_at();

COMMENT ON TABLE opm_demo.departments IS
    'Synthetic accountable office reference data for a programme tracker demonstration.';
COMMENT ON TABLE opm_demo.programme_actions IS
    'Programme action and current workflow state; not a classified case-management system.';
COMMENT ON TABLE opm_demo.action_events IS
    'Append-oriented history of action status transitions and associated actor references.';