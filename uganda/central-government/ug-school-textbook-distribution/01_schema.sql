-- Purpose: textbook allocation, dispatch, receipt, stock movement, shortage and return reconciliation.
-- Engine: PostgreSQL 15+. Additive bootstrap. Synthetic references only; no learner data.
CREATE SCHEMA IF NOT EXISTS ug_textbooks;

CREATE TABLE IF NOT EXISTS ug_textbooks.textbooks (
 textbook_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 textbook_code TEXT NOT NULL UNIQUE CHECK (textbook_code ~ '^[A-Z0-9_-]{3,48}$'),
 title TEXT NOT NULL CHECK (length(btrim(title))>0),
 subject_code TEXT NOT NULL CHECK (length(btrim(subject_code))>0),
 grade_level TEXT NOT NULL CHECK (length(btrim(grade_level))>0),
 edition TEXT NOT NULL CHECK (length(btrim(edition))>0),
 is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS ug_textbooks.warehouses (
 warehouse_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 warehouse_ref TEXT NOT NULL UNIQUE CHECK (warehouse_ref ~ '^UGTB-WH-[A-Z0-9-]{3,40}$'),
 warehouse_name TEXT NOT NULL CHECK (length(btrim(warehouse_name))>0),
 locality_ref TEXT NOT NULL CHECK (length(btrim(locality_ref))>0),
 is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS ug_textbooks.stock_movements (
 movement_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 movement_ref TEXT NOT NULL UNIQUE CHECK (movement_ref ~ '^UGTB-MV-[A-Z0-9-]{3,40}$'),
 warehouse_id BIGINT NOT NULL REFERENCES ug_textbooks.warehouses(warehouse_id) ON DELETE RESTRICT,
 textbook_id BIGINT NOT NULL REFERENCES ug_textbooks.textbooks(textbook_id) ON DELETE RESTRICT,
 movement_type TEXT NOT NULL CHECK (movement_type IN ('opening','receipt','dispatch','return_in','write_off','correction')),
 quantity_delta INTEGER NOT NULL CHECK (quantity_delta<>0),
 source_ref TEXT NOT NULL CHECK (length(btrim(source_ref))>0),
 reason TEXT NOT NULL CHECK (length(btrim(reason))>0),
 recorded_by TEXT NOT NULL CHECK (length(btrim(recorded_by))>0),
 idempotency_key TEXT NOT NULL UNIQUE CHECK (length(btrim(idempotency_key)) BETWEEN 8 AND 128),
 occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK ((movement_type IN ('opening','receipt','return_in') AND quantity_delta>0)
     OR (movement_type IN ('dispatch','write_off') AND quantity_delta<0)
     OR movement_type='correction')
);

CREATE TABLE IF NOT EXISTS ug_textbooks.allocations (
 allocation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 allocation_ref TEXT NOT NULL UNIQUE CHECK (allocation_ref ~ '^UGTB-AL-[A-Z0-9-]{3,40}$'),
 textbook_id BIGINT NOT NULL REFERENCES ug_textbooks.textbooks(textbook_id) ON DELETE RESTRICT,
 destination_school_ref TEXT NOT NULL CHECK (length(btrim(destination_school_ref))>0),
 academic_year TEXT NOT NULL CHECK (academic_year ~ '^[0-9]{4}(/[0-9]{4})?$'),
 allocated_quantity INTEGER NOT NULL CHECK (allocated_quantity>0),
 approved_by_ref TEXT NOT NULL CHECK (length(btrim(approved_by_ref))>0),
 approval_evidence_ref TEXT NOT NULL CHECK (length(btrim(approval_evidence_ref))>0),
 status TEXT NOT NULL DEFAULT 'approved' CHECK (status IN ('draft','approved','dispatched','received','closed','cancelled')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(textbook_id,destination_school_ref,academic_year)
);

CREATE TABLE IF NOT EXISTS ug_textbooks.dispatches (
 dispatch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 dispatch_ref TEXT NOT NULL UNIQUE CHECK (dispatch_ref ~ '^UGTB-DP-[A-Z0-9-]{3,40}$'),
 allocation_id BIGINT NOT NULL REFERENCES ug_textbooks.allocations(allocation_id) ON DELETE RESTRICT,
 warehouse_id BIGINT NOT NULL REFERENCES ug_textbooks.warehouses(warehouse_id) ON DELETE RESTRICT,
 quantity INTEGER NOT NULL CHECK (quantity>0),
 carrier_ref TEXT,
 dispatched_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 dispatched_by TEXT NOT NULL CHECK (length(btrim(dispatched_by))>0),
 status TEXT NOT NULL DEFAULT 'in_transit' CHECK (status IN ('in_transit','part_received','received','lost','cancelled')),
 UNIQUE(allocation_id,dispatch_ref)
);

CREATE TABLE IF NOT EXISTS ug_textbooks.receipts (
 receipt_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 receipt_ref TEXT NOT NULL UNIQUE CHECK (receipt_ref ~ '^UGTB-RC-[A-Z0-9-]{3,40}$'),
 dispatch_id BIGINT NOT NULL REFERENCES ug_textbooks.dispatches(dispatch_id) ON DELETE RESTRICT,
 quantity_received INTEGER NOT NULL CHECK (quantity_received>0),
 received_by_ref TEXT NOT NULL CHECK (length(btrim(received_by_ref))>0),
 evidence_ref TEXT NOT NULL CHECK (length(btrim(evidence_ref))>0),
 shortage_reason TEXT,
 received_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK (shortage_reason IS NULL OR length(btrim(shortage_reason))>0)
);

CREATE TABLE IF NOT EXISTS ug_textbooks.audit_events (
 event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 entity_type TEXT NOT NULL,
 entity_ref TEXT NOT NULL,
 event_type TEXT NOT NULL,
 actor_ref TEXT NOT NULL,
 reason TEXT NOT NULL,
 evidence_ref TEXT,
 occurred_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_textbook_movements_balance ON ug_textbooks.stock_movements(warehouse_id,textbook_id,occurred_at,movement_id);
CREATE INDEX IF NOT EXISTS ix_textbook_allocation_queue ON ug_textbooks.allocations(status,academic_year,allocation_ref);
CREATE INDEX IF NOT EXISTS ix_textbook_dispatch_status ON ug_textbooks.dispatches(status,dispatched_at);
CREATE INDEX IF NOT EXISTS ix_textbook_receipt_dispatch ON ug_textbooks.receipts(dispatch_id,received_at);

COMMENT ON SCHEMA ug_textbooks IS 'Synthetic textbook distribution reconciliation example; no child or learner-level records.';
