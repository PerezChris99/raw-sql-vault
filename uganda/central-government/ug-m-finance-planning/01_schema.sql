-- PostgreSQL 15+; illustrative synthetic UGX values only. No destructive reset.
CREATE SCHEMA IF NOT EXISTS finance_demo;
CREATE TABLE IF NOT EXISTS finance_demo.budget_lines(
 budget_line_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 budget_line_code TEXT NOT NULL UNIQUE,vote_code TEXT NOT NULL,programme_code TEXT NOT NULL,
 fiscal_year_start INTEGER NOT NULL CHECK(fiscal_year_start BETWEEN 2000 AND 2199),
 approved_ceiling_ugx NUMERIC(20,2) NOT NULL CHECK(approved_ceiling_ugx>=0),
 line_status TEXT NOT NULL DEFAULT 'active' CHECK(line_status IN('active','closed')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS finance_demo.releases(
 release_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 release_ref TEXT NOT NULL UNIQUE,budget_line_id BIGINT NOT NULL REFERENCES finance_demo.budget_lines(budget_line_id) ON DELETE RESTRICT,
 release_date DATE NOT NULL,amount_ugx NUMERIC(20,2) NOT NULL CHECK(amount_ugx>0),
 source_document_ref TEXT NOT NULL,idempotency_key TEXT NOT NULL UNIQUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS finance_demo.expenditures(
 expenditure_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 expenditure_ref TEXT NOT NULL UNIQUE,budget_line_id BIGINT NOT NULL REFERENCES finance_demo.budget_lines(budget_line_id) ON DELETE RESTRICT,
 expenditure_date DATE NOT NULL,amount_ugx NUMERIC(20,2) NOT NULL CHECK(amount_ugx>0),
 expenditure_type TEXT NOT NULL CHECK(expenditure_type IN('goods','services','payroll_aggregate','transfer','other')),
 source_document_ref TEXT NOT NULL,idempotency_key TEXT NOT NULL UNIQUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_finance_releases_line_date ON finance_demo.releases(budget_line_id,release_date);
CREATE INDEX IF NOT EXISTS ix_finance_expenditures_line_date ON finance_demo.expenditures(budget_line_id,expenditure_date);
CREATE INDEX IF NOT EXISTS ix_finance_expenditures_type_date ON finance_demo.expenditures(expenditure_type,expenditure_date);
COMMENT ON TABLE finance_demo.budget_lines IS 'Synthetic approved-ceiling metadata; not an appropriation or current budget record.';
COMMENT ON TABLE finance_demo.releases IS 'Synthetic authorised-release movement examples; require source-document verification in real systems.';
COMMENT ON TABLE finance_demo.expenditures IS 'Synthetic aggregate expenditure entries; contains no vendor or personal payroll details.';