-- PostgreSQL 15+; synthetic staff tokens only.
CREATE SCHEMA IF NOT EXISTS public_service_demo;
CREATE TABLE IF NOT EXISTS public_service_demo.departments(
 department_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 department_code TEXT NOT NULL UNIQUE, department_label TEXT NOT NULL, active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS public_service_demo.training_courses(
 course_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 course_code TEXT NOT NULL UNIQUE, course_title TEXT NOT NULL,
 topic TEXT NOT NULL CHECK(topic IN('digital_skills','records_management','procurement','leadership','ethics','service_delivery','other')),
 duration_hours NUMERIC(6,2) NOT NULL CHECK(duration_hours>0), active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS public_service_demo.cohorts(
 cohort_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 cohort_ref TEXT NOT NULL UNIQUE, course_id BIGINT NOT NULL REFERENCES public_service_demo.training_courses(course_id) ON DELETE RESTRICT,
 department_id BIGINT NOT NULL REFERENCES public_service_demo.departments(department_id) ON DELETE RESTRICT,
 starts_on DATE NOT NULL, ends_on DATE NOT NULL, capacity INTEGER NOT NULL CHECK(capacity>0),
 status TEXT NOT NULL DEFAULT 'planned' CHECK(status IN('planned','open','in_progress','completed','cancelled')),
 CHECK(ends_on>=starts_on)
);
CREATE TABLE IF NOT EXISTS public_service_demo.enrolments(
 enrolment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 enrolment_ref TEXT NOT NULL UNIQUE, cohort_id BIGINT NOT NULL REFERENCES public_service_demo.cohorts(cohort_id) ON DELETE RESTRICT,
 staff_token TEXT NOT NULL, enrolled_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 status TEXT NOT NULL DEFAULT 'enrolled' CHECK(status IN('enrolled','attended','completed','withdrawn')),
 score NUMERIC(5,2) CHECK(score IS NULL OR score BETWEEN 0 AND 100), completion_note TEXT,
 UNIQUE(cohort_id,staff_token), CHECK(status<>'completed' OR score IS NOT NULL)
);
CREATE TABLE IF NOT EXISTS public_service_demo.enrolment_events(
 event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 enrolment_id BIGINT NOT NULL REFERENCES public_service_demo.enrolments(enrolment_id) ON DELETE RESTRICT,
 previous_status TEXT,new_status TEXT NOT NULL CHECK(new_status IN('enrolled','attended','completed','withdrawn')),
 event_note TEXT NOT NULL,actor_ref TEXT NOT NULL,happened_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_ps_cohort_dates ON public_service_demo.cohorts(starts_on,status);
CREATE INDEX IF NOT EXISTS ix_ps_enrolment_status ON public_service_demo.enrolments(status,cohort_id);
CREATE INDEX IF NOT EXISTS ix_ps_events ON public_service_demo.enrolment_events(enrolment_id,happened_at DESC,event_id DESC);