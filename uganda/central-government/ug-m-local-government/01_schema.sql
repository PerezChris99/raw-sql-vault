-- PostgreSQL 15+; synthetic data only. Safe to re-run; no destructive reset.
CREATE SCHEMA IF NOT EXISTS lgmin_demo;
CREATE TABLE IF NOT EXISTS lgmin_demo.authorities(
 authority_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 authority_code TEXT NOT NULL UNIQUE, authority_name TEXT NOT NULL,
 authority_level TEXT NOT NULL CHECK(authority_level IN('district','city','municipality','division','subcounty','town_council')),
 parent_id BIGINT REFERENCES lgmin_demo.authorities(authority_id) ON DELETE RESTRICT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS lgmin_demo.programmes(
 programme_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 programme_ref TEXT NOT NULL UNIQUE, title TEXT NOT NULL CHECK(length(btrim(title))>0),
 authority_id BIGINT NOT NULL REFERENCES lgmin_demo.authorities(authority_id) ON DELETE RESTRICT,
 fiscal_year INTEGER NOT NULL CHECK(fiscal_year BETWEEN 2000 AND 2200),
 approved_ugx NUMERIC(18,2) NOT NULL CHECK(approved_ugx>=0),
 released_ugx NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK(released_ugx>=0 AND released_ugx<=approved_ugx),
 spent_ugx NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK(spent_ugx>=0 AND spent_ugx<=released_ugx),
 target_date DATE, status TEXT NOT NULL DEFAULT 'planned'
 CHECK(status IN('planned','active','blocked','completed','cancelled')),
 summary TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(), is_deleted BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE IF NOT EXISTS lgmin_demo.programme_events(
 event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 programme_id BIGINT NOT NULL REFERENCES lgmin_demo.programmes(programme_id) ON DELETE RESTRICT,
 previous_status TEXT,new_status TEXT NOT NULL CHECK(new_status IN('planned','active','blocked','completed','cancelled')),
 note TEXT NOT NULL, actor_ref TEXT NOT NULL,happened_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_lgmin_active_due ON lgmin_demo.programmes(target_date,status) WHERE is_deleted=FALSE;
CREATE INDEX IF NOT EXISTS ix_lgmin_event_history ON lgmin_demo.programme_events(programme_id,happened_at DESC);
CREATE OR REPLACE FUNCTION lgmin_demo.fn_touch_updated_at() RETURNS TRIGGER LANGUAGE plpgsql
SET search_path=pg_catalog,lgmin_demo AS $$
BEGIN NEW.updated_at:=clock_timestamp(); RETURN NEW; END; $$;
DROP TRIGGER IF EXISTS trg_lgmin_updated_at ON lgmin_demo.programmes;
CREATE TRIGGER trg_lgmin_updated_at BEFORE UPDATE ON lgmin_demo.programmes
FOR EACH ROW EXECUTE FUNCTION lgmin_demo.fn_touch_updated_at();
COMMENT ON TABLE lgmin_demo.programmes IS 'Synthetic programme and budget metadata, not authoritative fiscal records.';