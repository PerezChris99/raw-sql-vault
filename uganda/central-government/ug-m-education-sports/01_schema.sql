-- PostgreSQL 15+; synthetic school/materials data only. Rerunnable, no reset.
CREATE SCHEMA IF NOT EXISTS education_demo;
CREATE TABLE IF NOT EXISTS education_demo.schools(
 school_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 school_code TEXT NOT NULL UNIQUE, school_name TEXT NOT NULL,
 locality_code TEXT NOT NULL, school_level TEXT NOT NULL CHECK(school_level IN('primary','secondary','technical','other')),
 is_active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS education_demo.asset_catalog(
 asset_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 asset_code TEXT NOT NULL UNIQUE, asset_name TEXT NOT NULL,
 category TEXT NOT NULL CHECK(category IN('textbook','lab_kit','sports_kit','classroom_asset','other')),
 unit_of_measure TEXT NOT NULL DEFAULT 'unit', is_active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS education_demo.allocations(
 allocation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 allocation_ref TEXT NOT NULL UNIQUE,
 school_id BIGINT NOT NULL REFERENCES education_demo.schools(school_id) ON DELETE RESTRICT,
 asset_id BIGINT NOT NULL REFERENCES education_demo.asset_catalog(asset_id) ON DELETE RESTRICT,
 planned_quantity INTEGER NOT NULL CHECK(planned_quantity>0),
 dispatched_quantity INTEGER NOT NULL DEFAULT 0 CHECK(dispatched_quantity>=0 AND dispatched_quantity<=planned_quantity),
 received_quantity INTEGER NOT NULL DEFAULT 0 CHECK(received_quantity>=0 AND received_quantity<=dispatched_quantity),
 status TEXT NOT NULL DEFAULT 'planned' CHECK(status IN('planned','dispatched','received','disputed','cancelled')),
 planned_dispatch_date DATE, dispatch_reference TEXT, receipt_reference TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
 CHECK(status NOT IN('dispatched','received','disputed') OR dispatched_quantity>0),
 CHECK(status<>'received' OR received_quantity>0)
);
CREATE TABLE IF NOT EXISTS education_demo.allocation_events(
 event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 allocation_id BIGINT NOT NULL REFERENCES education_demo.allocations(allocation_id) ON DELETE RESTRICT,
 previous_status TEXT,new_status TEXT NOT NULL CHECK(new_status IN('planned','dispatched','received','disputed','cancelled')),
 event_note TEXT NOT NULL,actor_ref TEXT NOT NULL,happened_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_education_alloc_school ON education_demo.allocations(school_id,status);
CREATE INDEX IF NOT EXISTS ix_education_alloc_dispatch_date ON education_demo.allocations(planned_dispatch_date) WHERE is_deleted=FALSE AND status NOT IN('received','cancelled');
CREATE INDEX IF NOT EXISTS ix_education_event_history ON education_demo.allocation_events(allocation_id,happened_at DESC,event_id DESC);
CREATE OR REPLACE FUNCTION education_demo.fn_touch_updated_at() RETURNS TRIGGER LANGUAGE plpgsql SET search_path=pg_catalog,education_demo AS $$
BEGIN NEW.updated_at:=clock_timestamp(); RETURN NEW; END; $$;
DROP TRIGGER IF EXISTS trg_education_alloc_updated_at ON education_demo.allocations;
CREATE TRIGGER trg_education_alloc_updated_at BEFORE UPDATE ON education_demo.allocations FOR EACH ROW EXECUTE FUNCTION education_demo.fn_touch_updated_at();
COMMENT ON TABLE education_demo.allocations IS 'Synthetic allocation workflow; receipt quantities are not learning-outcome indicators.';