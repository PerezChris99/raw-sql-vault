-- Purpose: auditable agricultural input lot and distribution ledger.
-- Engine: PostgreSQL 15+. Prerequisites: none. Rerunnable: yes; additive.
CREATE SCHEMA IF NOT EXISTS ug_agri_inputs;

CREATE TABLE IF NOT EXISTS ug_agri_inputs.suppliers (
 supplier_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 supplier_ref TEXT NOT NULL UNIQUE CHECK (supplier_ref ~ '^UGSUP-[A-Z0-9-]{3,40}$'),
 supplier_name TEXT NOT NULL CHECK (length(btrim(supplier_name))>0),
 source_reference TEXT NOT NULL CHECK (length(btrim(source_reference))>0),
 is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS ug_agri_inputs.input_products (
 product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 product_code TEXT NOT NULL UNIQUE CHECK (product_code ~ '^[A-Z0-9_-]{3,40}$'),
 product_name TEXT NOT NULL CHECK (length(btrim(product_name))>0),
 input_type TEXT NOT NULL CHECK (input_type IN ('seed','fertiliser','tool','animal_health','feed','other')),
 unit_code TEXT NOT NULL CHECK (unit_code IN ('KG','L','UNIT','PACK')),
 is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS ug_agri_inputs.lots (
 lot_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 lot_ref TEXT NOT NULL UNIQUE CHECK (lot_ref ~ '^UGLOT-[A-Z0-9-]{3,40}$'),
 product_id BIGINT NOT NULL REFERENCES ug_agri_inputs.input_products(product_id) ON DELETE RESTRICT,
 supplier_id BIGINT REFERENCES ug_agri_inputs.suppliers(supplier_id) ON DELETE RESTRICT,
 supplier_lot_ref TEXT NOT NULL CHECK (length(btrim(supplier_lot_ref))>0),
 received_on DATE NOT NULL,
 expires_on DATE,
 warehouse_ref TEXT NOT NULL CHECK (length(btrim(warehouse_ref))>0),
 source_document_ref TEXT NOT NULL CHECK (length(btrim(source_document_ref))>0),
 lot_status TEXT NOT NULL DEFAULT 'available' CHECK (lot_status IN ('available','quarantined','expired','closed')),
 CHECK (expires_on IS NULL OR expires_on>=received_on)
);

CREATE TABLE IF NOT EXISTS ug_agri_inputs.stock_movements (
 movement_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 movement_ref TEXT NOT NULL UNIQUE CHECK (movement_ref ~ '^UGMOV-[A-Z0-9-]{3,40}$'),
 idempotency_key TEXT NOT NULL UNIQUE CHECK (length(btrim(idempotency_key)) BETWEEN 8 AND 128),
 lot_id BIGINT NOT NULL REFERENCES ug_agri_inputs.lots(lot_id) ON DELETE RESTRICT,
 movement_type TEXT NOT NULL CHECK (movement_type IN ('received','issued','returned','writeoff')),
 quantity NUMERIC(14,3) NOT NULL CHECK (quantity>0),
 recipient_ref TEXT,
 movement_at TIMESTAMPTZ NOT NULL,
 source_document_ref TEXT NOT NULL CHECK (length(btrim(source_document_ref))>0),
 reason TEXT NOT NULL CHECK (length(btrim(reason))>0),
 recorded_by TEXT NOT NULL CHECK (length(btrim(recorded_by))>0),
 recorded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK ((movement_type='issued' AND length(btrim(COALESCE(recipient_ref,'')))>0) OR movement_type<>'issued')
);

CREATE TABLE IF NOT EXISTS ug_agri_inputs.distribution_receipts (
 receipt_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 receipt_ref TEXT NOT NULL UNIQUE CHECK (receipt_ref ~ '^UGREC-[A-Z0-9-]{3,40}$'),
 movement_id BIGINT NOT NULL UNIQUE REFERENCES ug_agri_inputs.stock_movements(movement_id) ON DELETE RESTRICT,
 recipient_ref TEXT NOT NULL CHECK (length(btrim(recipient_ref))>0),
 received_quantity NUMERIC(14,3) NOT NULL CHECK (received_quantity>0),
 received_at TIMESTAMPTZ NOT NULL,
 evidence_reference TEXT NOT NULL CHECK (length(btrim(evidence_reference))>0),
 recorded_by TEXT NOT NULL CHECK (length(btrim(recorded_by))>0)
);

CREATE INDEX IF NOT EXISTS ix_agri_lots_product_status ON ug_agri_inputs.lots(product_id,lot_status,expires_on);
CREATE INDEX IF NOT EXISTS ix_agri_movements_lot_time ON ug_agri_inputs.stock_movements(lot_id,movement_at DESC,movement_id DESC);
CREATE INDEX IF NOT EXISTS ix_agri_movements_type_time ON ug_agri_inputs.stock_movements(movement_type,movement_at DESC);
CREATE INDEX IF NOT EXISTS ix_agri_receipts_recipient ON ug_agri_inputs.distribution_receipts(recipient_ref,received_at DESC);

COMMENT ON SCHEMA ug_agri_inputs IS 'Synthetic agricultural input traceability example; no real beneficiary data.';
COMMENT ON COLUMN ug_agri_inputs.stock_movements.recipient_ref IS 'Opaque authorised recipient token; do not store names, national IDs, contacts or household addresses.';
