-- Purpose: synthetic TVET course, skill, enrolment, assessment, placement and completion tracking.
-- Engine: PostgreSQL 15+. No real trainee identity or employer confidential records.
CREATE SCHEMA IF NOT EXISTS ug_tvet;

CREATE TABLE IF NOT EXISTS ug_tvet.institutions (
 institution_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 institution_ref TEXT NOT NULL UNIQUE CHECK (institution_ref ~ '^UGTVET-I-[A-Z0-9-]{3,40}$'),
 institution_name TEXT NOT NULL CHECK (length(btrim(institution_name))>0),
 locality_ref TEXT NOT NULL CHECK (length(btrim(locality_ref))>0),
 institution_type TEXT NOT NULL CHECK (institution_type IN ('public_tvet','private_tvet','community_training','employer_training')),
 is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS ug_tvet.programmes (
 programme_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 programme_ref TEXT NOT NULL UNIQUE CHECK (programme_ref ~ '^UGTVET-P-[A-Z0-9-]{3,40}$'),
 institution_id BIGINT NOT NULL REFERENCES ug_tvet.institutions(institution_id) ON DELETE RESTRICT,
 programme_name TEXT NOT NULL CHECK (length(btrim(programme_name))>0),
 qualification_level TEXT NOT NULL CHECK (length(btrim(qualification_level))>0),
 duration_weeks INTEGER NOT NULL CHECK (duration_weeks BETWEEN 1 AND 520),
 status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('draft','active','retired'))
);

CREATE TABLE IF NOT EXISTS ug_tvet.skills (
 skill_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 skill_code TEXT NOT NULL UNIQUE CHECK (length(btrim(skill_code))>0),
 skill_name TEXT NOT NULL CHECK (length(btrim(skill_name))>0),
 skill_category TEXT NOT NULL CHECK (length(btrim(skill_category))>0),
 framework_ref TEXT NOT NULL CHECK (length(btrim(framework_ref))>0)
);

CREATE TABLE IF NOT EXISTS ug_tvet.programme_skills (
 programme_id BIGINT NOT NULL REFERENCES ug_tvet.programmes(programme_id) ON DELETE RESTRICT,
 skill_id BIGINT NOT NULL REFERENCES ug_tvet.skills(skill_id) ON DELETE RESTRICT,
 proficiency_target TEXT NOT NULL CHECK (proficiency_target IN ('introductory','working','proficient','advanced')),
 PRIMARY KEY(programme_id,skill_id)
);

CREATE TABLE IF NOT EXISTS ug_tvet.cohorts (
 cohort_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 cohort_ref TEXT NOT NULL UNIQUE CHECK (cohort_ref ~ '^UGTVET-C-[A-Z0-9-]{3,40}$'),
 programme_id BIGINT NOT NULL REFERENCES ug_tvet.programmes(programme_id) ON DELETE RESTRICT,
 cohort_name TEXT NOT NULL CHECK (length(btrim(cohort_name))>0),
 starts_on DATE NOT NULL,
 planned_ends_on DATE NOT NULL,
 status TEXT NOT NULL DEFAULT 'planned' CHECK (status IN ('planned','active','completed','cancelled')),
 CHECK (planned_ends_on>=starts_on)
);

CREATE TABLE IF NOT EXISTS ug_tvet.enrolments (
 enrolment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 enrolment_ref TEXT NOT NULL UNIQUE CHECK (enrolment_ref ~ '^UGTVET-E-[A-Z0-9-]{3,40}$'),
 cohort_id BIGINT NOT NULL REFERENCES ug_tvet.cohorts(cohort_id) ON DELETE RESTRICT,
 trainee_ref TEXT NOT NULL CHECK (length(btrim(trainee_ref)) BETWEEN 4 AND 96),
 status TEXT NOT NULL DEFAULT 'enrolled' CHECK (status IN ('enrolled','withdrawn','completed','deferred')),
 enrolled_on DATE NOT NULL,
 outcome_reason_redacted TEXT,
 UNIQUE(cohort_id,trainee_ref)
);

CREATE TABLE IF NOT EXISTS ug_tvet.assessments (
 assessment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 enrolment_id BIGINT NOT NULL REFERENCES ug_tvet.enrolments(enrolment_id) ON DELETE RESTRICT,
 skill_id BIGINT NOT NULL REFERENCES ug_tvet.skills(skill_id) ON DELETE RESTRICT,
 assessed_on DATE NOT NULL,
 proficiency TEXT NOT NULL CHECK (proficiency IN ('not_assessed','introductory','working','proficient','advanced')),
 assessor_ref TEXT NOT NULL CHECK (length(btrim(assessor_ref))>0),
 evidence_ref TEXT NOT NULL CHECK (length(btrim(evidence_ref))>0),
 status TEXT NOT NULL DEFAULT 'valid' CHECK (status IN ('valid','superseded','withdrawn')),
 UNIQUE(enrolment_id,skill_id,assessed_on)
);

CREATE TABLE IF NOT EXISTS ug_tvet.placements (
 placement_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 placement_ref TEXT NOT NULL UNIQUE CHECK (placement_ref ~ '^UGTVET-PL-[A-Z0-9-]{3,40}$'),
 enrolment_id BIGINT NOT NULL REFERENCES ug_tvet.enrolments(enrolment_id) ON DELETE RESTRICT,
 employer_ref TEXT NOT NULL CHECK (length(btrim(employer_ref))>0),
 placement_type TEXT NOT NULL CHECK (placement_type IN ('apprenticeship','internship','employment','self_employment','further_training')),
 starts_on DATE NOT NULL,
 ends_on DATE,
 status TEXT NOT NULL DEFAULT 'planned' CHECK (status IN ('planned','active','completed','ended_early')),
 outcome_ref TEXT,
 CHECK (ends_on IS NULL OR ends_on>=starts_on)
);

CREATE TABLE IF NOT EXISTS ug_tvet.employer_feedback (
 feedback_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 placement_id BIGINT NOT NULL REFERENCES ug_tvet.placements(placement_id) ON DELETE RESTRICT,
 feedback_period DATE NOT NULL,
 skill_code TEXT NOT NULL,
 rating SMALLINT CHECK (rating BETWEEN 1 AND 5),
 comment_redacted TEXT,
 submitted_by_ref TEXT NOT NULL CHECK (length(btrim(submitted_by_ref))>0),
 evidence_ref TEXT NOT NULL CHECK (length(btrim(evidence_ref))>0),
 UNIQUE(placement_id,feedback_period,skill_code)
);

CREATE INDEX IF NOT EXISTS ix_tvet_cohort_status ON ug_tvet.cohorts(status,starts_on);
CREATE INDEX IF NOT EXISTS ix_tvet_enrolment_status ON ug_tvet.enrolments(cohort_id,status);
CREATE INDEX IF NOT EXISTS ix_tvet_assessment_latest ON ug_tvet.assessments(enrolment_id,skill_id,assessed_on DESC) WHERE status='valid';
CREATE INDEX IF NOT EXISTS ix_tvet_placement_status ON ug_tvet.placements(status,starts_on);

COMMENT ON SCHEMA ug_tvet IS 'Synthetic TVET outcomes example; not a national learner registry or accreditation decision system.';
COMMENT ON COLUMN ug_tvet.enrolments.trainee_ref IS 'Opaque trainee token only; identity mapping must remain separately protected.';
