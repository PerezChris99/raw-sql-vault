-- Purpose: appointment slot scheduling with conflict prevention and auditable booking events.
-- Engine: PostgreSQL 15+. Prerequisites: none. Rerunnable: yes; additive.
CREATE SCHEMA IF NOT EXISTS ug_clinic_sched;

CREATE TABLE IF NOT EXISTS ug_clinic_sched.clinics (
 clinic_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 clinic_ref TEXT NOT NULL UNIQUE CHECK (clinic_ref ~ '^UGCL-[A-Z0-9-]{3,40}$'),
 clinic_name TEXT NOT NULL CHECK (length(btrim(clinic_name))>0),
 locality_ref TEXT NOT NULL CHECK (length(btrim(locality_ref))>0),
 is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS ug_clinic_sched.services (
 service_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 service_code TEXT NOT NULL UNIQUE CHECK (service_code ~ '^[A-Z0-9_-]{3,40}$'),
 service_name TEXT NOT NULL CHECK (length(btrim(service_name))>0),
 default_duration_minutes INTEGER NOT NULL CHECK (default_duration_minutes BETWEEN 5 AND 240),
 is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS ug_clinic_sched.slots (
 slot_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 slot_ref TEXT NOT NULL UNIQUE CHECK (slot_ref ~ '^UGSLOT-[A-Z0-9-]{3,40}$'),
 clinic_id BIGINT NOT NULL REFERENCES ug_clinic_sched.clinics(clinic_id) ON DELETE RESTRICT,
 service_id BIGINT NOT NULL REFERENCES ug_clinic_sched.services(service_id) ON DELETE RESTRICT,
 clinician_ref TEXT NOT NULL CHECK (length(btrim(clinician_ref))>0),
 starts_at TIMESTAMPTZ NOT NULL,
 ends_at TIMESTAMPTZ NOT NULL,
 status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open','closed')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK (ends_at>starts_at),
 UNIQUE(clinic_id,service_id,clinician_ref,starts_at)
);

CREATE TABLE IF NOT EXISTS ug_clinic_sched.appointments (
 appointment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 appointment_ref TEXT NOT NULL UNIQUE CHECK (appointment_ref ~ '^UGAPT-[A-Z0-9-]{3,40}$'),
 idempotency_key TEXT NOT NULL UNIQUE CHECK (length(btrim(idempotency_key)) BETWEEN 8 AND 128),
 slot_id BIGINT NOT NULL REFERENCES ug_clinic_sched.slots(slot_id) ON DELETE RESTRICT,
 patient_ref TEXT NOT NULL CHECK (length(btrim(patient_ref)) BETWEEN 3 AND 96),
 status TEXT NOT NULL DEFAULT 'booked' CHECK (status IN ('booked','checked_in','completed','cancelled','no_show')),
 booked_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 cancelled_at TIMESTAMPTZ,
 cancellation_reason TEXT,
 recorded_by TEXT NOT NULL CHECK (length(btrim(recorded_by))>0),
 CHECK ((status='cancelled') = (cancelled_at IS NOT NULL)),
 CHECK ((cancelled_at IS NULL AND cancellation_reason IS NULL)
    OR (cancelled_at IS NOT NULL AND length(btrim(COALESCE(cancellation_reason,'')))>0))
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_clinic_active_slot_booking
 ON ug_clinic_sched.appointments(slot_id) WHERE status IN ('booked','checked_in');

CREATE TABLE IF NOT EXISTS ug_clinic_sched.appointment_events (
 event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 appointment_id BIGINT NOT NULL REFERENCES ug_clinic_sched.appointments(appointment_id) ON DELETE RESTRICT,
 event_type TEXT NOT NULL CHECK (event_type IN ('booked','checked_in','completed','cancelled','no_show','corrected')),
 from_status TEXT,
 to_status TEXT NOT NULL CHECK (to_status IN ('booked','checked_in','completed','cancelled','no_show')),
 actor_ref TEXT NOT NULL CHECK (length(btrim(actor_ref))>0),
 reason TEXT NOT NULL CHECK (length(btrim(reason))>0),
 occurred_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_clinic_slots_schedule ON ug_clinic_sched.slots(clinic_id,starts_at,status);
CREATE INDEX IF NOT EXISTS ix_clinic_appointments_patient ON ug_clinic_sched.appointments(patient_ref,booked_at DESC);
CREATE INDEX IF NOT EXISTS ix_clinic_appointments_status ON ug_clinic_sched.appointments(status,booked_at);
CREATE INDEX IF NOT EXISTS ix_clinic_events_history ON ug_clinic_sched.appointment_events(appointment_id,occurred_at DESC,event_id DESC);

COMMENT ON SCHEMA ug_clinic_sched IS 'Synthetic appointment scheduling example; no clinical records are stored.';
COMMENT ON COLUMN ug_clinic_sched.appointments.patient_ref IS 'Opaque patient token only; do not store names, contacts, national IDs or clinical information.';
