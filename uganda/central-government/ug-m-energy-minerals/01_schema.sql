-- PostgreSQL 15+; synthetic licence/inspection metadata only.
CREATE SCHEMA IF NOT EXISTS energy_demo;
CREATE TABLE IF NOT EXISTS energy_demo.licence_holders(
 holder_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 holder_ref TEXT NOT NULL UNIQUE, holder_type TEXT NOT NULL CHECK(holder_type IN('public_operator','private_operator','cooperative','other')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS energy_demo.licences(
 licence_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 licence_ref TEXT NOT NULL UNIQUE, holder_id BIGINT NOT NULL REFERENCES energy_demo.licence_holders(holder_id) ON DELETE RESTRICT,
 sector TEXT NOT NULL CHECK(sector IN('electricity','petroleum','mineral_exploration','mineral_production','renewable','other')),
 issued_on DATE, expires_on DATE, status TEXT NOT NULL DEFAULT 'draft'
 CHECK(status IN('draft','active','suspended','expired','closed')),
 region_code TEXT NOT NULL, public_summary TEXT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK(expires_on IS NULL OR issued_on IS NULL OR expires_on>=issued_on)
);
CREATE TABLE IF NOT EXISTS energy_demo.inspections(
 inspection_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 inspection_ref TEXT NOT NULL UNIQUE, licence_id BIGINT NOT NULL REFERENCES energy_demo.licences(licence_id) ON DELETE RESTRICT,
 inspected_at TIMESTAMPTZ NOT NULL, inspection_type TEXT NOT NULL CHECK(inspection_type IN('routine','follow_up','document_review','other')),
 outcome TEXT NOT NULL CHECK(outcome IN('pending','no_action','follow_up_required','refer_for_review')),
 inspector_ref TEXT NOT NULL, finding_summary TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS energy_demo.corrective_actions(
 action_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 action_ref TEXT NOT NULL UNIQUE, inspection_id BIGINT NOT NULL REFERENCES energy_demo.inspections(inspection_id) ON DELETE RESTRICT,
 summary TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'open' CHECK(status IN('open','in_progress','blocked','closed','cancelled')),
 due_date DATE, closed_at TIMESTAMPTZ, owner_ref TEXT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK(status<>'closed' OR closed_at IS NOT NULL)
);
CREATE TABLE IF NOT EXISTS energy_demo.action_events(
 event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 action_id BIGINT NOT NULL REFERENCES energy_demo.corrective_actions(action_id) ON DELETE RESTRICT,
 previous_status TEXT,new_status TEXT NOT NULL CHECK(new_status IN('open','in_progress','blocked','closed','cancelled')),
 event_note TEXT NOT NULL,actor_ref TEXT NOT NULL,happened_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_energy_licence_expiry ON energy_demo.licences(status,expires_on);
CREATE INDEX IF NOT EXISTS ix_energy_inspection_licence_time ON energy_demo.inspections(licence_id,inspected_at DESC);
CREATE INDEX IF NOT EXISTS ix_energy_action_due ON energy_demo.corrective_actions(status,due_date) WHERE status NOT IN('closed','cancelled');
CREATE INDEX IF NOT EXISTS ix_energy_action_event ON energy_demo.action_events(action_id,happened_at DESC,event_id DESC);
