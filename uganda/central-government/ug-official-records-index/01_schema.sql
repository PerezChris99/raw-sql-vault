-- Purpose: metadata-only index for official records, custody, retention and authorised disposition.
-- Engine: PostgreSQL 15+. Synthetic references only; document contents remain in secured storage.
CREATE SCHEMA IF NOT EXISTS ug_records;

CREATE TABLE IF NOT EXISTS ug_records.offices (
 office_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 office_ref TEXT NOT NULL UNIQUE CHECK (office_ref ~ '^UGOFF-[A-Z0-9-]{3,40}$'),
 office_name TEXT NOT NULL CHECK (length(btrim(office_name))>0),
 locality_ref TEXT NOT NULL CHECK (length(btrim(locality_ref))>0),
 is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS ug_records.record_categories (
 category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 category_code TEXT NOT NULL UNIQUE CHECK (length(btrim(category_code))>0),
 category_name TEXT NOT NULL CHECK (length(btrim(category_name))>0),
 retention_months INTEGER CHECK (retention_months IS NULL OR retention_months>=0),
 disposal_authority_ref TEXT NOT NULL CHECK (length(btrim(disposal_authority_ref))>0),
 classification_default TEXT NOT NULL CHECK (classification_default IN ('public','internal','restricted','highly_restricted')),
 requires_disposition_approval BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS ug_records.records (
 record_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 record_ref TEXT NOT NULL UNIQUE CHECK (record_ref ~ '^UGREC-[A-Z0-9-]{3,48}$'),
 category_id BIGINT NOT NULL REFERENCES ug_records.record_categories(category_id) ON DELETE RESTRICT,
 originating_office_id BIGINT NOT NULL REFERENCES ug_records.offices(office_id) ON DELETE RESTRICT,
 current_custodian_office_id BIGINT NOT NULL REFERENCES ug_records.offices(office_id) ON DELETE RESTRICT,
 external_reference TEXT NOT NULL CHECK (length(btrim(external_reference))>0),
 title_redacted TEXT NOT NULL CHECK (length(btrim(title_redacted))>0),
 document_object_ref TEXT NOT NULL CHECK (length(btrim(document_object_ref))>0),
 sha256_hex TEXT NOT NULL CHECK (sha256_hex ~ '^[0-9a-f]{64}$'),
 classification TEXT NOT NULL CHECK (classification IN ('public','internal','restricted','highly_restricted')),
 received_on DATE NOT NULL,
 retention_until DATE,
 legal_hold BOOLEAN NOT NULL DEFAULT FALSE,
 status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','transferred','pending_disposition','disposed')),
 created_by_ref TEXT NOT NULL CHECK (length(btrim(created_by_ref))>0),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK (retention_until IS NULL OR retention_until>=received_on),
 CHECK (status<>'disposed' OR legal_hold=FALSE)
);

CREATE TABLE IF NOT EXISTS ug_records.custody_events (
 custody_event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 record_id BIGINT NOT NULL REFERENCES ug_records.records(record_id) ON DELETE RESTRICT,
 from_office_id BIGINT REFERENCES ug_records.offices(office_id) ON DELETE RESTRICT,
 to_office_id BIGINT NOT NULL REFERENCES ug_records.offices(office_id) ON DELETE RESTRICT,
 transferred_by_ref TEXT NOT NULL CHECK (length(btrim(transferred_by_ref))>0),
 accepted_by_ref TEXT NOT NULL CHECK (length(btrim(accepted_by_ref))>0),
 evidence_ref TEXT NOT NULL CHECK (length(btrim(evidence_ref))>0),
 transferred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 reason TEXT NOT NULL CHECK (length(btrim(reason))>0)
);

CREATE TABLE IF NOT EXISTS ug_records.disposition_requests (
 disposition_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 disposition_ref TEXT NOT NULL UNIQUE CHECK (disposition_ref ~ '^UGDISP-[A-Z0-9-]{3,40}$'),
 record_id BIGINT NOT NULL REFERENCES ug_records.records(record_id) ON DELETE RESTRICT,
 requested_by_ref TEXT NOT NULL CHECK (length(btrim(requested_by_ref))>0),
 reason TEXT NOT NULL CHECK (length(btrim(reason))>0),
 authority_evidence_ref TEXT NOT NULL CHECK (length(btrim(authority_evidence_ref))>0),
 status TEXT NOT NULL DEFAULT 'requested' CHECK (status IN ('requested','approved','rejected','executed','cancelled')),
 reviewed_by_ref TEXT,
 reviewed_at TIMESTAMPTZ,
 review_evidence_ref TEXT,
 executed_at TIMESTAMPTZ,
 execution_evidence_ref TEXT,
 CHECK ((status='requested' AND reviewed_at IS NULL) OR (status<>'requested' AND reviewed_at IS NOT NULL)),
 CHECK ((reviewed_at IS NULL AND reviewed_by_ref IS NULL AND review_evidence_ref IS NULL)
    OR (reviewed_at IS NOT NULL AND length(btrim(COALESCE(reviewed_by_ref,'')))>0 AND length(btrim(COALESCE(review_evidence_ref,'')))>0)),
 CHECK ((status='executed') = (executed_at IS NOT NULL AND execution_evidence_ref IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS ug_records.access_events (
 access_event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 record_id BIGINT NOT NULL REFERENCES ug_records.records(record_id) ON DELETE RESTRICT,
 actor_ref TEXT NOT NULL CHECK (length(btrim(actor_ref))>0),
 action TEXT NOT NULL CHECK (action IN ('view_metadata','view_document','export','print','correct_metadata','set_hold','release_hold')),
 purpose TEXT NOT NULL CHECK (length(btrim(purpose))>0),
 occurred_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_records_classification_status ON ug_records.records(classification,status,record_id);
CREATE INDEX IF NOT EXISTS ix_records_retention ON ug_records.records(retention_until,status) WHERE legal_hold=FALSE;
CREATE INDEX IF NOT EXISTS ix_records_custody_history ON ug_records.custody_events(record_id,transferred_at DESC);
CREATE INDEX IF NOT EXISTS ix_records_disposition_queue ON ug_records.disposition_requests(status,disposition_id);

COMMENT ON SCHEMA ug_records IS 'Metadata-only records index; document content remains outside the database in separately secured storage.';
