-- Purpose: synthetic approved budget, release, commitment, expenditure and service-output reconciliation.
-- Engine: PostgreSQL 15+. Additive bootstrap; not an official accounting ledger.
CREATE SCHEMA IF NOT EXISTS ug_budget_exec;

CREATE TABLE IF NOT EXISTS ug_budget_exec.programmes (
 programme_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 programme_ref TEXT NOT NULL UNIQUE CHECK (programme_ref ~ '^UGBUD-[A-Z0-9-]{3,40}$'),
 office_ref TEXT NOT NULL CHECK (length(btrim(office_ref))>0),
 programme_name TEXT NOT NULL CHECK (length(btrim(programme_name))>0),
 fiscal_year TEXT NOT NULL CHECK (fiscal_year ~ '^[0-9]{4}(/[0-9]{4})?$'),
 currency_code CHAR(3) NOT NULL DEFAULT 'UGX' CHECK (currency_code ~ '^[A-Z]{3}$'),
 status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','approved','closed')),
 UNIQUE(office_ref,programme_name,fiscal_year)
);

CREATE TABLE IF NOT EXISTS ug_budget_exec.appropriations (
 appropriation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 programme_id BIGINT NOT NULL REFERENCES ug_budget_exec.programmes(programme_id) ON DELETE RESTRICT,
 version_no INTEGER NOT NULL CHECK (version_no>0),
 approved_amount NUMERIC(16,2) NOT NULL CHECK (approved_amount>=0),
 approved_by_ref TEXT NOT NULL CHECK (length(btrim(approved_by_ref))>0),
 evidence_ref TEXT NOT NULL CHECK (length(btrim(evidence_ref))>0),
 effective_on DATE NOT NULL,
 recorded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(programme_id,version_no)
);

CREATE TABLE IF NOT EXISTS ug_budget_exec.releases (
 release_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 release_ref TEXT NOT NULL UNIQUE CHECK (release_ref ~ '^UGREL-[A-Z0-9-]{3,40}$'),
 programme_id BIGINT NOT NULL REFERENCES ug_budget_exec.programmes(programme_id) ON DELETE RESTRICT,
 amount NUMERIC(16,2) NOT NULL CHECK (amount>0),
 treasury_reference TEXT NOT NULL UNIQUE CHECK (length(btrim(treasury_reference))>0),
 released_on DATE NOT NULL,
 recorded_by_ref TEXT NOT NULL CHECK (length(btrim(recorded_by_ref))>0),
 evidence_ref TEXT NOT NULL CHECK (length(btrim(evidence_ref))>0)
);

CREATE TABLE IF NOT EXISTS ug_budget_exec.commitments (
 commitment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 commitment_ref TEXT NOT NULL UNIQUE CHECK (commitment_ref ~ '^UGCOM-[A-Z0-9-]{3,40}$'),
 programme_id BIGINT NOT NULL REFERENCES ug_budget_exec.programmes(programme_id) ON DELETE RESTRICT,
 supplier_ref TEXT NOT NULL CHECK (length(btrim(supplier_ref))>0),
 amount NUMERIC(16,2) NOT NULL CHECK (amount>0),
 status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open','partially_settled','settled','cancelled')),
 committed_on DATE NOT NULL,
 approval_ref TEXT NOT NULL CHECK (length(btrim(approval_ref))>0),
 recorded_by_ref TEXT NOT NULL CHECK (length(btrim(recorded_by_ref))>0)
);

CREATE TABLE IF NOT EXISTS ug_budget_exec.expenditures (
 expenditure_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 expenditure_ref TEXT NOT NULL UNIQUE CHECK (expenditure_ref ~ '^UGEXP-[A-Z0-9-]{3,40}$'),
 idempotency_key TEXT NOT NULL UNIQUE CHECK (length(btrim(idempotency_key)) BETWEEN 8 AND 128),
 commitment_id BIGINT NOT NULL REFERENCES ug_budget_exec.commitments(commitment_id) ON DELETE RESTRICT,
 amount NUMERIC(16,2) NOT NULL CHECK (amount>0),
 payment_reference TEXT NOT NULL UNIQUE CHECK (length(btrim(payment_reference))>0),
 paid_on DATE NOT NULL,
 recorded_by_ref TEXT NOT NULL CHECK (length(btrim(recorded_by_ref))>0),
 evidence_ref TEXT NOT NULL CHECK (length(btrim(evidence_ref))>0)
);

CREATE TABLE IF NOT EXISTS ug_budget_exec.service_outputs (
 output_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 output_ref TEXT NOT NULL UNIQUE CHECK (length(btrim(output_ref))>0),
 programme_id BIGINT NOT NULL REFERENCES ug_budget_exec.programmes(programme_id) ON DELETE RESTRICT,
 reporting_period DATE NOT NULL,
 output_metric TEXT NOT NULL CHECK (length(btrim(output_metric))>0),
 planned_quantity NUMERIC(16,3) NOT NULL CHECK (planned_quantity>=0),
 achieved_quantity NUMERIC(16,3) NOT NULL CHECK (achieved_quantity>=0),
 unit_code TEXT NOT NULL CHECK (length(btrim(unit_code))>0),
 source_ref TEXT NOT NULL CHECK (length(btrim(source_ref))>0),
 quality_status TEXT NOT NULL DEFAULT 'unreviewed' CHECK (quality_status IN ('unreviewed','verified','rejected')),
 UNIQUE(programme_id,reporting_period,output_metric)
);

CREATE INDEX IF NOT EXISTS ix_budget_releases_programme ON ug_budget_exec.releases(programme_id,released_on);
CREATE INDEX IF NOT EXISTS ix_budget_commitments_status ON ug_budget_exec.commitments(programme_id,status,committed_on);
CREATE INDEX IF NOT EXISTS ix_budget_expenditures_commitment ON ug_budget_exec.expenditures(commitment_id,paid_on);
CREATE INDEX IF NOT EXISTS ix_budget_outputs_period ON ug_budget_exec.service_outputs(programme_id,reporting_period,quality_status);

COMMENT ON SCHEMA ug_budget_exec IS 'Synthetic budget monitoring example; not a replacement for the official treasury or accounting ledger.';
