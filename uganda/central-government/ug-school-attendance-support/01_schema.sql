-- Purpose: attendance summaries and confidential, human-led learner support follow-up.
-- Engine: PostgreSQL 15+. Synthetic tokens only; no names, contacts, national IDs or clinical data.
CREATE SCHEMA IF NOT EXISTS ug_attendance;

CREATE TABLE IF NOT EXISTS ug_attendance.schools (
 school_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 school_ref TEXT NOT NULL UNIQUE CHECK (school_ref ~ '^UGSCH-[A-Z0-9-]{3,40}$'),
 locality_ref TEXT NOT NULL CHECK (length(btrim(locality_ref))>0),
 school_name TEXT NOT NULL CHECK (length(btrim(school_name))>0),
 is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS ug_attendance.terms (
 term_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 term_ref TEXT NOT NULL UNIQUE CHECK (term_ref ~ '^UGTERM-[A-Z0-9-]{3,40}$'),
 academic_year TEXT NOT NULL CHECK (academic_year ~ '^[0-9]{4}(/[0-9]{4})?$'),
 term_name TEXT NOT NULL CHECK (length(btrim(term_name))>0),
 starts_on DATE NOT NULL,
 ends_on DATE NOT NULL,
 CHECK (ends_on>=starts_on),
 UNIQUE(academic_year,term_name)
);

CREATE TABLE IF NOT EXISTS ug_attendance.sessions (
 session_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 session_ref TEXT NOT NULL UNIQUE CHECK (session_ref ~ '^UGATT-[A-Z0-9-]{3,40}$'),
 school_id BIGINT NOT NULL REFERENCES ug_attendance.schools(school_id) ON DELETE RESTRICT,
 term_id BIGINT NOT NULL REFERENCES ug_attendance.terms(term_id) ON DELETE RESTRICT,
 session_date DATE NOT NULL,
 class_ref TEXT NOT NULL CHECK (length(btrim(class_ref))>0),
 recorded_by_ref TEXT NOT NULL CHECK (length(btrim(recorded_by_ref))>0),
 source_ref TEXT NOT NULL CHECK (length(btrim(source_ref))>0),
 status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open','submitted','corrected','void')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(school_id,session_date,class_ref),
 UNIQUE(session_id,term_id),
 FOREIGN KEY(term_id) REFERENCES ug_attendance.terms(term_id) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS ug_attendance.marks (
 mark_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 session_id BIGINT NOT NULL REFERENCES ug_attendance.sessions(session_id) ON DELETE RESTRICT,
 learner_ref TEXT NOT NULL CHECK (length(btrim(learner_ref)) BETWEEN 4 AND 96),
 attendance_status TEXT NOT NULL CHECK (attendance_status IN ('present','absent','late','excused')),
 reason_code TEXT CHECK (reason_code IS NULL OR length(btrim(reason_code))>0),
 recorded_by_ref TEXT NOT NULL CHECK (length(btrim(recorded_by_ref))>0),
 recorded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(session_id,learner_ref)
);

CREATE TABLE IF NOT EXISTS ug_attendance.mark_corrections (
 correction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 mark_id BIGINT NOT NULL REFERENCES ug_attendance.marks(mark_id) ON DELETE RESTRICT,
 previous_status TEXT NOT NULL CHECK (previous_status IN ('present','absent','late','excused')),
 corrected_status TEXT NOT NULL CHECK (corrected_status IN ('present','absent','late','excused')),
 reason TEXT NOT NULL CHECK (length(btrim(reason))>0),
 evidence_ref TEXT NOT NULL CHECK (length(btrim(evidence_ref))>0),
 corrected_by_ref TEXT NOT NULL CHECK (length(btrim(corrected_by_ref))>0),
 corrected_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK(previous_status<>corrected_status)
);

CREATE TABLE IF NOT EXISTS ug_attendance.support_cases (
 support_case_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 support_ref TEXT NOT NULL UNIQUE CHECK (support_ref ~ '^UGSUP-[A-Z0-9-]{3,40}$'),
 school_id BIGINT NOT NULL REFERENCES ug_attendance.schools(school_id) ON DELETE RESTRICT,
 learner_ref TEXT NOT NULL CHECK (length(btrim(learner_ref)) BETWEEN 4 AND 96),
 term_id BIGINT NOT NULL REFERENCES ug_attendance.terms(term_id) ON DELETE RESTRICT,
 concern_category TEXT NOT NULL CHECK (concern_category IN ('attendance_pattern','transport_barrier','school_access','health_referral','safeguarding_referral','other')),
 concern_summary_redacted TEXT NOT NULL CHECK (length(btrim(concern_summary_redacted))>0),
 opened_by_ref TEXT NOT NULL CHECK (length(btrim(opened_by_ref))>0),
 status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open','assigned','referred','resolved','closed')),
 opened_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 closed_at TIMESTAMPTZ,
 UNIQUE(school_id,learner_ref,term_id,concern_category,support_ref),
 CHECK ((status IN ('resolved','closed')) = (closed_at IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS ug_attendance.support_events (
 support_event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 support_case_id BIGINT NOT NULL REFERENCES ug_attendance.support_cases(support_case_id) ON DELETE RESTRICT,
 event_type TEXT NOT NULL CHECK (event_type IN ('assigned','contact_attempt_recorded','referral','plan_agreed','review','resolved','reopened','closed')),
 actor_ref TEXT NOT NULL CHECK (length(btrim(actor_ref))>0),
 reason_redacted TEXT NOT NULL CHECK (length(btrim(reason_redacted))>0),
 evidence_ref TEXT,
 occurred_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_attendance_session_date ON ug_attendance.sessions(school_id,session_date,class_ref);
CREATE INDEX IF NOT EXISTS ix_attendance_marks_status ON ug_attendance.marks(session_id,attendance_status);
CREATE INDEX IF NOT EXISTS ix_attendance_support_queue ON ug_attendance.support_cases(status,opened_at,support_ref);
CREATE INDEX IF NOT EXISTS ix_attendance_support_history ON ug_attendance.support_events(support_case_id,occurred_at DESC);

COMMENT ON SCHEMA ug_attendance IS 'Synthetic school attendance and supportive follow-up example; no real learner identity.';
COMMENT ON COLUMN ug_attendance.marks.learner_ref IS 'Pseudonymous token only; identity mapping must remain separately protected by the authorised school.';
