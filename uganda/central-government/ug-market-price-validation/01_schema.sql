-- Purpose: sourced market-price collection with reviewable observations and provenance.
-- Engine: PostgreSQL 15+. Prerequisites: none. Rerunnable: yes; additive.
CREATE SCHEMA IF NOT EXISTS ug_market_price;

CREATE TABLE IF NOT EXISTS ug_market_price.markets (
    market_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    market_code TEXT NOT NULL UNIQUE CHECK (market_code ~ '^[A-Z0-9_-]{3,48}$'),
    market_name TEXT NOT NULL CHECK (length(btrim(market_name)) > 0),
    locality_ref TEXT NOT NULL CHECK (length(btrim(locality_ref)) > 0),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    source_reference TEXT NOT NULL CHECK (length(btrim(source_reference)) > 0)
);

CREATE TABLE IF NOT EXISTS ug_market_price.commodities (
    commodity_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    commodity_code TEXT NOT NULL UNIQUE CHECK (commodity_code ~ '^[A-Z0-9_-]{2,48}$'),
    commodity_name TEXT NOT NULL CHECK (length(btrim(commodity_name)) > 0),
    category_code TEXT NOT NULL CHECK (length(btrim(category_code)) > 0),
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS ug_market_price.measurement_units (
    unit_code TEXT PRIMARY KEY CHECK (unit_code ~ '^[A-Z0-9_-]{1,12}$'),
    unit_name TEXT NOT NULL CHECK (length(btrim(unit_name)) > 0),
    description TEXT NOT NULL CHECK (length(btrim(description)) > 0)
);

CREATE TABLE IF NOT EXISTS ug_market_price.observations (
    observation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    observation_ref TEXT NOT NULL UNIQUE CHECK (observation_ref ~ '^UGMP-[A-Z0-9-]{4,40}$'),
    idempotency_key TEXT NOT NULL UNIQUE CHECK (length(btrim(idempotency_key)) BETWEEN 8 AND 128),
    market_id BIGINT NOT NULL REFERENCES ug_market_price.markets(market_id) ON DELETE RESTRICT,
    commodity_id BIGINT NOT NULL REFERENCES ug_market_price.commodities(commodity_id) ON DELETE RESTRICT,
    unit_code TEXT NOT NULL REFERENCES ug_market_price.measurement_units(unit_code) ON DELETE RESTRICT,
    observed_on DATE NOT NULL,
    price_amount NUMERIC(14,4) NOT NULL CHECK (price_amount > 0),
    currency_code CHAR(3) NOT NULL DEFAULT 'UGX' CHECK (currency_code ~ '^[A-Z]{3}$'),
    collection_method TEXT NOT NULL CHECK (collection_method IN ('field_visit','phone_quote','published_bulletin','authorised_import')),
    source_record_ref TEXT NOT NULL CHECK (length(btrim(source_record_ref)) > 0),
    collector_ref TEXT NOT NULL CHECK (length(btrim(collector_ref)) > 0),
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','flagged','accepted','rejected')),
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    reviewed_at TIMESTAMPTZ,
    reviewed_by TEXT,
    review_reason TEXT,
    correction_of_observation_id BIGINT REFERENCES ug_market_price.observations(observation_id) ON DELETE RESTRICT,
    CHECK ((status IN ('accepted','rejected')) = (reviewed_at IS NOT NULL)),
    CHECK ((reviewed_at IS NULL AND reviewed_by IS NULL AND review_reason IS NULL)
        OR (reviewed_at IS NOT NULL AND length(btrim(COALESCE(reviewed_by,'')))>0 AND length(btrim(COALESCE(review_reason,'')))>0))
);

CREATE TABLE IF NOT EXISTS ug_market_price.review_events (
    review_event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    observation_id BIGINT NOT NULL REFERENCES ug_market_price.observations(observation_id) ON DELETE RESTRICT,
    event_type TEXT NOT NULL CHECK (event_type IN ('submitted','flagged','accepted','rejected','correction_linked','note_added')),
    from_status TEXT,
    to_status TEXT NOT NULL CHECK (to_status IN ('pending','flagged','accepted','rejected')),
    actor_ref TEXT NOT NULL CHECK (length(btrim(actor_ref)) > 0),
    reason TEXT NOT NULL CHECK (length(btrim(reason)) > 0),
    evidence_reference TEXT,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_market_price_observations_lookup
 ON ug_market_price.observations(market_id,commodity_id,unit_code,observed_on DESC);
CREATE INDEX IF NOT EXISTS ix_market_price_review_queue
 ON ug_market_price.observations(status,submitted_at,observation_id);
CREATE INDEX IF NOT EXISTS ix_market_price_review_history
 ON ug_market_price.review_events(observation_id,occurred_at DESC,review_event_id DESC);

COMMENT ON SCHEMA ug_market_price IS 'Synthetic market price collection and validation example; no official price series is included.';
COMMENT ON COLUMN ug_market_price.observations.price_amount IS 'Price for the declared measurement unit; comparisons require matching commodity, unit and currency.';
COMMENT ON COLUMN ug_market_price.observations.collector_ref IS 'Opaque staff/source identifier; do not store personal contact details.';
