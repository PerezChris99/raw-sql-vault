-- Purpose: synthetic public-works project, budget version, contractor milestone and certificate register.
-- Engine: PostgreSQL 15+. Rerunnable additive bootstrap. All money amounts are UGX unless stated.
CREATE SCHEMA IF NOT EXISTS ug_works_contract;

CREATE TABLE IF NOT EXISTS ug_works_contract.projects (
 project_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_ref TEXT NOT NULL UNIQUE CHECK (project_ref ~ '^UGW-[A-Z0-9-]{3,40}$'),
 project_name TEXT NOT NULL CHECK (length(btrim(project_name))>0),
 sponsor_office_ref TEXT NOT NULL CHECK (length(btrim(sponsor_office_ref))>0),
 locality_ref TEXT NOT NULL CHECK (length(btrim(locality_ref))>0),
 project_status TEXT NOT NULL DEFAULT 'planned' CHECK (project_status IN ('planned','approved','active','suspended','completed','cancelled')),
 approved_on DATE,
 planned_start DATE NOT NULL,
 planned_end DATE NOT NULL,
 CHECK (planned_end>=planned_start),
 CHECK (project_status NOT IN ('approved','active','suspended','completed') OR approved_on IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS ug_works_contract.contracts (
 contract_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 contract_ref TEXT NOT NULL UNIQUE CHECK (contract_ref ~ '^UGWC-[A-Z0-9-]{3,40}$'),
 project_id BIGINT NOT NULL REFERENCES ug_works_contract.projects(project_id) ON DELETE RESTRICT,
 supplier_ref TEXT NOT NULL CHECK (length(btrim(supplier_ref))>0),
 signed_on DATE NOT NULL,
 planned_completion DATE NOT NULL,
 contract_value NUMERIC(16,2) NOT NULL CHECK (contract_value>0),
 currency_code CHAR(3) NOT NULL DEFAULT 'UGX' CHECK (currency_code ~ '^[A-Z]{3}$'),
 status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','signed','in_progress','suspended','completed','terminated')),
 CHECK (planned_completion>=signed_on)
);

CREATE TABLE IF NOT EXISTS ug_works_contract.budget_versions (
 budget_version_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 contract_id BIGINT NOT NULL REFERENCES ug_works_contract.contracts(contract_id) ON DELETE RESTRICT,
 version_no INTEGER NOT NULL CHECK (version_no>0),
 approved_amount NUMERIC(16,2) NOT NULL CHECK (approved_amount>0),
 approved_by_ref TEXT NOT NULL CHECK (length(btrim(approved_by_ref))>0),
 approval_evidence_ref TEXT NOT NULL CHECK (length(btrim(approval_evidence_ref))>0),
 effective_on DATE NOT NULL,
 recorded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(contract_id,version_no)
);

CREATE TABLE IF NOT EXISTS ug_works_contract.milestones (
 milestone_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 contract_id BIGINT NOT NULL REFERENCES ug_works_contract.contracts(contract_id) ON DELETE RESTRICT,
 milestone_code TEXT NOT NULL CHECK (length(btrim(milestone_code))>0),
 milestone_name TEXT NOT NULL CHECK (length(btrim(milestone_name))>0),
 planned_due_on DATE NOT NULL,
 planned_value NUMERIC(16,2) NOT NULL CHECK (planned_value>=0),
 status TEXT NOT NULL DEFAULT 'planned' CHECK (status IN ('planned','submitted','under_review','accepted','rejected','waived')),
 UNIQUE(contract_id,milestone_code)
);

CREATE TABLE IF NOT EXISTS ug_works_contract.certificates (
 certificate_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 certificate_ref TEXT NOT NULL UNIQUE CHECK (certificate_ref ~ '^UGCERT-[A-Z0-9-]{3,40}$'),
 milestone_id BIGINT NOT NULL REFERENCES ug_works_contract.milestones(milestone_id) ON DELETE RESTRICT,
 submitted_amount NUMERIC(16,2) NOT NULL CHECK (submitted_amount>0),
 submitted_by_ref TEXT NOT NULL CHECK (length(btrim(submitted_by_ref))>0),
 submitted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 status TEXT NOT NULL DEFAULT 'submitted' CHECK (status IN ('submitted','under_review','approved','rejected','paid','void')),
 reviewed_by_ref TEXT,
 reviewed_at TIMESTAMPTZ,
 decision_reason TEXT,
 evidence_ref TEXT,
 paid_at TIMESTAMPTZ,
 payment_ref TEXT UNIQUE,
 CHECK ((reviewed_at IS NULL AND reviewed_by_ref IS NULL AND decision_reason IS NULL AND evidence_ref IS NULL)
    OR (reviewed_at IS NOT NULL AND length(btrim(COALESCE(reviewed_by_ref,'')))>0
        AND length(btrim(COALESCE(decision_reason,'')))>0 AND length(btrim(COALESCE(evidence_ref,'')))>0)),
 CHECK ((status IN ('approved','rejected','paid','void')) = (reviewed_at IS NOT NULL)),
 CHECK ((status='paid') = (paid_at IS NOT NULL AND payment_ref IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS ug_works_contract.events (
 event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 entity_type TEXT NOT NULL CHECK (entity_type IN ('project','contract','budget','milestone','certificate')),
 entity_ref TEXT NOT NULL CHECK (length(btrim(entity_ref))>0),
 event_type TEXT NOT NULL CHECK (length(btrim(event_type))>0),
 actor_ref TEXT NOT NULL CHECK (length(btrim(actor_ref))>0),
 reason TEXT NOT NULL CHECK (length(btrim(reason))>0),
 evidence_ref TEXT,
 occurred_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_works_contract_status ON ug_works_contract.contracts(status,planned_completion);
CREATE INDEX IF NOT EXISTS ix_works_milestone_due ON ug_works_contract.milestones(status,planned_due_on);
CREATE INDEX IF NOT EXISTS ix_works_certificate_queue ON ug_works_contract.certificates(status,submitted_at,certificate_id);
CREATE INDEX IF NOT EXISTS ix_works_events_entity ON ug_works_contract.events(entity_type,entity_ref,occurred_at DESC);

COMMENT ON SCHEMA ug_works_contract IS 'Synthetic public works contract milestone and certificate workflow; not an official procurement register.';
COMMENT ON COLUMN ug_works_contract.contracts.supplier_ref IS 'Opaque supplier reference; supplier identity and due diligence belong in an authorised system.';
