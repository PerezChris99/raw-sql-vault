-- Purpose: synthetic public transport route, stop, timetable, observed departure and disruption reporting.
-- Engine: PostgreSQL 15+. Aggregate service operations only; no passenger-level movement histories.
CREATE SCHEMA IF NOT EXISTS ug_transport;

CREATE TABLE IF NOT EXISTS ug_transport.operators (
 operator_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 operator_ref TEXT NOT NULL UNIQUE CHECK (operator_ref ~ '^UGTOP-[A-Z0-9-]{3,40}$'),
 operator_name TEXT NOT NULL CHECK (length(btrim(operator_name))>0),
 operator_type TEXT NOT NULL CHECK (operator_type IN ('public','licensed_private','community','other')),
 status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','suspended','retired'))
);

CREATE TABLE IF NOT EXISTS ug_transport.routes (
 route_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 route_ref TEXT NOT NULL UNIQUE CHECK (route_ref ~ '^UGTR-[A-Z0-9-]{3,40}$'),
 operator_id BIGINT NOT NULL REFERENCES ug_transport.operators(operator_id) ON DELETE RESTRICT,
 origin_locality_ref TEXT NOT NULL CHECK (length(btrim(origin_locality_ref))>0),
 destination_locality_ref TEXT NOT NULL CHECK (length(btrim(destination_locality_ref))>0),
 route_name TEXT NOT NULL CHECK (length(btrim(route_name))>0),
 planned_minutes INTEGER NOT NULL CHECK (planned_minutes BETWEEN 1 AND 2000),
 status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('draft','active','suspended','retired'))
);

CREATE TABLE IF NOT EXISTS ug_transport.stops (
 stop_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 stop_ref TEXT NOT NULL UNIQUE CHECK (stop_ref ~ '^UGTS-[A-Z0-9-]{3,40}$'),
 locality_ref TEXT NOT NULL CHECK (length(btrim(locality_ref))>0),
 stop_name TEXT NOT NULL CHECK (length(btrim(stop_name))>0),
 accessibility_notes_redacted TEXT,
 is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS ug_transport.route_stops (
 route_id BIGINT NOT NULL REFERENCES ug_transport.routes(route_id) ON DELETE RESTRICT,
 stop_id BIGINT NOT NULL REFERENCES ug_transport.stops(stop_id) ON DELETE RESTRICT,
 sequence_no INTEGER NOT NULL CHECK (sequence_no>0),
 scheduled_offset_minutes INTEGER NOT NULL CHECK (scheduled_offset_minutes>=0),
 PRIMARY KEY(route_id,stop_id),
 UNIQUE(route_id,sequence_no)
);

CREATE TABLE IF NOT EXISTS ug_transport.departure_schedules (
 schedule_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 schedule_ref TEXT NOT NULL UNIQUE CHECK (schedule_ref ~ '^UGTSCH-[A-Z0-9-]{3,40}$'),
 route_id BIGINT NOT NULL REFERENCES ug_transport.routes(route_id) ON DELETE RESTRICT,
 stop_id BIGINT NOT NULL REFERENCES ug_transport.stops(stop_id) ON DELETE RESTRICT,
 scheduled_at TIMESTAMPTZ NOT NULL,
 service_date DATE NOT NULL,
 vehicle_class TEXT NOT NULL CHECK (length(btrim(vehicle_class))>0),
 status TEXT NOT NULL DEFAULT 'scheduled' CHECK (status IN ('scheduled','observed','cancelled','missed')),
 UNIQUE(route_id,stop_id,scheduled_at)
);

CREATE TABLE IF NOT EXISTS ug_transport.departure_observations (
 observation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 observation_ref TEXT NOT NULL UNIQUE CHECK (observation_ref ~ '^UGTOBS-[A-Z0-9-]{3,40}$'),
 idempotency_key TEXT NOT NULL UNIQUE CHECK (length(btrim(idempotency_key)) BETWEEN 8 AND 128),
 schedule_id BIGINT NOT NULL REFERENCES ug_transport.departure_schedules(schedule_id) ON DELETE RESTRICT,
 observed_at TIMESTAMPTZ,
 observation_status TEXT NOT NULL CHECK (observation_status IN ('departed','delayed','cancelled','not_observed')),
 delay_minutes INTEGER CHECK (delay_minutes IS NULL OR delay_minutes>=0),
 source_type TEXT NOT NULL CHECK (source_type IN ('authorised_manual','operator_report','approved_sensor','survey')),
 source_ref TEXT NOT NULL CHECK (length(btrim(source_ref))>0),
 recorded_by_ref TEXT NOT NULL CHECK (length(btrim(recorded_by_ref))>0),
 evidence_ref TEXT NOT NULL CHECK (length(btrim(evidence_ref))>0),
 CHECK ((observation_status='not_observed') OR observed_at IS NOT NULL),
 CHECK (observation_status<>'departed' OR delay_minutes IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS ug_transport.disruptions (
 disruption_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 disruption_ref TEXT NOT NULL UNIQUE CHECK (disruption_ref ~ '^UGTDIS-[A-Z0-9-]{3,40}$'),
 route_id BIGINT NOT NULL REFERENCES ug_transport.routes(route_id) ON DELETE RESTRICT,
 started_at TIMESTAMPTZ NOT NULL,
 ended_at TIMESTAMPTZ,
 category TEXT NOT NULL CHECK (category IN ('weather','road_condition','vehicle_shortage','operator_issue','safety','other')),
 summary_redacted TEXT NOT NULL CHECK (length(btrim(summary_redacted))>0),
 source_ref TEXT NOT NULL CHECK (length(btrim(source_ref))>0),
 status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open','resolved','closed')),
 resolution_ref TEXT,
 CHECK (ended_at IS NULL OR ended_at>=started_at),
 CHECK ((status IN ('resolved','closed')) = (ended_at IS NOT NULL AND resolution_ref IS NOT NULL))
);

CREATE INDEX IF NOT EXISTS ix_transport_schedule_route_date ON ug_transport.departure_schedules(route_id,service_date,scheduled_at);
CREATE INDEX IF NOT EXISTS ix_transport_observation_status ON ug_transport.departure_observations(observation_status,schedule_id);
CREATE INDEX IF NOT EXISTS ix_transport_disruption_queue ON ug_transport.disruptions(status,started_at);

COMMENT ON SCHEMA ug_transport IS 'Synthetic route-level public transport reliability analytics; not an individual passenger tracking system.';
