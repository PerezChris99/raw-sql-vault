-- Purpose: cold-chain equipment, temperature observations and maintenance workflow.
-- Engine: PostgreSQL 15+. Prerequisites: none. Rerunnable: yes; additive.
CREATE SCHEMA IF NOT EXISTS ug_cold_chain;

CREATE TABLE IF NOT EXISTS ug_cold_chain.facilities (
    facility_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    facility_ref TEXT NOT NULL UNIQUE CHECK (facility_ref ~ '^UGFAC-[A-Z0-9-]{3,40}$'),
    facility_name TEXT NOT NULL CHECK (length(btrim(facility_name))>0),
    locality_ref TEXT NOT NULL CHECK (length(btrim(locality_ref))>0),
    source_reference TEXT NOT NULL CHECK (length(btrim(source_reference))>0),
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS ug_cold_chain.equipment (
    equipment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_ref TEXT NOT NULL UNIQUE CHECK (equipment_ref ~ '^UGCC-[A-Z0-9-]{3,40}$'),
    facility_id BIGINT NOT NULL REFERENCES ug_cold_chain.facilities(facility_id) ON DELETE RESTRICT,
    equipment_type TEXT NOT NULL CHECK (equipment_type IN ('vaccine_fridge','medical_freezer','cold_room','cold_box','temperature_logger')),
    manufacturer_ref TEXT,
    serial_ref TEXT NOT NULL UNIQUE CHECK (length(btrim(serial_ref))>0),
    temperature_min_c NUMERIC(5,2) NOT NULL,
    temperature_max_c NUMERIC(5,2) NOT NULL,
    commissioned_on DATE NOT NULL,
    calibration_due_on DATE,
    operational_status TEXT NOT NULL DEFAULT 'active'
      CHECK (operational_status IN ('active','maintenance','retired','quarantined')),
    CHECK (temperature_min_c < temperature_max_c),
    CHECK (calibration_due_on IS NULL OR calibration_due_on >= commissioned_on)
);

CREATE TABLE IF NOT EXISTS ug_cold_chain.temperature_readings (
    reading_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reading_ref TEXT NOT NULL UNIQUE CHECK (reading_ref ~ '^UGTEMP-[A-Z0-9-]{3,40}$'),
    idempotency_key TEXT NOT NULL UNIQUE CHECK (length(btrim(idempotency_key)) BETWEEN 8 AND 128),
    equipment_id BIGINT NOT NULL REFERENCES ug_cold_chain.equipment(equipment_id) ON DELETE RESTRICT,
    observed_at TIMESTAMPTZ NOT NULL,
    temperature_c NUMERIC(6,2) NOT NULL CHECK (temperature_c BETWEEN -100 AND 100),
    sensor_ref TEXT NOT NULL CHECK (length(btrim(sensor_ref))>0),
    source_reference TEXT NOT NULL CHECK (length(btrim(source_reference))>0),
    calibration_was_current BOOLEAN NOT NULL,
    recorded_by TEXT NOT NULL CHECK (length(btrim(recorded_by))>0),
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_cold_chain_readings_equipment_time
 ON ug_cold_chain.temperature_readings(equipment_id,observed_at DESC);

CREATE TABLE IF NOT EXISTS ug_cold_chain.excursions (
    excursion_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reading_id BIGINT NOT NULL UNIQUE REFERENCES ug_cold_chain.temperature_readings(reading_id) ON DELETE RESTRICT,
    equipment_id BIGINT NOT NULL REFERENCES ug_cold_chain.equipment(equipment_id) ON DELETE RESTRICT,
    excursion_kind TEXT NOT NULL CHECK (excursion_kind IN ('below_minimum','above_maximum','calibration_overdue')),
    severity TEXT NOT NULL CHECK (severity IN ('low','moderate','high','critical')),
    status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open','investigating','resolved','accepted_risk')),
    detected_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolved_at TIMESTAMPTZ,
    resolution_reason TEXT,
    resolved_by TEXT,
    CHECK ((status IN ('resolved','accepted_risk')) = (resolved_at IS NOT NULL)),
    CHECK ((resolved_at IS NULL AND resolution_reason IS NULL AND resolved_by IS NULL)
       OR (resolved_at IS NOT NULL AND length(btrim(COALESCE(resolution_reason,'')))>0 AND length(btrim(COALESCE(resolved_by,'')))>0))
);

CREATE TABLE IF NOT EXISTS ug_cold_chain.maintenance_orders (
    work_order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_order_ref TEXT NOT NULL UNIQUE CHECK (work_order_ref ~ '^UGWO-[A-Z0-9-]{3,40}$'),
    equipment_id BIGINT NOT NULL REFERENCES ug_cold_chain.equipment(equipment_id) ON DELETE RESTRICT,
    excursion_id BIGINT REFERENCES ug_cold_chain.excursions(excursion_id) ON DELETE RESTRICT,
    priority TEXT NOT NULL CHECK (priority IN ('low','normal','high','urgent')),
    status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open','assigned','in_progress','completed','cancelled')),
    reported_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    assigned_to_ref TEXT,
    completed_at TIMESTAMPTZ,
    completion_reference TEXT,
    created_by TEXT NOT NULL CHECK (length(btrim(created_by))>0),
    CHECK ((status='completed') = (completed_at IS NOT NULL)),
    CHECK ((completed_at IS NULL AND completion_reference IS NULL)
       OR (completed_at IS NOT NULL AND length(btrim(COALESCE(completion_reference,'')))>0))
);

CREATE TABLE IF NOT EXISTS ug_cold_chain.maintenance_events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_order_id BIGINT NOT NULL REFERENCES ug_cold_chain.maintenance_orders(work_order_id) ON DELETE RESTRICT,
    from_status TEXT,
    to_status TEXT NOT NULL CHECK (to_status IN ('open','assigned','in_progress','completed','cancelled')),
    actor_ref TEXT NOT NULL CHECK (length(btrim(actor_ref))>0),
    reason TEXT NOT NULL CHECK (length(btrim(reason))>0),
    evidence_reference TEXT,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_cold_chain_excursion_queue ON ug_cold_chain.excursions(status,severity,detected_at);
CREATE INDEX IF NOT EXISTS ix_cold_chain_work_order_queue ON ug_cold_chain.maintenance_orders(status,priority,reported_at);
CREATE INDEX IF NOT EXISTS ix_cold_chain_work_order_history ON ug_cold_chain.maintenance_events(work_order_id,occurred_at DESC,event_id DESC);

COMMENT ON SCHEMA ug_cold_chain IS 'Synthetic cold-chain monitoring and maintenance workflow; not a clinical or vaccine inventory system.';
COMMENT ON COLUMN ug_cold_chain.temperature_readings.calibration_was_current IS 'Snapshot at ingest time; preserve even if calibration metadata later changes.';
