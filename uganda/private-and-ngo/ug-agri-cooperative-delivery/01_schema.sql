-- PostgreSQL 15+; synthetic agricultural and payables records only.
CREATE SCHEMA IF NOT EXISTS coop_demo;
CREATE TABLE IF NOT EXISTS coop_demo.cooperatives(
 cooperative_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 cooperative_code TEXT NOT NULL UNIQUE,cooperative_label TEXT NOT NULL,locality_code TEXT NOT NULL,
 is_active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS coop_demo.members(
 member_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 cooperative_id BIGINT NOT NULL REFERENCES coop_demo.cooperatives(cooperative_id) ON DELETE RESTRICT,
 member_ref TEXT NOT NULL UNIQUE,joined_on DATE NOT NULL DEFAULT CURRENT_DATE,is_active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS coop_demo.produce_catalog(
 produce_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,produce_code TEXT NOT NULL UNIQUE,
 produce_label TEXT NOT NULL,unit_of_measure TEXT NOT NULL DEFAULT 'kg',is_active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS coop_demo.deliveries(
 delivery_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,delivery_ref TEXT NOT NULL UNIQUE,
 member_id BIGINT NOT NULL REFERENCES coop_demo.members(member_id) ON DELETE RESTRICT,
 produce_id BIGINT NOT NULL REFERENCES coop_demo.produce_catalog(produce_id) ON DELETE RESTRICT,
 delivery_date DATE NOT NULL,gross_kg NUMERIC(12,3) NOT NULL CHECK(gross_kg>0),
 accepted_kg NUMERIC(12,3) NOT NULL CHECK(accepted_kg>=0),
 rejected_kg NUMERIC(12,3) NOT NULL CHECK(rejected_kg>=0 AND rejected_kg<=gross_kg),
 price_per_kg_ugx NUMERIC(18,2) NOT NULL CHECK(price_per_kg_ugx>=0),
 payable_ugx NUMERIC(20,2) GENERATED ALWAYS AS (round(accepted_kg*price_per_kg_ugx,2)) STORED,
 grade_ref TEXT NOT NULL,status TEXT NOT NULL DEFAULT 'received' CHECK(status IN('received','quality_checked','approved','rejected')),
 quality_note TEXT,approved_by_ref TEXT,approved_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK(accepted_kg+rejected_kg=gross_kg),
 CHECK(status<>'approved' OR (approved_by_ref IS NOT NULL AND approved_at IS NOT NULL))
);
CREATE TABLE IF NOT EXISTS coop_demo.delivery_events(
 event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 delivery_id BIGINT NOT NULL REFERENCES coop_demo.deliveries(delivery_id) ON DELETE RESTRICT,
 previous_status TEXT,new_status TEXT NOT NULL CHECK(new_status IN('received','quality_checked','approved','rejected')),
 event_note TEXT NOT NULL,actor_ref TEXT NOT NULL,grade_ref TEXT,happened_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_coop_delivery_events_history ON coop_demo.delivery_events(delivery_id,happened_at DESC,event_id DESC);
CREATE TABLE IF NOT EXISTS coop_demo.payments(
 payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,payment_ref TEXT NOT NULL UNIQUE,
 delivery_id BIGINT NOT NULL REFERENCES coop_demo.deliveries(delivery_id) ON DELETE RESTRICT,
 paid_at TIMESTAMPTZ NOT NULL DEFAULT now(),amount_ugx NUMERIC(20,2) NOT NULL CHECK(amount_ugx>0),
 channel TEXT NOT NULL CHECK(channel IN('bank_transfer','mobile_money_batch','cash_receipt','other')),
 external_reference TEXT NOT NULL,idempotency_key TEXT NOT NULL UNIQUE
);
CREATE INDEX IF NOT EXISTS ix_coop_delivery_member_date ON coop_demo.deliveries(member_id,delivery_date DESC);
CREATE INDEX IF NOT EXISTS ix_coop_delivery_status_date ON coop_demo.deliveries(status,delivery_date);
CREATE INDEX IF NOT EXISTS ix_coop_payments_delivery_time ON coop_demo.payments(delivery_id,paid_at DESC);
COMMENT ON TABLE coop_demo.members IS 'Pseudonymous synthetic member refs only; no direct personal identifiers.';
COMMENT ON TABLE coop_demo.payments IS 'Synthetic payment events, not a payment-provider ledger.';