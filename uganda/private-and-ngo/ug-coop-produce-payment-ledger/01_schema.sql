-- Purpose: auditable cooperative produce delivery valuation and payment allocation.
-- Engine: PostgreSQL 15+. Prerequisites: none. Rerunnable: yes; additive.
CREATE SCHEMA IF NOT EXISTS ug_coop_pay;

CREATE TABLE IF NOT EXISTS ug_coop_pay.members (
    member_ref TEXT PRIMARY KEY CHECK (length(btrim(member_ref)) BETWEEN 3 AND 96),
    member_code TEXT NOT NULL UNIQUE CHECK (member_code ~ '^[A-Z0-9_-]{3,40}$'),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS ug_coop_pay.produce_types (
    produce_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produce_code TEXT NOT NULL UNIQUE CHECK (produce_code ~ '^[A-Z0-9_-]{2,40}$'),
    produce_name TEXT NOT NULL CHECK (length(btrim(produce_name)) > 0),
    unit_code TEXT NOT NULL DEFAULT 'KG' CHECK (unit_code IN ('KG')),
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS ug_coop_pay.price_rates (
    price_rate_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produce_type_id BIGINT NOT NULL REFERENCES ug_coop_pay.produce_types(produce_type_id) ON DELETE RESTRICT,
    grade_code TEXT NOT NULL CHECK (length(btrim(grade_code)) > 0),
    valid_from DATE NOT NULL,
    valid_to DATE,
    rate_per_kg NUMERIC(14,4) NOT NULL CHECK (rate_per_kg >= 0),
    currency_code CHAR(3) NOT NULL DEFAULT 'UGX' CHECK (currency_code ~ '^[A-Z]{3}$'),
    source_reference TEXT NOT NULL CHECK (length(btrim(source_reference)) > 0),
    approved_by TEXT NOT NULL CHECK (length(btrim(approved_by)) > 0),
    CHECK (valid_to IS NULL OR valid_to >= valid_from)
);
CREATE INDEX IF NOT EXISTS ix_coop_rates_lookup
 ON ug_coop_pay.price_rates(produce_type_id,grade_code,valid_from DESC,valid_to);

CREATE TABLE IF NOT EXISTS ug_coop_pay.deliveries (
    delivery_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    delivery_ref TEXT NOT NULL UNIQUE CHECK (delivery_ref ~ '^UGD-[A-Z0-9-]{4,40}$'),
    source_ticket_ref TEXT NOT NULL UNIQUE CHECK (length(btrim(source_ticket_ref)) > 0),
    member_ref TEXT NOT NULL REFERENCES ug_coop_pay.members(member_ref) ON DELETE RESTRICT,
    produce_type_id BIGINT NOT NULL REFERENCES ug_coop_pay.produce_types(produce_type_id) ON DELETE RESTRICT,
    grade_code TEXT NOT NULL CHECK (length(btrim(grade_code)) > 0),
    received_at TIMESTAMPTZ NOT NULL,
    gross_weight_kg NUMERIC(14,3) NOT NULL CHECK (gross_weight_kg > 0),
    accepted_weight_kg NUMERIC(14,3) NOT NULL CHECK (accepted_weight_kg >= 0 AND accepted_weight_kg <= gross_weight_kg),
    status TEXT NOT NULL CHECK (status IN ('accepted','partially_accepted','rejected')),
    scale_reference TEXT NOT NULL CHECK (length(btrim(scale_reference)) > 0),
    recorded_by TEXT NOT NULL CHECK (length(btrim(recorded_by)) > 0),
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK ((status='accepted' AND accepted_weight_kg=gross_weight_kg)
        OR (status='partially_accepted' AND accepted_weight_kg>0 AND accepted_weight_kg<gross_weight_kg)
        OR (status='rejected' AND accepted_weight_kg=0))
);

CREATE TABLE IF NOT EXISTS ug_coop_pay.deductions (
    deduction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    delivery_id BIGINT NOT NULL REFERENCES ug_coop_pay.deliveries(delivery_id) ON DELETE RESTRICT,
    deduction_code TEXT NOT NULL CHECK (length(btrim(deduction_code)) > 0),
    amount NUMERIC(14,2) NOT NULL CHECK (amount > 0),
    reason TEXT NOT NULL CHECK (length(btrim(reason)) > 0),
    source_reference TEXT NOT NULL CHECK (length(btrim(source_reference)) > 0),
    recorded_by TEXT NOT NULL CHECK (length(btrim(recorded_by)) > 0),
    approved_by TEXT,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (approved_by IS NULL OR length(btrim(approved_by)) > 0)
);

CREATE TABLE IF NOT EXISTS ug_coop_pay.payments (
    payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_ref TEXT NOT NULL UNIQUE CHECK (payment_ref ~ '^UGPAY-[A-Z0-9-]{4,40}$'),
    member_ref TEXT NOT NULL REFERENCES ug_coop_pay.members(member_ref) ON DELETE RESTRICT,
    idempotency_key TEXT NOT NULL UNIQUE CHECK (length(btrim(idempotency_key)) BETWEEN 8 AND 128),
    amount NUMERIC(14,2) NOT NULL CHECK (amount > 0),
    currency_code CHAR(3) NOT NULL DEFAULT 'UGX' CHECK (currency_code ~ '^[A-Z]{3}$'),
    payment_method_ref TEXT NOT NULL CHECK (length(btrim(payment_method_ref)) > 0),
    source_reference TEXT NOT NULL CHECK (length(btrim(source_reference)) > 0),
    paid_at TIMESTAMPTZ NOT NULL,
    recorded_by TEXT NOT NULL CHECK (length(btrim(recorded_by)) > 0),
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS ug_coop_pay.payment_allocations (
    allocation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id BIGINT NOT NULL REFERENCES ug_coop_pay.payments(payment_id) ON DELETE RESTRICT,
    delivery_id BIGINT NOT NULL REFERENCES ug_coop_pay.deliveries(delivery_id) ON DELETE RESTRICT,
    amount NUMERIC(14,2) NOT NULL CHECK (amount > 0),
    allocated_by TEXT NOT NULL CHECK (length(btrim(allocated_by)) > 0),
    allocation_reference TEXT NOT NULL UNIQUE CHECK (length(btrim(allocation_reference)) > 0),
    allocated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(payment_id,delivery_id)
);

CREATE TABLE IF NOT EXISTS ug_coop_pay.delivery_events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    delivery_id BIGINT NOT NULL REFERENCES ug_coop_pay.deliveries(delivery_id) ON DELETE RESTRICT,
    event_type TEXT NOT NULL CHECK (event_type IN ('received','weighed','graded','corrected','valued','disputed')),
    reason TEXT NOT NULL CHECK (length(btrim(reason)) > 0),
    source_reference TEXT NOT NULL CHECK (length(btrim(source_reference)) > 0),
    recorded_by TEXT NOT NULL CHECK (length(btrim(recorded_by)) > 0),
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_coop_deliveries_member_date ON ug_coop_pay.deliveries(member_ref,received_at DESC);
CREATE INDEX IF NOT EXISTS ix_coop_deliveries_type_grade_date ON ug_coop_pay.deliveries(produce_type_id,grade_code,received_at);
CREATE INDEX IF NOT EXISTS ix_coop_deductions_delivery ON ug_coop_pay.deductions(delivery_id,approved_by);
CREATE INDEX IF NOT EXISTS ix_coop_payments_member_date ON ug_coop_pay.payments(member_ref,paid_at DESC);
CREATE INDEX IF NOT EXISTS ix_coop_allocations_delivery ON ug_coop_pay.payment_allocations(delivery_id,allocated_at DESC);

COMMENT ON SCHEMA ug_coop_pay IS 'Synthetic cooperative produce settlement example; not an official payment or banking system.';
COMMENT ON COLUMN ug_coop_pay.members.member_ref IS 'Opaque cooperative member key; do not store national IDs, phone numbers or home addresses.';
COMMENT ON COLUMN ug_coop_pay.payments.payment_method_ref IS 'External provider reference only; never store account credentials or payment-card data.';
