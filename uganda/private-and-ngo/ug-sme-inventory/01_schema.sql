-- Purpose: normalized product catalogue and append-oriented stock ledger.
-- Engine: PostgreSQL 15+; no extensions required.
-- Rerun safety: CREATE IF NOT EXISTS; no data reset.
-- Ledger rows should be corrected with counter-movements, not edited/deleted.

CREATE SCHEMA IF NOT EXISTS sme_stock_demo;

CREATE TABLE IF NOT EXISTS sme_stock_demo.products (
    product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku TEXT NOT NULL UNIQUE,
    product_name TEXT NOT NULL CHECK (length(btrim(product_name)) > 0),
    category TEXT NOT NULL,
    unit_of_measure TEXT NOT NULL DEFAULT 'unit',
    unit_cost NUMERIC(18,2) NOT NULL CHECK (unit_cost >= 0),
    unit_price NUMERIC(18,2) NOT NULL CHECK (unit_price >= 0),
    currency CHAR(3) NOT NULL DEFAULT 'UGX',
    reorder_level INTEGER NOT NULL DEFAULT 0 CHECK (reorder_level >= 0),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS sme_stock_demo.stock_movements (
    movement_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES sme_stock_demo.products(product_id) ON DELETE RESTRICT,
    quantity_delta INTEGER NOT NULL CHECK (quantity_delta <> 0),
    reason TEXT NOT NULL CHECK (reason IN ('receipt', 'sale', 'return', 'adjustment')),
    idempotency_key TEXT NOT NULL UNIQUE CHECK (length(btrim(idempotency_key)) > 0),
    source_ref TEXT,
    actor_ref TEXT NOT NULL,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_stock_movements_product_time
    ON sme_stock_demo.stock_movements(product_id, recorded_at DESC, movement_id DESC);

CREATE INDEX IF NOT EXISTS ix_products_active_sku
    ON sme_stock_demo.products(sku) WHERE is_active = TRUE;

COMMENT ON TABLE sme_stock_demo.stock_movements IS
    'Append-oriented stock ledger; do not grant runtime users direct UPDATE/DELETE.';
COMMENT ON COLUMN sme_stock_demo.stock_movements.quantity_delta IS
    'Positive for receipts/returns, negative for sales/issues; total should never fall below zero.';