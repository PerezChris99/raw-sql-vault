-- Purpose: synthetic SME supplier quotation, purchase order, goods receipt and invoice matching workflow.
-- Engine: PostgreSQL 15+. Not a full accounting or payment system.
CREATE SCHEMA IF NOT EXISTS ug_sme_procure;

CREATE TABLE IF NOT EXISTS ug_sme_procure.suppliers (
 supplier_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 supplier_ref TEXT NOT NULL UNIQUE CHECK (supplier_ref ~ '^UGSUPP-[A-Z0-9-]{3,40}$'),
 supplier_name TEXT NOT NULL CHECK (length(btrim(supplier_name))>0),
 status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('pending_review','active','suspended','retired')),
 due_diligence_ref TEXT,
 reviewed_by_ref TEXT,
 reviewed_at TIMESTAMPTZ,
 CHECK ((status='pending_review' AND reviewed_at IS NULL) OR (status<>'pending_review' AND reviewed_at IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS ug_sme_procure.purchase_requests (
 request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 request_ref TEXT NOT NULL UNIQUE CHECK (request_ref ~ '^UGPR-[A-Z0-9-]{3,40}$'),
 requesting_unit_ref TEXT NOT NULL CHECK (length(btrim(requesting_unit_ref))>0),
 requested_by_ref TEXT NOT NULL CHECK (length(btrim(requested_by_ref))>0),
 reason TEXT NOT NULL CHECK (length(btrim(reason))>0),
 requested_on DATE NOT NULL DEFAULT CURRENT_DATE,
 status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','submitted','approved','rejected','ordered','cancelled')),
 reviewed_by_ref TEXT,
 reviewed_at TIMESTAMPTZ,
 review_evidence_ref TEXT,
 CHECK ((status IN ('approved','rejected','ordered') ) = (reviewed_at IS NOT NULL)),
 CHECK ((reviewed_at IS NULL AND reviewed_by_ref IS NULL AND review_evidence_ref IS NULL)
    OR (reviewed_at IS NOT NULL AND length(btrim(COALESCE(reviewed_by_ref,'')))>0 AND length(btrim(COALESCE(review_evidence_ref,'')))>0))
);

CREATE TABLE IF NOT EXISTS ug_sme_procure.purchase_orders (
 purchase_order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 po_ref TEXT NOT NULL UNIQUE CHECK (po_ref ~ '^UGPO-[A-Z0-9-]{3,40}$'),
 request_id BIGINT NOT NULL UNIQUE REFERENCES ug_sme_procure.purchase_requests(request_id) ON DELETE RESTRICT,
 supplier_id BIGINT NOT NULL REFERENCES ug_sme_procure.suppliers(supplier_id) ON DELETE RESTRICT,
 currency_code CHAR(3) NOT NULL DEFAULT 'UGX' CHECK (currency_code ~ '^[A-Z]{3}$'),
 ordered_on DATE NOT NULL,
 expected_on DATE,
 status TEXT NOT NULL DEFAULT 'issued' CHECK (status IN ('draft','issued','part_received','received','cancelled','closed')),
 approved_by_ref TEXT NOT NULL CHECK (length(btrim(approved_by_ref))>0),
 approval_evidence_ref TEXT NOT NULL CHECK (length(btrim(approval_evidence_ref))>0),
 CHECK (expected_on IS NULL OR expected_on>=ordered_on)
);

CREATE TABLE IF NOT EXISTS ug_sme_procure.purchase_order_lines (
 po_line_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 purchase_order_id BIGINT NOT NULL REFERENCES ug_sme_procure.purchase_orders(purchase_order_id) ON DELETE RESTRICT,
 line_no INTEGER NOT NULL CHECK (line_no>0),
 item_ref TEXT NOT NULL CHECK (length(btrim(item_ref))>0),
 description TEXT NOT NULL CHECK (length(btrim(description))>0),
 ordered_quantity NUMERIC(14,3) NOT NULL CHECK (ordered_quantity>0),
 unit_price NUMERIC(14,2) NOT NULL CHECK (unit_price>=0),
 tax_amount NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (tax_amount>=0),
 UNIQUE(purchase_order_id,line_no)
);

CREATE TABLE IF NOT EXISTS ug_sme_procure.goods_receipts (
 receipt_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 receipt_ref TEXT NOT NULL UNIQUE CHECK (receipt_ref ~ '^UGGR-[A-Z0-9-]{3,40}$'),
 purchase_order_id BIGINT NOT NULL REFERENCES ug_sme_procure.purchase_orders(purchase_order_id) ON DELETE RESTRICT,
 received_on DATE NOT NULL,
 received_by_ref TEXT NOT NULL CHECK (length(btrim(received_by_ref))>0),
 evidence_ref TEXT NOT NULL CHECK (length(btrim(evidence_ref))>0),
 status TEXT NOT NULL DEFAULT 'accepted' CHECK (status IN ('accepted','partial','rejected','reversed'))
);

CREATE TABLE IF NOT EXISTS ug_sme_procure.goods_receipt_lines (
 receipt_line_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 receipt_id BIGINT NOT NULL REFERENCES ug_sme_procure.goods_receipts(receipt_id) ON DELETE RESTRICT,
 po_line_id BIGINT NOT NULL REFERENCES ug_sme_procure.purchase_order_lines(po_line_id) ON DELETE RESTRICT,
 quantity_received NUMERIC(14,3) NOT NULL CHECK (quantity_received>0),
 quantity_rejected NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK (quantity_rejected>=0),
 reason TEXT,
 UNIQUE(receipt_id,po_line_id),
 CHECK (quantity_rejected<=quantity_received)
);

CREATE TABLE IF NOT EXISTS ug_sme_procure.supplier_invoices (
 invoice_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 invoice_ref TEXT NOT NULL UNIQUE CHECK (invoice_ref ~ '^UGINV-[A-Z0-9-]{3,40}$'),
 supplier_id BIGINT NOT NULL REFERENCES ug_sme_procure.suppliers(supplier_id) ON DELETE RESTRICT,
 purchase_order_id BIGINT NOT NULL REFERENCES ug_sme_procure.purchase_orders(purchase_order_id) ON DELETE RESTRICT,
 supplier_invoice_number TEXT NOT NULL,
 invoice_date DATE NOT NULL,
 invoice_amount NUMERIC(14,2) NOT NULL CHECK (invoice_amount>0),
 evidence_ref TEXT NOT NULL CHECK (length(btrim(evidence_ref))>0),
 status TEXT NOT NULL DEFAULT 'received' CHECK (status IN ('received','matched','exception','approved','rejected','paid')),
 UNIQUE(supplier_id,supplier_invoice_number)
);

CREATE INDEX IF NOT EXISTS ix_sme_po_status ON ug_sme_procure.purchase_orders(status,expected_on);
CREATE INDEX IF NOT EXISTS ix_sme_receipts_po ON ug_sme_procure.goods_receipts(purchase_order_id,received_on);
CREATE INDEX IF NOT EXISTS ix_sme_invoice_queue ON ug_sme_procure.supplier_invoices(status,invoice_date);

COMMENT ON SCHEMA ug_sme_procure IS 'Synthetic SME purchasing workflow; payment execution and general ledger posting are out of scope.';
