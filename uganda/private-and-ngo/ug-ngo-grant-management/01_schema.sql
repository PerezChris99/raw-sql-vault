-- PostgreSQL 15+; synthetic grant references only.
CREATE SCHEMA IF NOT EXISTS ngo_demo;
CREATE TABLE IF NOT EXISTS ngo_demo.donors(
 donor_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,donor_code TEXT NOT NULL UNIQUE,
 donor_label TEXT NOT NULL,donor_type TEXT NOT NULL CHECK(donor_type IN('foundation','government_demo','multilateral_demo','corporate_demo','other'))
);
CREATE TABLE IF NOT EXISTS ngo_demo.projects(
 project_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,project_code TEXT NOT NULL UNIQUE,
 project_label TEXT NOT NULL,locality_code TEXT NOT NULL,sector TEXT NOT NULL,
 start_date DATE NOT NULL,end_date DATE NOT NULL,status TEXT NOT NULL DEFAULT 'planned' CHECK(status IN('planned','active','completed','cancelled')),
 CHECK(end_date>=start_date)
);
CREATE TABLE IF NOT EXISTS ngo_demo.grants(
 grant_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,grant_ref TEXT NOT NULL UNIQUE,
 donor_id BIGINT NOT NULL REFERENCES ngo_demo.donors(donor_id) ON DELETE RESTRICT,
 project_id BIGINT NOT NULL REFERENCES ngo_demo.projects(project_id) ON DELETE RESTRICT,
 agreement_ref TEXT NOT NULL,grant_currency CHAR(3) NOT NULL,award_ceiling NUMERIC(20,2) NOT NULL CHECK(award_ceiling>=0),
 start_date DATE NOT NULL,end_date DATE NOT NULL,status TEXT NOT NULL DEFAULT 'active' CHECK(status IN('draft','active','suspended','closed')),
 CHECK(end_date>=start_date)
);
CREATE TABLE IF NOT EXISTS ngo_demo.expenditures(
 expenditure_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,expenditure_ref TEXT NOT NULL UNIQUE,
 grant_id BIGINT NOT NULL REFERENCES ngo_demo.grants(grant_id) ON DELETE RESTRICT,
 expense_date DATE NOT NULL,expense_category TEXT NOT NULL CHECK(expense_category IN('personnel_aggregate','supplies','transport','service_contract','grant_transfer','other')),
 amount NUMERIC(20,2) NOT NULL CHECK(amount>0),currency CHAR(3) NOT NULL,
 source_document_ref TEXT NOT NULL,idempotency_key TEXT NOT NULL UNIQUE,created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS ngo_demo.milestones(
 milestone_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,milestone_ref TEXT NOT NULL UNIQUE,
 project_id BIGINT NOT NULL REFERENCES ngo_demo.projects(project_id) ON DELETE RESTRICT,
 milestone_title TEXT NOT NULL,due_date DATE NOT NULL,status TEXT NOT NULL DEFAULT 'planned' CHECK(status IN('planned','submitted','verified','delayed','waived')),
 evidence_ref TEXT,verified_by_ref TEXT,verified_at TIMESTAMPTZ,
 CHECK(status<>'verified' OR (evidence_ref IS NOT NULL AND verified_by_ref IS NOT NULL AND verified_at IS NOT NULL))
);
CREATE TABLE IF NOT EXISTS ngo_demo.milestone_events(
 event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,milestone_id BIGINT NOT NULL REFERENCES ngo_demo.milestones(milestone_id) ON DELETE RESTRICT,
 previous_status TEXT,new_status TEXT NOT NULL CHECK(new_status IN('planned','submitted','verified','delayed','waived')),
 note TEXT NOT NULL,actor_ref TEXT NOT NULL,happened_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS ngo_demo.outcome_observations(
 observation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,observation_ref TEXT NOT NULL UNIQUE,
 project_id BIGINT NOT NULL REFERENCES ngo_demo.projects(project_id) ON DELETE RESTRICT,
 indicator_code TEXT NOT NULL,period_start DATE NOT NULL,period_end DATE NOT NULL,
 observed_value NUMERIC(20,4) NOT NULL,unit_label TEXT NOT NULL,disaggregation_code TEXT NOT NULL DEFAULT 'total',
 source_ref TEXT NOT NULL,recorded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK(period_end>=period_start),UNIQUE(project_id,indicator_code,period_start,period_end,disaggregation_code)
);
CREATE INDEX IF NOT EXISTS ix_ngo_grant_project_status ON ngo_demo.grants(project_id,status);
CREATE INDEX IF NOT EXISTS ix_ngo_expense_grant_date ON ngo_demo.expenditures(grant_id,expense_date DESC);
CREATE INDEX IF NOT EXISTS ix_ngo_milestone_due_status ON ngo_demo.milestones(status,due_date);
CREATE INDEX IF NOT EXISTS ix_ngo_outcome_indicator_period ON ngo_demo.outcome_observations(indicator_code,period_end DESC);
COMMENT ON TABLE ngo_demo.outcome_observations IS 'Aggregate synthetic indicators only; no beneficiary-level facts or impact claim is implied.';