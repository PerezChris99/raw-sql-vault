-- Purpose: synthetic humanitarian assistance authorisation, delivery and reconciliation workflow.
-- Engine: PostgreSQL 15+. Highly restricted teaching model; use pseudonymous recipient tokens only.
CREATE SCHEMA IF NOT EXISTS ug_aid;

CREATE TABLE IF NOT EXISTS ug_aid.programmes (
 programme_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 programme_ref TEXT NOT NULL UNIQUE CHECK (programme_ref ~ '^UGAID-P-[A-Z0-9-]{3,40}$'),
 sponsor_ref TEXT NOT NULL CHECK (length(btrim(sponsor_ref))>0),
 programme_name TEXT NOT NULL CHECK (length(btrim(programme_name))>0),
 assistance_type TEXT NOT NULL CHECK (assistance_type IN ('food','cash_reference','shelter','health_referral','education_support','water_sanitation','other')),
 period_start DATE NOT NULL,
 period_end DATE NOT NULL,
 status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','active','closed')),
 CHECK(period_end>=period_start)
);

CREATE TABLE IF NOT EXISTS ug_aid.recipients (
 recipient_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 recipient_token TEXT NOT NULL UNIQUE CHECK (recipient_token ~ '^SYN-AID-[A-Z0-9-]{3,48}$'),
 locality_ref TEXT NOT NULL CHECK (length(btrim(locality_ref))>0),
 registration_source_ref TEXT NOT NULL CHECK (length(btrim(registration_source_ref))>0),
 consent_or_authority_ref TEXT NOT NULL CHECK (length(btrim(consent_or_authority_ref))>0),
 status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','suspended','closed')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS ug_aid.authorisations (
 authorisation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 authorisation_ref TEXT NOT NULL UNIQUE CHECK (authorisation_ref ~ '^UGAID-A-[A-Z0-9-]{3,40}$'),
 programme_id BIGINT NOT NULL REFERENCES ug_aid.programmes(programme_id) ON DELETE RESTRICT,
 recipient_id BIGINT NOT NULL REFERENCES ug_aid.recipients(recipient_id) ON DELETE RESTRICT,
 assistance_period DATE NOT NULL,
 quantity NUMERIC(14,3) NOT NULL CHECK (quantity>0),
 unit_code TEXT NOT NULL CHECK (length(btrim(unit_code))>0),
 decision TEXT NOT NULL CHECK (decision IN ('approved','rejected','deferred')),
 decision_by_ref TEXT NOT NULL CHECK (length(btrim(decision_by_ref))>0),
 decision_reason_redacted TEXT NOT NULL CHECK (length(btrim(decision_reason_redacted))>0),
 evidence_ref TEXT NOT NULL CHECK (length(btrim(evidence_ref))>0),
 decided_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(programme_id,recipient_id,assistance_period),
 CHECK (decision<>'approved' OR quantity>0)
);

CREATE TABLE IF NOT EXISTS ug_aid.deliveries (
 delivery_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 delivery_ref TEXT NOT NULL UNIQUE CHECK (delivery_ref ~ '^UGAID-D-[A-Z0-9-]{3,40}$'),
 idempotency_key TEXT NOT NULL UNIQUE CHECK (length(btrim(idempotency_key)) BETWEEN 8 AND 128),
 authorisation_id BIGINT NOT NULL REFERENCES ug_aid.authorisations(authorisation_id) ON DELETE RESTRICT,
 quantity_delivered NUMERIC(14,3) NOT NULL CHECK (quantity_delivered>0),
 delivery_status TEXT NOT NULL CHECK (delivery_status IN ('delivered','partial','failed','returned')),
 delivered_at TIMESTAMPTZ NOT NULL,
 delivery_point_ref TEXT NOT NULL CHECK (length(btrim(delivery_point_ref))>0),
 recorded_by_ref TEXT NOT NULL CHECK (length(btrim(recorded_by_ref))>0),
 evidence_ref TEXT NOT NULL CHECK (length(btrim(evidence_ref))>0),
 exception_reason TEXT,
 CHECK (delivery_status NOT IN ('failed','returned') OR length(btrim(COALESCE(exception_reason,'')))>0)
);

CREATE TABLE IF NOT EXISTS ug_aid.referrals (
 referral_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 referral_ref TEXT NOT NULL UNIQUE CHECK (referral_ref ~ '^UGAID-R-[A-Z0-9-]{3,40}$'),
 recipient_id BIGINT NOT NULL REFERENCES ug_aid.recipients(recipient_id) ON DELETE RESTRICT,
 referral_type TEXT NOT NULL CHECK (referral_type IN ('protection','health','shelter','education','legal','other')),
 receiving_service_ref TEXT NOT NULL CHECK (length(btrim(receiving_service_ref))>0),
 reason_redacted TEXT NOT NULL CHECK (length(btrim(reason_redacted))>0),
 referred_by_ref TEXT NOT NULL CHECK (length(btrim(referred_by_ref))>0),
 consent_or_authority_ref TEXT NOT NULL CHECK (length(btrim(consent_or_authority_ref))>0),
 status TEXT NOT NULL DEFAULT 'referred' CHECK (status IN ('referred','accepted','completed','declined','closed')),
 referred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 outcome_evidence_ref TEXT
);

CREATE TABLE IF NOT EXISTS ug_aid.audit_events (
 event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 entity_type TEXT NOT NULL,
 entity_ref TEXT NOT NULL,
 event_type TEXT NOT NULL,
 actor_ref TEXT NOT NULL,
 reason_redacted TEXT NOT NULL,
 evidence_ref TEXT,
 occurred_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_aid_authorisation_queue ON ug_aid.authorisations(programme_id,decision,assistance_period);
CREATE INDEX IF NOT EXISTS ix_aid_delivery_status ON ug_aid.deliveries(delivery_status,delivered_at);
CREATE INDEX IF NOT EXISTS ix_aid_referral_queue ON ug_aid.referrals(status,referred_at);

COMMENT ON SCHEMA ug_aid IS 'Synthetic high-sensitivity aid reconciliation example; not a beneficiary registry.';
COMMENT ON COLUMN ug_aid.recipients.recipient_token IS 'Opaque synthetic token; never store names, exact household coordinates or protection narratives.';
