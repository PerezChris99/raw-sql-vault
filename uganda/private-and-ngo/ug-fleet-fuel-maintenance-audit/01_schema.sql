-- Purpose: synthetic fleet assignment, fuel issue, odometer and maintenance audit.
-- Engine: PostgreSQL 15+. Anomaly reports are investigation leads, not evidence of misconduct.
CREATE SCHEMA IF NOT EXISTS ug_fleet;

CREATE TABLE IF NOT EXISTS ug_fleet.vehicles (
 vehicle_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 vehicle_ref TEXT NOT NULL UNIQUE CHECK (vehicle_ref ~ '^UGVEH-[A-Z0-9-]{3,40}$'),
 vehicle_type TEXT NOT NULL CHECK (length(btrim(vehicle_type))>0),
 fuel_type TEXT NOT NULL CHECK (fuel_type IN ('petrol','diesel','electric','hybrid','other')),
 locality_ref TEXT NOT NULL CHECK (length(btrim(locality_ref))>0),
 odometer_unit TEXT NOT NULL DEFAULT 'km' CHECK (odometer_unit IN ('km','mi')),
 status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','maintenance','retired')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS ug_fleet.assignments (
 assignment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 assignment_ref TEXT NOT NULL UNIQUE CHECK (assignment_ref ~ '^UGASG-[A-Z0-9-]{3,40}$'),
 vehicle_id BIGINT NOT NULL REFERENCES ug_fleet.vehicles(vehicle_id) ON DELETE RESTRICT,
 operator_ref TEXT NOT NULL CHECK (length(btrim(operator_ref))>0),
 purpose_redacted TEXT NOT NULL CHECK (length(btrim(purpose_redacted))>0),
 starts_at TIMESTAMPTZ NOT NULL,
 ends_at TIMESTAMPTZ,
 approved_by_ref TEXT NOT NULL CHECK (length(btrim(approved_by_ref))>0),
 approval_evidence_ref TEXT NOT NULL CHECK (length(btrim(approval_evidence_ref))>0),
 CHECK (ends_at IS NULL OR ends_at>=starts_at)
);

CREATE TABLE IF NOT EXISTS ug_fleet.fuel_events (
 fuel_event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 fuel_ref TEXT NOT NULL UNIQUE CHECK (fuel_ref ~ '^UGFUEL-[A-Z0-9-]{3,40}$'),
 idempotency_key TEXT NOT NULL UNIQUE CHECK (length(btrim(idempotency_key)) BETWEEN 8 AND 128),
 vehicle_id BIGINT NOT NULL REFERENCES ug_fleet.vehicles(vehicle_id) ON DELETE RESTRICT,
 supplier_ref TEXT NOT NULL CHECK (length(btrim(supplier_ref))>0),
 fuel_date TIMESTAMPTZ NOT NULL,
 quantity_litres NUMERIC(12,3) NOT NULL CHECK (quantity_litres>0),
 unit_price NUMERIC(14,2) NOT NULL CHECK (unit_price>=0),
 odometer_reading NUMERIC(14,1) NOT NULL CHECK (odometer_reading>=0),
 receipt_ref TEXT NOT NULL UNIQUE CHECK (length(btrim(receipt_ref))>0),
 recorded_by_ref TEXT NOT NULL CHECK (length(btrim(recorded_by_ref))>0),
 evidence_ref TEXT NOT NULL CHECK (length(btrim(evidence_ref))>0)
);

CREATE TABLE IF NOT EXISTS ug_fleet.maintenance_orders (
 maintenance_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 maintenance_ref TEXT NOT NULL UNIQUE CHECK (maintenance_ref ~ '^UGMNT-[A-Z0-9-]{3,40}$'),
 vehicle_id BIGINT NOT NULL REFERENCES ug_fleet.vehicles(vehicle_id) ON DELETE RESTRICT,
 reported_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 odometer_reading NUMERIC(14,1) NOT NULL CHECK (odometer_reading>=0),
 issue_category TEXT NOT NULL CHECK (length(btrim(issue_category))>0),
 issue_summary_redacted TEXT NOT NULL CHECK (length(btrim(issue_summary_redacted))>0),
 priority TEXT NOT NULL DEFAULT 'normal' CHECK (priority IN ('low','normal','high','urgent')),
 status TEXT NOT NULL DEFAULT 'reported' CHECK (status IN ('reported','approved','in_progress','completed','cancelled')),
 approved_by_ref TEXT,
 approval_evidence_ref TEXT,
 completed_at TIMESTAMPTZ,
 completion_evidence_ref TEXT,
 CHECK ((status IN ('approved','in_progress','completed')) = (approved_by_ref IS NOT NULL AND approval_evidence_ref IS NOT NULL)),
 CHECK ((status='completed') = (completed_at IS NOT NULL AND completion_evidence_ref IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS ug_fleet.audit_events (
 event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 vehicle_id BIGINT NOT NULL REFERENCES ug_fleet.vehicles(vehicle_id) ON DELETE RESTRICT,
 event_type TEXT NOT NULL,
 actor_ref TEXT NOT NULL,
 reason TEXT NOT NULL,
 evidence_ref TEXT,
 occurred_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_fleet_fuel_vehicle_date ON ug_fleet.fuel_events(vehicle_id,fuel_date DESC);
CREATE INDEX IF NOT EXISTS ix_fleet_maintenance_queue ON ug_fleet.maintenance_orders(status,priority,reported_at);
CREATE INDEX IF NOT EXISTS ix_fleet_assignments_active ON ug_fleet.assignments(vehicle_id,starts_at,ends_at);

COMMENT ON SCHEMA ug_fleet IS 'Synthetic fleet audit example; no driver personal details or live vehicle telematics.';
