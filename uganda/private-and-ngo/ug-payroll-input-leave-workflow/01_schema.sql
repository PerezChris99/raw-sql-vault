-- Purpose: synthetic HR leave and approved payroll-input export workflow; not a payroll calculator.
-- Engine: PostgreSQL 15+. Store no bank details, national IDs or unnecessary employee personal data.
CREATE SCHEMA IF NOT EXISTS ug_hr_payroll;

CREATE TABLE IF NOT EXISTS ug_hr_payroll.staff_refs (
 staff_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 staff_ref TEXT NOT NULL UNIQUE CHECK (staff_ref ~ '^UGSTAFF-[A-Z0-9-]{3,40}$'),
 employing_unit_ref TEXT NOT NULL CHECK (length(btrim(employing_unit_ref))>0),
 role_ref TEXT NOT NULL CHECK (length(btrim(role_ref))>0),
 employment_type TEXT NOT NULL CHECK (employment_type IN ('permanent','contract','temporary','apprentice','other')),
 start_date DATE NOT NULL,
 end_date DATE,
 status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','on_leave','ended')),
 CHECK (end_date IS NULL OR end_date>=start_date)
);

CREATE TABLE IF NOT EXISTS ug_hr_payroll.leave_policies (
 policy_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 policy_ref TEXT NOT NULL UNIQUE CHECK (length(btrim(policy_ref))>0),
 leave_type TEXT NOT NULL CHECK (leave_type IN ('annual','sick','parental','study','compassionate','unpaid','other')),
 annual_entitlement_days NUMERIC(7,2) NOT NULL CHECK (annual_entitlement_days>=0),
 requires_evidence BOOLEAN NOT NULL DEFAULT FALSE,
 effective_from DATE NOT NULL,
 effective_to DATE,
 CHECK (effective_to IS NULL OR effective_to>=effective_from),
 UNIQUE(leave_type,effective_from)
);

CREATE TABLE IF NOT EXISTS ug_hr_payroll.leave_requests (
 leave_request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 leave_ref TEXT NOT NULL UNIQUE CHECK (leave_ref ~ '^UGLV-[A-Z0-9-]{3,40}$'),
 staff_id BIGINT NOT NULL REFERENCES ug_hr_payroll.staff_refs(staff_id) ON DELETE RESTRICT,
 policy_id BIGINT NOT NULL REFERENCES ug_hr_payroll.leave_policies(policy_id) ON DELETE RESTRICT,
 starts_on DATE NOT NULL,
 ends_on DATE NOT NULL,
 requested_days NUMERIC(7,2) NOT NULL CHECK (requested_days>0),
 reason_redacted TEXT NOT NULL CHECK (length(btrim(reason_redacted))>0),
 status TEXT NOT NULL DEFAULT 'submitted' CHECK (status IN ('draft','submitted','approved','rejected','cancelled','taken')),
 submitted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 reviewed_by_ref TEXT,
 reviewed_at TIMESTAMPTZ,
 review_evidence_ref TEXT,
 CHECK (ends_on>=starts_on),
 CHECK ((status IN ('approved','rejected','taken')) = (reviewed_at IS NOT NULL)),
 CHECK ((reviewed_at IS NULL AND reviewed_by_ref IS NULL AND review_evidence_ref IS NULL)
    OR (reviewed_at IS NOT NULL AND length(btrim(COALESCE(reviewed_by_ref,'')))>0 AND length(btrim(COALESCE(review_evidence_ref,'')))>0))
);

CREATE TABLE IF NOT EXISTS ug_hr_payroll.payroll_periods (
 period_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 period_ref TEXT NOT NULL UNIQUE CHECK (period_ref ~ '^UGPAY-P-[A-Z0-9-]{3,40}$'),
 period_start DATE NOT NULL,
 period_end DATE NOT NULL,
 status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open','review','approved','exported','closed')),
 approved_by_ref TEXT,
 approved_at TIMESTAMPTZ,
 approval_evidence_ref TEXT,
 exported_at TIMESTAMPTZ,
 export_reference TEXT UNIQUE,
 CHECK (period_end>=period_start),
 CHECK ((status IN ('approved','exported','closed')) = (approved_at IS NOT NULL)),
 CHECK ((status='exported' OR status='closed') = (exported_at IS NOT NULL AND export_reference IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS ug_hr_payroll.payroll_inputs (
 input_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 input_ref TEXT NOT NULL UNIQUE CHECK (input_ref ~ '^UGPAY-I-[A-Z0-9-]{3,40}$'),
 idempotency_key TEXT NOT NULL UNIQUE CHECK (length(btrim(idempotency_key)) BETWEEN 8 AND 128),
 period_id BIGINT NOT NULL REFERENCES ug_hr_payroll.payroll_periods(period_id) ON DELETE RESTRICT,
 staff_id BIGINT NOT NULL REFERENCES ug_hr_payroll.staff_refs(staff_id) ON DELETE RESTRICT,
 input_type TEXT NOT NULL CHECK (input_type IN ('base_pay_reference','allowance_reference','deduction_reference','overtime_hours','leave_days','correction_reference')),
 quantity NUMERIC(14,3) NOT NULL,
 unit_code TEXT NOT NULL CHECK (length(btrim(unit_code))>0),
 source_reference TEXT NOT NULL CHECK (length(btrim(source_reference))>0),
 approved_by_ref TEXT NOT NULL CHECK (length(btrim(approved_by_ref))>0),
 evidence_ref TEXT NOT NULL CHECK (length(btrim(evidence_ref))>0),
 recorded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(period_id,staff_id,input_type,source_reference)
);

CREATE TABLE IF NOT EXISTS ug_hr_payroll.audit_events (
 event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 entity_type TEXT NOT NULL,
 entity_ref TEXT NOT NULL,
 event_type TEXT NOT NULL,
 actor_ref TEXT NOT NULL,
 reason TEXT NOT NULL,
 evidence_ref TEXT,
 occurred_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_hr_leave_queue ON ug_hr_payroll.leave_requests(status,starts_on,leave_ref);
CREATE INDEX IF NOT EXISTS ix_hr_payroll_period ON ug_hr_payroll.payroll_inputs(period_id,staff_id);
CREATE INDEX IF NOT EXISTS ix_hr_staff_active ON ug_hr_payroll.staff_refs(status,employing_unit_ref);

COMMENT ON SCHEMA ug_hr_payroll IS 'Synthetic HR leave and payroll input control; not a payroll calculation, bank or tax filing system.';
