-- Purpose: synthetic SME double-entry journal, chart of accounts, accounting periods and receivables/payables references.
-- Engine: PostgreSQL 15+. Educational ledger only; not tax advice, certified accounting software or a bank connection.
CREATE SCHEMA IF NOT EXISTS ug_sme_ledger;

CREATE TABLE IF NOT EXISTS ug_sme_ledger.accounts (
 account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 account_code TEXT NOT NULL UNIQUE CHECK (account_code ~ '^[0-9A-Z_-]{2,32}$'),
 account_name TEXT NOT NULL CHECK (length(btrim(account_name))>0),
 account_type TEXT NOT NULL CHECK (account_type IN ('asset','liability','equity','income','expense')),
 parent_account_id BIGINT REFERENCES ug_sme_ledger.accounts(account_id) ON DELETE RESTRICT,
 is_control_account BOOLEAN NOT NULL DEFAULT FALSE,
 is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS ug_sme_ledger.periods (
 period_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 period_ref TEXT NOT NULL UNIQUE CHECK (period_ref ~ '^UGLED-P-[A-Z0-9-]{3,40}$'),
 starts_on DATE NOT NULL,
 ends_on DATE NOT NULL,
 status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open','review','closed')),
 closed_by_ref TEXT,
 closed_at TIMESTAMPTZ,
 closure_evidence_ref TEXT,
 CHECK(ends_on>=starts_on),
 CHECK((status='closed')=(closed_at IS NOT NULL AND closed_by_ref IS NOT NULL AND closure_evidence_ref IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS ug_sme_ledger.journal_entries (
 journal_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 journal_ref TEXT NOT NULL UNIQUE CHECK (journal_ref ~ '^UGLED-J-[A-Z0-9-]{3,40}$'),
 idempotency_key TEXT NOT NULL UNIQUE CHECK (length(btrim(idempotency_key)) BETWEEN 8 AND 128),
 period_id BIGINT NOT NULL REFERENCES ug_sme_ledger.periods(period_id) ON DELETE RESTRICT,
 transaction_date DATE NOT NULL,
 description_redacted TEXT NOT NULL CHECK (length(btrim(description_redacted))>0),
 source_type TEXT NOT NULL CHECK (source_type IN ('invoice_ref','receipt_ref','bank_ref','payroll_ref','adjustment_ref','opening_ref','other')),
 source_ref TEXT NOT NULL CHECK (length(btrim(source_ref))>0),
 status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','posted','reversed')),
 created_by_ref TEXT NOT NULL CHECK (length(btrim(created_by_ref))>0),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 posted_by_ref TEXT,
 posted_at TIMESTAMPTZ,
 posting_evidence_ref TEXT,
 reverses_journal_id BIGINT REFERENCES ug_sme_ledger.journal_entries(journal_id) ON DELETE RESTRICT,
 CHECK((status='draft')=(posted_at IS NULL AND posted_by_ref IS NULL AND posting_evidence_ref IS NULL)),
 CHECK(status<>'reversed' OR reverses_journal_id IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS ug_sme_ledger.journal_lines (
 line_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 journal_id BIGINT NOT NULL REFERENCES ug_sme_ledger.journal_entries(journal_id) ON DELETE RESTRICT,
 line_no INTEGER NOT NULL CHECK (line_no>0),
 account_id BIGINT NOT NULL REFERENCES ug_sme_ledger.accounts(account_id) ON DELETE RESTRICT,
 debit NUMERIC(16,2) NOT NULL DEFAULT 0 CHECK (debit>=0),
 credit NUMERIC(16,2) NOT NULL DEFAULT 0 CHECK (credit>=0),
 line_description_redacted TEXT NOT NULL CHECK (length(btrim(line_description_redacted))>0),
 cost_centre_ref TEXT,
 UNIQUE(journal_id,line_no),
 CHECK ((debit>0 AND credit=0) OR (credit>0 AND debit=0))
);

CREATE TABLE IF NOT EXISTS ug_sme_ledger.audit_events (
 event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 journal_id BIGINT NOT NULL REFERENCES ug_sme_ledger.journal_entries(journal_id) ON DELETE RESTRICT,
 event_type TEXT NOT NULL CHECK (event_type IN ('created','posted','reversed','period_closed')),
 actor_ref TEXT NOT NULL,
 reason TEXT NOT NULL,
 evidence_ref TEXT,
 occurred_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_ledger_journal_period_date ON ug_sme_ledger.journal_entries(period_id,transaction_date,status);
CREATE INDEX IF NOT EXISTS ix_ledger_lines_account_journal ON ug_sme_ledger.journal_lines(account_id,journal_id);
CREATE INDEX IF NOT EXISTS ix_ledger_audit_history ON ug_sme_ledger.audit_events(journal_id,occurred_at DESC);

COMMENT ON SCHEMA ug_sme_ledger IS 'Synthetic double-entry teaching ledger; not an official financial or tax system.';
