-- Purpose: synthetic cooperative/SME sales, returns, category margin and seasonality analytics.
-- Engine: PostgreSQL 15+. Customer tokens are optional and pseudonymous; no direct identity data.
CREATE SCHEMA IF NOT EXISTS ug_sales_analytics;

CREATE TABLE IF NOT EXISTS ug_sales_analytics.products (
 product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 product_ref TEXT NOT NULL UNIQUE CHECK (product_ref ~ '^UGSA-P-[A-Z0-9-]{3,40}$'),
 product_name TEXT NOT NULL CHECK (length(btrim(product_name))>0),
 category_ref TEXT NOT NULL CHECK (length(btrim(category_ref))>0),
 unit_code TEXT NOT NULL CHECK (length(btrim(unit_code))>0),
 active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS ug_sales_analytics.sales (
 sale_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 sale_ref TEXT NOT NULL UNIQUE CHECK (sale_ref ~ '^UGSA-S-[A-Z0-9-]{3,40}$'),
 idempotency_key TEXT NOT NULL UNIQUE CHECK (length(btrim(idempotency_key)) BETWEEN 8 AND 128),
 business_ref TEXT NOT NULL CHECK (length(btrim(business_ref))>0),
 sale_channel TEXT NOT NULL CHECK (sale_channel IN ('shop','market','wholesale','delivery','digital','other')),
 customer_token TEXT,
 sold_at TIMESTAMPTZ NOT NULL,
 currency_code CHAR(3) NOT NULL DEFAULT 'UGX' CHECK (currency_code ~ '^[A-Z]{3}$'),
 status TEXT NOT NULL DEFAULT 'completed' CHECK (status IN ('draft','completed','voided')),
 recorded_by_ref TEXT NOT NULL CHECK (length(btrim(recorded_by_ref))>0),
 source_receipt_ref TEXT NOT NULL UNIQUE CHECK (length(btrim(source_receipt_ref))>0)
);

CREATE TABLE IF NOT EXISTS ug_sales_analytics.sale_lines (
 sale_line_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 sale_id BIGINT NOT NULL REFERENCES ug_sales_analytics.sales(sale_id) ON DELETE RESTRICT,
 line_no INTEGER NOT NULL CHECK (line_no>0),
 product_id BIGINT NOT NULL REFERENCES ug_sales_analytics.products(product_id) ON DELETE RESTRICT,
 quantity NUMERIC(14,3) NOT NULL CHECK (quantity>0),
 unit_price NUMERIC(14,2) NOT NULL CHECK (unit_price>=0),
 unit_cost NUMERIC(14,2) NOT NULL CHECK (unit_cost>=0),
 UNIQUE(sale_id,line_no)
);

CREATE TABLE IF NOT EXISTS ug_sales_analytics.returns (
 return_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 return_ref TEXT NOT NULL UNIQUE CHECK (return_ref ~ '^UGSA-R-[A-Z0-9-]{3,40}$'),
 idempotency_key TEXT NOT NULL UNIQUE CHECK (length(btrim(idempotency_key)) BETWEEN 8 AND 128),
 sale_line_id BIGINT NOT NULL REFERENCES ug_sales_analytics.sale_lines(sale_line_id) ON DELETE RESTRICT,
 quantity NUMERIC(14,3) NOT NULL CHECK (quantity>0),
 refund_amount NUMERIC(14,2) NOT NULL CHECK (refund_amount>=0),
 reason TEXT NOT NULL CHECK (length(btrim(reason))>0),
 source_ref TEXT NOT NULL UNIQUE CHECK (length(btrim(source_ref))>0),
 recorded_by_ref TEXT NOT NULL CHECK (length(btrim(recorded_by_ref))>0),
 returned_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_sales_business_date ON ug_sales_analytics.sales(business_ref,sold_at,status);
CREATE INDEX IF NOT EXISTS ix_sales_lines_product ON ug_sales_analytics.sale_lines(product_id,sale_id);
CREATE INDEX IF NOT EXISTS ix_sales_returns_line ON ug_sales_analytics.returns(sale_line_id,returned_at);

COMMENT ON SCHEMA ug_sales_analytics IS 'Synthetic SME/cooperative sales analytics; not tax, payment or accounting software.';
