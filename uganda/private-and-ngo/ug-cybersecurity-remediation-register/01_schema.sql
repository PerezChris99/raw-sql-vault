-- Purpose: authorised asset inventory and vulnerability remediation tracking without exploit payloads.
-- Engine: PostgreSQL 15+. Do not store credentials, exploit steps, secrets or public IP details.
CREATE SCHEMA IF NOT EXISTS ug_cyber;

CREATE TABLE IF NOT EXISTS ug_cyber.asset_classes (
 class_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 class_code TEXT NOT NULL UNIQUE CHECK (length(btrim(class_code))>0),
 class_name TEXT NOT NULL CHECK (length(btrim(class_name))>0),
 default_criticality TEXT NOT NULL CHECK (default_criticality IN ('low','medium','high','critical'))
);

CREATE TABLE IF NOT EXISTS ug_cyber.assets (
 asset_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 asset_ref TEXT NOT NULL UNIQUE CHECK (asset_ref ~ '^UGASSET-[A-Z0-9-]{3,40}$'),
 class_id BIGINT NOT NULL REFERENCES ug_cyber.asset_classes(class_id) ON DELETE RESTRICT,
 owner_unit_ref TEXT NOT NULL CHECK (length(btrim(owner_unit_ref))>0),
 asset_label_redacted TEXT NOT NULL CHECK (length(btrim(asset_label_redacted))>0),
 environment TEXT NOT NULL CHECK (environment IN ('production','staging','development','lab','other')),
 criticality TEXT NOT NULL CHECK (criticality IN ('low','medium','high','critical')),
 data_classification TEXT NOT NULL CHECK (data_classification IN ('public','internal','restricted','highly_restricted')),
 authorised_inventory_ref TEXT NOT NULL CHECK (length(btrim(authorised_inventory_ref))>0),
 status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','quarantined','retired')),
 last_verified_at TIMESTAMPTZ,
 UNIQUE(owner_unit_ref,asset_label_redacted)
);

CREATE TABLE IF NOT EXISTS ug_cyber.findings (
 finding_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 finding_ref TEXT NOT NULL UNIQUE CHECK (finding_ref ~ '^UGFIND-[A-Z0-9-]{3,40}$'),
 asset_id BIGINT NOT NULL REFERENCES ug_cyber.assets(asset_id) ON DELETE RESTRICT,
 source_ref TEXT NOT NULL CHECK (length(btrim(source_ref))>0),
 category TEXT NOT NULL CHECK (category IN ('patching','configuration','access_review','certificate','backup','logging','dependency','policy','other')),
 severity TEXT NOT NULL CHECK (severity IN ('informational','low','medium','high','critical')),
 summary_redacted TEXT NOT NULL CHECK (length(btrim(summary_redacted))>0),
 discovered_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 remediation_due DATE NOT NULL,
 status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open','accepted_risk','in_progress','remediated','verified','closed')),
 owner_ref TEXT NOT NULL CHECK (length(btrim(owner_ref))>0),
 risk_acceptance_ref TEXT,
 CHECK (status<>'accepted_risk' OR length(btrim(COALESCE(risk_acceptance_ref,'')))>0)
);

CREATE TABLE IF NOT EXISTS ug_cyber.remediation_events (
 remediation_event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 finding_id BIGINT NOT NULL REFERENCES ug_cyber.findings(finding_id) ON DELETE RESTRICT,
 event_type TEXT NOT NULL CHECK (event_type IN ('assigned','plan_approved','risk_accepted','fix_deployed','verification_passed','verification_failed','reopened','closed')),
 actor_ref TEXT NOT NULL CHECK (length(btrim(actor_ref))>0),
 reason_redacted TEXT NOT NULL CHECK (length(btrim(reason_redacted))>0),
 change_reference TEXT,
 evidence_ref TEXT NOT NULL CHECK (length(btrim(evidence_ref))>0),
 occurred_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS ug_cyber.verification_results (
 verification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 finding_id BIGINT NOT NULL REFERENCES ug_cyber.findings(finding_id) ON DELETE RESTRICT,
 verifier_ref TEXT NOT NULL CHECK (length(btrim(verifier_ref))>0),
 verified_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 result TEXT NOT NULL CHECK (result IN ('pass','fail','inconclusive')),
 evidence_ref TEXT NOT NULL CHECK (length(btrim(evidence_ref))>0),
 notes_redacted TEXT NOT NULL CHECK (length(btrim(notes_redacted))>0)
);

CREATE INDEX IF NOT EXISTS ix_cyber_finding_queue ON ug_cyber.findings(status,severity,remediation_due);
CREATE INDEX IF NOT EXISTS ix_cyber_asset_criticality ON ug_cyber.assets(criticality,status);
CREATE INDEX IF NOT EXISTS ix_cyber_remediation_history ON ug_cyber.remediation_events(finding_id,occurred_at DESC);

COMMENT ON SCHEMA ug_cyber IS 'Authorised defensive asset and remediation register; no exploit payloads or credentials.';
