-- Purpose: synthetic customer support ticket lifecycle, response/resolution SLA and escalation reporting.
-- Engine: PostgreSQL 15+. Do not store passwords, payment card data or unredacted secrets.
CREATE SCHEMA IF NOT EXISTS ug_support;

CREATE TABLE IF NOT EXISTS ug_support.queues (
 queue_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 queue_ref TEXT NOT NULL UNIQUE CHECK (queue_ref ~ '^UGSUPQ-[A-Z0-9-]{3,40}$'),
 queue_name TEXT NOT NULL CHECK (length(btrim(queue_name))>0),
 first_response_minutes INTEGER NOT NULL CHECK (first_response_minutes BETWEEN 1 AND 100800),
 resolution_minutes INTEGER NOT NULL CHECK (resolution_minutes BETWEEN first_response_minutes AND 200000),
 business_calendar_ref TEXT NOT NULL CHECK (length(btrim(business_calendar_ref))>0),
 is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS ug_support.tickets (
 ticket_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ticket_ref TEXT NOT NULL UNIQUE CHECK (ticket_ref ~ '^UGTKT-[A-Z0-9-]{3,40}$'),
 idempotency_key TEXT NOT NULL UNIQUE CHECK (length(btrim(idempotency_key)) BETWEEN 8 AND 128),
 queue_id BIGINT NOT NULL REFERENCES ug_support.queues(queue_id) ON DELETE RESTRICT,
 customer_ref TEXT NOT NULL CHECK (length(btrim(customer_ref))>0),
 category TEXT NOT NULL CHECK (length(btrim(category))>0),
 priority TEXT NOT NULL DEFAULT 'normal' CHECK (priority IN ('low','normal','high','urgent')),
 subject_redacted TEXT NOT NULL CHECK (length(btrim(subject_redacted))>0),
 description_redacted TEXT,
 status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open','assigned','waiting_customer','waiting_third_party','resolved','closed','reopened')),
 assigned_to_ref TEXT,
 opened_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 first_response_at TIMESTAMPTZ,
 resolved_at TIMESTAMPTZ,
 closed_at TIMESTAMPTZ,
 source_ref TEXT NOT NULL CHECK (length(btrim(source_ref))>0),
 CHECK (resolved_at IS NULL OR resolved_at>=opened_at),
 CHECK (closed_at IS NULL OR (resolved_at IS NOT NULL AND closed_at>=resolved_at))
);

CREATE TABLE IF NOT EXISTS ug_support.ticket_events (
 event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ticket_id BIGINT NOT NULL REFERENCES ug_support.tickets(ticket_id) ON DELETE RESTRICT,
 event_type TEXT NOT NULL CHECK (event_type IN ('opened','assigned','first_response','status_changed','customer_reply','internal_note','escalated','resolved','closed','reopened','corrected')),
 from_status TEXT,
 to_status TEXT,
 actor_ref TEXT NOT NULL CHECK (length(btrim(actor_ref))>0),
 note_redacted TEXT NOT NULL CHECK (length(btrim(note_redacted))>0),
 evidence_ref TEXT,
 occurred_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS ug_support.sla_pauses (
 pause_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ticket_id BIGINT NOT NULL REFERENCES ug_support.tickets(ticket_id) ON DELETE RESTRICT,
 pause_reason TEXT NOT NULL CHECK (pause_reason IN ('waiting_customer','waiting_third_party','approved_maintenance')),
 started_at TIMESTAMPTZ NOT NULL,
 ended_at TIMESTAMPTZ,
 approved_by_ref TEXT NOT NULL CHECK (length(btrim(approved_by_ref))>0),
 evidence_ref TEXT NOT NULL CHECK (length(btrim(evidence_ref))>0),
 CHECK (ended_at IS NULL OR ended_at>=started_at)
);

CREATE INDEX IF NOT EXISTS ix_support_queue_status ON ug_support.tickets(queue_id,status,priority,opened_at);
CREATE INDEX IF NOT EXISTS ix_support_ticket_events ON ug_support.ticket_events(ticket_id,occurred_at DESC,event_id DESC);
CREATE INDEX IF NOT EXISTS ix_support_opened_at ON ug_support.tickets(opened_at,status);

COMMENT ON SCHEMA ug_support IS 'Synthetic support SLA workflow; not a customer identity or payment system.';
