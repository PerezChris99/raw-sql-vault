-- Purpose: synthetic hospitality room/table booking and stock-consumption reference workflow.
-- Engine: PostgreSQL 15+. No payment-card data, guest identity documents or sensitive travel details.
CREATE SCHEMA IF NOT EXISTS ug_hospitality;

CREATE TABLE IF NOT EXISTS ug_hospitality.properties (
 property_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 property_ref TEXT NOT NULL UNIQUE CHECK (property_ref ~ '^UGHOT-[A-Z0-9-]{3,40}$'),
 property_name TEXT NOT NULL CHECK (length(btrim(property_name))>0),
 locality_ref TEXT NOT NULL CHECK (length(btrim(locality_ref))>0),
 property_type TEXT NOT NULL CHECK (property_type IN ('hotel','guesthouse','restaurant','cafe','lodge','other')),
 status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','suspended','retired'))
);

CREATE TABLE IF NOT EXISTS ug_hospitality.resources (
 resource_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 property_id BIGINT NOT NULL REFERENCES ug_hospitality.properties(property_id) ON DELETE RESTRICT,
 resource_ref TEXT NOT NULL UNIQUE CHECK (resource_ref ~ '^UGHRES-[A-Z0-9-]{3,40}$'),
 resource_type TEXT NOT NULL CHECK (resource_type IN ('room','table','event_space','service_slot')),
 capacity INTEGER NOT NULL CHECK (capacity>0),
 status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','out_of_service','retired')),
 UNIQUE(property_id,resource_ref)
);

CREATE TABLE IF NOT EXISTS ug_hospitality.reservations (
 reservation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 reservation_ref TEXT NOT NULL UNIQUE CHECK (reservation_ref ~ '^UGHBOOK-[A-Z0-9-]{3,40}$'),
 idempotency_key TEXT NOT NULL UNIQUE CHECK (length(btrim(idempotency_key)) BETWEEN 8 AND 128),
 resource_id BIGINT NOT NULL REFERENCES ug_hospitality.resources(resource_id) ON DELETE RESTRICT,
 customer_token TEXT NOT NULL CHECK (length(btrim(customer_token))>0),
 starts_at TIMESTAMPTZ NOT NULL,
 ends_at TIMESTAMPTZ NOT NULL,
 party_size INTEGER NOT NULL CHECK (party_size>0),
 status TEXT NOT NULL DEFAULT 'confirmed' CHECK (status IN ('requested','confirmed','checked_in','completed','cancelled','no_show')),
 source_ref TEXT NOT NULL CHECK (length(btrim(source_ref))>0),
 recorded_by_ref TEXT NOT NULL CHECK (length(btrim(recorded_by_ref))>0),
 cancellation_reason TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK (ends_at>starts_at),
 CHECK (status<>'cancelled' OR length(btrim(COALESCE(cancellation_reason,'')))>0)
);

CREATE TABLE IF NOT EXISTS ug_hospitality.inventory_items (
 item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 property_id BIGINT NOT NULL REFERENCES ug_hospitality.properties(property_id) ON DELETE RESTRICT,
 item_ref TEXT NOT NULL UNIQUE CHECK (item_ref ~ '^UGHITEM-[A-Z0-9-]{3,40}$'),
 item_name TEXT NOT NULL CHECK (length(btrim(item_name))>0),
 unit_code TEXT NOT NULL CHECK (length(btrim(unit_code))>0),
 reorder_level NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK (reorder_level>=0),
 is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS ug_hospitality.stock_movements (
 movement_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 movement_ref TEXT NOT NULL UNIQUE CHECK (movement_ref ~ '^UGHSTK-[A-Z0-9-]{3,40}$'),
 idempotency_key TEXT NOT NULL UNIQUE CHECK (length(btrim(idempotency_key)) BETWEEN 8 AND 128),
 item_id BIGINT NOT NULL REFERENCES ug_hospitality.inventory_items(item_id) ON DELETE RESTRICT,
 quantity_delta NUMERIC(14,3) NOT NULL CHECK (quantity_delta<>0),
 movement_type TEXT NOT NULL CHECK (movement_type IN ('opening','receipt','order_consumption','waste','return','correction')),
 source_ref TEXT NOT NULL CHECK (length(btrim(source_ref))>0),
 reason TEXT NOT NULL CHECK (length(btrim(reason))>0),
 recorded_by_ref TEXT NOT NULL CHECK (length(btrim(recorded_by_ref))>0),
 occurred_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS ug_hospitality.orders (
 order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_ref TEXT NOT NULL UNIQUE CHECK (order_ref ~ '^UGHORD-[A-Z0-9-]{3,40}$'),
 idempotency_key TEXT NOT NULL UNIQUE CHECK (length(btrim(idempotency_key)) BETWEEN 8 AND 128),
 property_id BIGINT NOT NULL REFERENCES ug_hospitality.properties(property_id) ON DELETE RESTRICT,
 reservation_id BIGINT REFERENCES ug_hospitality.reservations(reservation_id) ON DELETE RESTRICT,
 order_status TEXT NOT NULL DEFAULT 'open' CHECK (order_status IN ('open','fulfilled','cancelled')),
 recorded_by_ref TEXT NOT NULL CHECK (length(btrim(recorded_by_ref))>0),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS ug_hospitality.order_lines (
 order_line_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id BIGINT NOT NULL REFERENCES ug_hospitality.orders(order_id) ON DELETE RESTRICT,
 line_no INTEGER NOT NULL CHECK (line_no>0),
 item_id BIGINT NOT NULL REFERENCES ug_hospitality.inventory_items(item_id) ON DELETE RESTRICT,
 quantity NUMERIC(14,3) NOT NULL CHECK (quantity>0),
 unit_price NUMERIC(14,2) NOT NULL CHECK (unit_price>=0),
 UNIQUE(order_id,line_no)
);

CREATE INDEX IF NOT EXISTS ix_hospitality_reservation_resource ON ug_hospitality.reservations(resource_id,starts_at,ends_at,status);
CREATE INDEX IF NOT EXISTS ix_hospitality_stock_balance ON ug_hospitality.stock_movements(item_id,occurred_at,movement_id);
CREATE INDEX IF NOT EXISTS ix_hospitality_orders_status ON ug_hospitality.orders(property_id,order_status,created_at);

COMMENT ON SCHEMA ug_hospitality IS 'Synthetic hospitality booking and stock example; no payment processing.';
