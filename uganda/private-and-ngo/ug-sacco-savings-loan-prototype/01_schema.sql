-- Purpose: synthetic SACCO member-token, savings transaction and human-reviewed loan ledger prototype.
-- Engine: PostgreSQL 15+. High-risk financial teaching model; no real member identity or money movement.
CREATE SCHEMA IF NOT EXISTS ug_sacco;

CREATE TABLE IF NOT EXISTS ug_sacco.members (
 member_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 member_token TEXT NOT NULL UNIQUE CHECK (member_token ~ '^SYN-SACCO-[A-Z0-9-]{3,40}$'),
 joining_source_ref TEXT NOT NULL CHECK (length(btrim(joining_source_ref))>0),
 consent_or_authority_ref TEXT NOT NULL CHECK (length(btrim(consent_or_authority_ref))>0),
 status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','suspended','exited')),
 joined_on DATE NOT NULL,
 exited_on DATE,
 CHECK (exited_on IS NULL OR exited_on>=joined_on)
);

CREATE TABLE IF NOT EXISTS ug_sacco.savings_accounts (
 savings_account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 account_ref TEXT NOT NULL UNIQUE CHECK (account_ref ~ '^UGSAC-SAV-[A-Z0-9-]{3,40}$'),
 member_id BIGINT NOT NULL REFERENCES ug_sacco.members(member_id) ON DELETE RESTRICT,
 product_code TEXT NOT NULL CHECK (length(btrim(product_code))>0),
 currency_code CHAR(3) NOT NULL DEFAULT 'UGX' CHECK (currency_code ~ '^[A-Z]{3}$'),
 opened_on DATE NOT NULL,
 status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open','frozen','closed')),
 UNIQUE(member_id,product_code)
);

CREATE TABLE IF NOT EXISTS ug_sacco.savings_transactions (
 savings_txn_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 txn_ref TEXT NOT NULL UNIQUE CHECK (txn_ref ~ '^UGSAC-ST-[A-Z0-9-]{3,40}$'),
 idempotency_key TEXT NOT NULL UNIQUE CHECK (length(btrim(idempotency_key)) BETWEEN 8 AND 128),
 savings_account_id BIGINT NOT NULL REFERENCES ug_sacco.savings_accounts(savings_account_id) ON DELETE RESTRICT,
 txn_type TEXT NOT NULL CHECK (txn_type IN ('deposit','withdrawal','correction_credit','correction_debit')),
 amount NUMERIC(16,2) NOT NULL CHECK (amount>0),
 external_reference TEXT NOT NULL UNIQUE CHECK (length(btrim(external_reference))>0),
 occurred_at TIMESTAMPTZ NOT NULL,
 recorded_by_ref TEXT NOT NULL CHECK (length(btrim(recorded_by_ref))>0),
 evidence_ref TEXT NOT NULL CHECK (length(btrim(evidence_ref))>0)
);

CREATE TABLE IF NOT EXISTS ug_sacco.loan_applications (
 application_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 application_ref TEXT NOT NULL UNIQUE CHECK (application_ref ~ '^UGSAC-LA-[A-Z0-9-]{3,40}$'),
 member_id BIGINT NOT NULL REFERENCES ug_sacco.members(member_id) ON DELETE RESTRICT,
 product_code TEXT NOT NULL CHECK (length(btrim(product_code))>0),
 requested_amount NUMERIC(16,2) NOT NULL CHECK (requested_amount>0),
 purpose_redacted TEXT NOT NULL CHECK (length(btrim(purpose_redacted))>0),
 status TEXT NOT NULL DEFAULT 'submitted' CHECK (status IN ('submitted','under_review','approved','rejected','withdrawn')),
 decided_amount NUMERIC(16,2),
 decision_by_ref TEXT,
 decision_reason_redacted TEXT,
 decision_evidence_ref TEXT,
 decided_at TIMESTAMPTZ,
 submitted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK (decided_amount IS NULL OR decided_amount>0),
 CHECK ((status IN ('approved','rejected'))=(decided_at IS NOT NULL)),
 CHECK ((decided_at IS NULL AND decision_by_ref IS NULL AND decision_reason_redacted IS NULL AND decision_evidence_ref IS NULL)
    OR (decided_at IS NOT NULL AND length(btrim(COALESCE(decision_by_ref,'')))>0
        AND length(btrim(COALESCE(decision_reason_redacted,'')))>0 AND length(btrim(COALESCE(decision_evidence_ref,'')))>0))
);

CREATE TABLE IF NOT EXISTS ug_sacco.loans (
 loan_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 loan_ref TEXT NOT NULL UNIQUE CHECK (loan_ref ~ '^UGSAC-LOAN-[A-Z0-9-]{3,40}$'),
 application_id BIGINT NOT NULL UNIQUE REFERENCES ug_sacco.loan_applications(application_id) ON DELETE RESTRICT,
 member_id BIGINT NOT NULL REFERENCES ug_sacco.members(member_id) ON DELETE RESTRICT,
 approved_principal NUMERIC(16,2) NOT NULL CHECK (approved_principal>0),
 currency_code CHAR(3) NOT NULL DEFAULT 'UGX' CHECK (currency_code ~ '^[A-Z]{3}$'),
 disbursed_at TIMESTAMPTZ,
 disbursement_reference TEXT UNIQUE,
 status TEXT NOT NULL DEFAULT 'approved' CHECK (status IN ('approved','active','settled','default_review','written_off')),
 CHECK ((disbursed_at IS NULL AND disbursement_reference IS NULL) OR (disbursed_at IS NOT NULL AND length(btrim(disbursement_reference))>0))
);

CREATE TABLE IF NOT EXISTS ug_sacco.loan_transactions (
 loan_txn_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 txn_ref TEXT NOT NULL UNIQUE CHECK (txn_ref ~ '^UGSAC-LT-[A-Z0-9-]{3,40}$'),
 idempotency_key TEXT NOT NULL UNIQUE CHECK (length(btrim(idempotency_key)) BETWEEN 8 AND 128),
 loan_id BIGINT NOT NULL REFERENCES ug_sacco.loans(loan_id) ON DELETE RESTRICT,
 txn_type TEXT NOT NULL CHECK (txn_type IN ('disbursement','repayment','principal_correction_credit','principal_correction_debit')),
 amount NUMERIC(16,2) NOT NULL CHECK (amount>0),
 external_reference TEXT NOT NULL UNIQUE CHECK (length(btrim(external_reference))>0),
 occurred_at TIMESTAMPTZ NOT NULL,
 recorded_by_ref TEXT NOT NULL CHECK (length(btrim(recorded_by_ref))>0),
 evidence_ref TEXT NOT NULL CHECK (length(btrim(evidence_ref))>0)
);

CREATE INDEX IF NOT EXISTS ix_sacco_savings_txn_account ON ug_sacco.savings_transactions(savings_account_id,occurred_at,savings_txn_id);
CREATE INDEX IF NOT EXISTS ix_sacco_loan_application_queue ON ug_sacco.loan_applications(status,submitted_at);
CREATE INDEX IF NOT EXISTS ix_sacco_loan_txn_ledger ON ug_sacco.loan_transactions(loan_id,occurred_at,loan_txn_id);

COMMENT ON SCHEMA ug_sacco IS 'Synthetic SACCO financial ledger prototype; not production lending, accounting or payment software.';
COMMENT ON COLUMN ug_sacco.members.member_token IS 'Pseudonymous token only; no name, national ID, phone or address is stored.';
