-- Purpose: local-government service request schema with effective locality references.
-- Engine: PostgreSQL 15+; no extensions required.
-- Rerun safety: CREATE IF NOT EXISTS and CREATE OR REPLACE; no destructive reset.
-- Sample locality codes are synthetic and must not be used as official boundary identifiers.

CREATE SCHEMA IF NOT EXISTS service_demo;

CREATE TABLE IF NOT EXISTS service_demo.localities (
    locality_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    locality_code TEXT NOT NULL UNIQUE,
    locality_name TEXT NOT NULL,
    locality_type TEXT NOT NULL CHECK (
        locality_type IN ('district', 'city', 'municipality', 'division', 'subcounty', 'parish', 'village', 'ward')
    ),
    parent_locality_id BIGINT REFERENCES service_demo.localities(locality_id) ON DELETE RESTRICT,
    valid_from DATE NOT NULL DEFAULT CURRENT_DATE,
    valid_to DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (valid_to IS NULL OR valid_to >= valid_from)
);

CREATE TABLE IF NOT EXISTS service_demo.service_requests (
    request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_ref TEXT NOT NULL UNIQUE,
    request_type TEXT NOT NULL CHECK (
        request_type IN ('drainage', 'road_defect', 'waste', 'streetlight', 'water_point', 'other')
    ),
    description TEXT NOT NULL CHECK (length(btrim(description)) > 0),
    locality_id BIGINT NOT NULL REFERENCES service_demo.localities(locality_id) ON DELETE RESTRICT,
    priority SMALLINT NOT NULL DEFAULT 3 CHECK (priority BETWEEN 1 AND 5),
    status TEXT NOT NULL DEFAULT 'new'
        CHECK (status IN ('new', 'triaged', 'in_progress', 'blocked', 'resolved', 'cancelled')),
    reporter_ref TEXT,
    due_at TIMESTAMPTZ,
    resolved_at TIMESTAMPTZ,
    created_by_ref TEXT NOT NULL DEFAULT 'demo-intake',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    CHECK (status <> 'resolved' OR resolved_at IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS ix_service_requests_locality
    ON service_demo.service_requests(locality_id);
CREATE INDEX IF NOT EXISTS ix_service_requests_status_due
    ON service_demo.service_requests(status, due_at)
    WHERE is_deleted = FALSE;
CREATE INDEX IF NOT EXISTS ix_service_requests_created_at
    ON service_demo.service_requests(created_at DESC);

CREATE TABLE IF NOT EXISTS service_demo.request_events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL REFERENCES service_demo.service_requests(request_id) ON DELETE RESTRICT,
    previous_status TEXT,
    new_status TEXT NOT NULL CHECK (
        new_status IN ('new', 'triaged', 'in_progress', 'blocked', 'resolved', 'cancelled')
    ),
    event_note TEXT NOT NULL,
    actor_ref TEXT NOT NULL,
    happened_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_request_events_request_time
    ON service_demo.request_events(request_id, happened_at DESC);

CREATE OR REPLACE FUNCTION service_demo.fn_set_updated_at()
RETURNS TRIGGER LANGUAGE plpgsql SET search_path = pg_catalog, service_demo
AS $function$
BEGIN
    NEW.updated_at := clock_timestamp();
    RETURN NEW;
END;
$function$;

DROP TRIGGER IF EXISTS trg_service_requests_updated_at ON service_demo.service_requests;
CREATE TRIGGER trg_service_requests_updated_at
BEFORE UPDATE ON service_demo.service_requests
FOR EACH ROW EXECUTE FUNCTION service_demo.fn_set_updated_at();

COMMENT ON TABLE service_demo.service_requests IS
    'Synthetic service issues; description must not contain real personal or sensitive details.';
COMMENT ON TABLE service_demo.request_events IS
    'Workflow status change history for synthetic service requests.';