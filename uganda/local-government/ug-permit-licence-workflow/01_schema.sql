-- Purpose: auditable, human-reviewed permit/licence application workflow.
-- Engine: PostgreSQL 15+. Prerequisites: none. Rerunnable: yes; additive.
CREATE SCHEMA IF NOT EXISTS ug_permit;

CREATE TABLE IF NOT EXISTS ug_permit.permit_types (
    permit_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_code TEXT NOT NULL UNIQUE CHECK (type_code ~ '^[A-Z0-9][A-Z0-9_-]{1,47}$'),
    type_name TEXT NOT NULL CHECK (length(btrim(type_name)) > 0),
    issuing_office_code TEXT NOT NULL CHECK (length(btrim(issuing_office_code)) > 0),
    validity_days INTEGER CHECK (validity_days IS NULL OR validity_days > 0),
    fee_amount NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (fee_amount >= 0),
    currency_code CHAR(3) NOT NULL DEFAULT 'UGX' CHECK (currency_code ~ '^[A-Z]{3}$'),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS ug_permit.applications (
    application_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_ref TEXT NOT NULL UNIQUE CHECK (application_ref ~ '^UGP-[A-Z0-9-]{4,40}$'),
    permit_type_id BIGINT NOT NULL REFERENCES ug_permit.permit_types(permit_type_id) ON DELETE RESTRICT,
    applicant_ref TEXT NOT NULL CHECK (length(btrim(applicant_ref)) BETWEEN 3 AND 128),
    locality_code TEXT,
    status TEXT NOT NULL DEFAULT 'draft'
      CHECK (status IN ('draft','submitted','under_review','awaiting_documents','approved','rejected','withdrawn','expired')),
    submitted_at TIMESTAMPTZ,
    decision_at TIMESTAMPTZ,
    expires_on DATE,
    created_by TEXT NOT NULL CHECK (length(btrim(created_by)) > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK ((status NOT IN ('approved','rejected')) OR decision_at IS NOT NULL),
    CHECK (expires_on IS NULL OR status='approved' OR status='expired')
);

CREATE TABLE IF NOT EXISTS ug_permit.application_events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL REFERENCES ug_permit.applications(application_id) ON DELETE RESTRICT,
    event_type TEXT NOT NULL CHECK (event_type IN ('created','submitted','assigned_for_review','requested_documents','documents_received','approved','rejected','withdrawn','expired','corrected')),
    from_status TEXT CHECK (from_status IS NULL OR from_status IN ('draft','submitted','under_review','awaiting_documents','approved','rejected','withdrawn','expired')),
    to_status TEXT NOT NULL CHECK (to_status IN ('draft','submitted','under_review','awaiting_documents','approved','rejected','withdrawn','expired')),
    actor_ref TEXT NOT NULL CHECK (length(btrim(actor_ref)) > 0),
    reason TEXT NOT NULL CHECK (length(btrim(reason)) > 0),
    evidence_ref TEXT,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS ug_permit.application_documents (
    document_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL REFERENCES ug_permit.applications(application_id) ON DELETE RESTRICT,
    document_type TEXT NOT NULL CHECK (length(btrim(document_type)) > 0),
    object_ref TEXT NOT NULL CHECK (length(btrim(object_ref)) > 0),
    sha256_hex TEXT NOT NULL CHECK (sha256_hex ~ '^[0-9a-f]{64}$'),
    uploaded_by TEXT NOT NULL CHECK (length(btrim(uploaded_by)) > 0),
    classification TEXT NOT NULL DEFAULT 'restricted'
      CHECK (classification IN ('public','internal','restricted','highly_restricted')),
    received_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    supersedes_document_id BIGINT REFERENCES ug_permit.application_documents(document_id) ON DELETE RESTRICT,
    UNIQUE(application_id,document_type,sha256_hex)
);

CREATE TABLE IF NOT EXISTS ug_permit.fee_events (
    fee_event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL REFERENCES ug_permit.applications(application_id) ON DELETE RESTRICT,
    event_kind TEXT NOT NULL CHECK (event_kind IN ('assessed','payment_recorded','waived','reversed','refunded','adjusted')),
    amount NUMERIC(14,2) NOT NULL CHECK (amount >= 0),
    currency_code CHAR(3) NOT NULL CHECK (currency_code ~ '^[A-Z]{3}$'),
    external_reference TEXT,
    reason TEXT NOT NULL CHECK (length(btrim(reason)) > 0),
    recorded_by TEXT NOT NULL CHECK (length(btrim(recorded_by)) > 0),
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_permit_applications_queue
    ON ug_permit.applications(status,created_at,application_id);
CREATE INDEX IF NOT EXISTS ix_permit_applications_type_created
    ON ug_permit.applications(permit_type_id,created_at DESC);
CREATE INDEX IF NOT EXISTS ix_permit_events_history
    ON ug_permit.application_events(application_id,occurred_at DESC,event_id DESC);
CREATE INDEX IF NOT EXISTS ix_permit_documents_app
    ON ug_permit.application_documents(application_id,received_at DESC);
CREATE INDEX IF NOT EXISTS ix_permit_fee_events_app
    ON ug_permit.fee_events(application_id,recorded_at DESC,fee_event_id DESC);

COMMENT ON SCHEMA ug_permit IS 'Synthetic permit/licence workflow example; no real applicant personal data.';
COMMENT ON COLUMN ug_permit.applications.applicant_ref IS 'Opaque external reference only; do not store names, national IDs, phone numbers or addresses here.';
COMMENT ON COLUMN ug_permit.application_documents.object_ref IS 'Pointer to an access-controlled document store; document bytes are not stored in this schema.';
