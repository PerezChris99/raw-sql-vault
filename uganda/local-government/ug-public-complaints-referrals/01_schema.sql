-- Purpose: confidential complaints and referral workflow with event history.
-- Engine: PostgreSQL 15+. Prerequisites: none. Rerunnable: yes; additive.
CREATE SCHEMA IF NOT EXISTS ug_public_case;

CREATE TABLE IF NOT EXISTS ug_public_case.case_categories (
 category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 category_code TEXT NOT NULL UNIQUE CHECK (category_code ~ '^[A-Z0-9_-]{3,48}$'),
 category_name TEXT NOT NULL CHECK (length(btrim(category_name))>0),
 default_sla_hours INTEGER NOT NULL CHECK (default_sla_hours BETWEEN 1 AND 8760),
 confidentiality TEXT NOT NULL DEFAULT 'restricted' CHECK (confidentiality IN ('internal','restricted','highly_restricted')),
 is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS ug_public_case.cases (
 case_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 case_ref TEXT NOT NULL UNIQUE CHECK (case_ref ~ '^UGCASE-[A-Z0-9-]{4,40}$'),
 idempotency_key TEXT NOT NULL UNIQUE CHECK (length(btrim(idempotency_key)) BETWEEN 8 AND 128),
 category_id BIGINT NOT NULL REFERENCES ug_public_case.case_categories(category_id) ON DELETE RESTRICT,
 received_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 channel TEXT NOT NULL CHECK (channel IN ('in_person','telephone','web_form','letter','authorised_referral')),
 complainant_ref TEXT,
 locality_ref TEXT,
 severity TEXT NOT NULL DEFAULT 'normal' CHECK (severity IN ('low','normal','high','urgent')),
 status TEXT NOT NULL DEFAULT 'received' CHECK (status IN ('received','triaged','assigned','referred','awaiting_response','resolved','closed','withdrawn')),
 assigned_team_ref TEXT,
 due_at TIMESTAMPTZ NOT NULL,
 confidentiality TEXT NOT NULL DEFAULT 'restricted' CHECK (confidentiality IN ('internal','restricted','highly_restricted')),
 created_by TEXT NOT NULL CHECK (length(btrim(created_by))>0),
 closed_at TIMESTAMPTZ,
 closure_reason TEXT,
 CHECK ((status IN ('closed','withdrawn')) = (closed_at IS NOT NULL)),
 CHECK ((closed_at IS NULL AND closure_reason IS NULL)
    OR (closed_at IS NOT NULL AND length(btrim(COALESCE(closure_reason,'')))>0)),
 CHECK (complainant_ref IS NULL OR length(btrim(complainant_ref)) BETWEEN 3 AND 96),
 CHECK (locality_ref IS NULL OR length(btrim(locality_ref)) BETWEEN 3 AND 96)
);

CREATE TABLE IF NOT EXISTS ug_public_case.case_events (
 event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 case_id BIGINT NOT NULL REFERENCES ug_public_case.cases(case_id) ON DELETE RESTRICT,
 event_type TEXT NOT NULL CHECK (event_type IN ('received','triaged','assigned','referred','awaiting_response','response_received','resolved','closed','withdrawn','reopened','corrected')),
 from_status TEXT,
 to_status TEXT NOT NULL CHECK (to_status IN ('received','triaged','assigned','referred','awaiting_response','resolved','closed','withdrawn')),
 actor_ref TEXT NOT NULL CHECK (length(btrim(actor_ref))>0),
 reason TEXT NOT NULL CHECK (length(btrim(reason))>0),
 evidence_reference TEXT,
 occurred_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS ug_public_case.referrals (
 referral_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 referral_ref TEXT NOT NULL UNIQUE CHECK (referral_ref ~ '^UGREF-[A-Z0-9-]{4,40}$'),
 case_id BIGINT NOT NULL REFERENCES ug_public_case.cases(case_id) ON DELETE RESTRICT,
 receiving_office_ref TEXT NOT NULL CHECK (length(btrim(receiving_office_ref))>0),
 referral_reason TEXT NOT NULL CHECK (length(btrim(referral_reason))>0),
 source_evidence_ref TEXT NOT NULL CHECK (length(btrim(source_evidence_ref))>0),
 status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','accepted','declined','response_received','closed')),
 sent_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 due_at TIMESTAMPTZ NOT NULL,
 response_evidence_ref TEXT,
 responded_at TIMESTAMPTZ,
 recorded_by TEXT NOT NULL CHECK (length(btrim(recorded_by))>0),
 CHECK ((status IN ('response_received','closed')) = (responded_at IS NOT NULL)),
 CHECK ((responded_at IS NULL AND response_evidence_ref IS NULL)
    OR (responded_at IS NOT NULL AND length(btrim(COALESCE(response_evidence_ref,'')))>0))
);

CREATE INDEX IF NOT EXISTS ix_public_case_queue ON ug_public_case.cases(status,severity,due_at,case_id);
CREATE INDEX IF NOT EXISTS ix_public_case_received ON ug_public_case.cases(received_at DESC,category_id);
CREATE INDEX IF NOT EXISTS ix_public_case_events ON ug_public_case.case_events(case_id,occurred_at DESC,event_id DESC);
CREATE INDEX IF NOT EXISTS ix_public_case_referrals ON ug_public_case.referrals(status,due_at,case_id);

COMMENT ON SCHEMA ug_public_case IS 'Synthetic confidential complaint/referral metadata; do not store complaint narratives or identity details.';
COMMENT ON COLUMN ug_public_case.cases.complainant_ref IS 'Opaque case-management token only; do not store name, national ID, phone, address or narrative here.';
COMMENT ON COLUMN ug_public_case.referrals.source_evidence_ref IS 'Reference to separately secured evidence store, not document contents.';
