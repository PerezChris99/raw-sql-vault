-- Purpose: effective-dated Uganda administrative geography reference model.
-- Engine: PostgreSQL 15+. Prerequisites: none. Rerunnable: yes; non-destructive.
CREATE SCHEMA IF NOT EXISTS ug_admin_ref;

CREATE TABLE IF NOT EXISTS ug_admin_ref.allowed_parent_levels (
    child_level TEXT NOT NULL,
    parent_level TEXT NOT NULL,
    PRIMARY KEY (child_level, parent_level),
    CHECK (child_level IN ('district','city','county','municipality','town_council','sub_county','division','parish','ward','village','cell')),
    CHECK (parent_level = 'ROOT' OR parent_level IN ('district','city','county','municipality','town_council','sub_county','division','parish','ward','village','cell'))
);

INSERT INTO ug_admin_ref.allowed_parent_levels(child_level,parent_level) VALUES
 ('district','ROOT'),('city','ROOT'),
 ('county','district'),('municipality','district'),('municipality','city'),('town_council','district'),('town_council','county'),('town_council','sub_county'),
 ('sub_county','district'),('sub_county','county'),('division','city'),('division','municipality'),
 ('parish','sub_county'),('parish','town_council'),('parish','municipality'),('ward','division'),('ward','municipality'),('ward','city'),
 ('village','parish'),('cell','ward'),('cell','parish')
ON CONFLICT DO NOTHING;

CREATE TABLE IF NOT EXISTS ug_admin_ref.admin_units (
    admin_unit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_code TEXT NOT NULL UNIQUE,
    unit_name TEXT NOT NULL CHECK (length(btrim(unit_name)) > 0),
    unit_level TEXT NOT NULL CHECK (unit_level IN ('district','city','county','municipality','town_council','sub_county','division','parish','ward','village','cell')),
    parent_admin_unit_id BIGINT REFERENCES ug_admin_ref.admin_units(admin_unit_id) ON DELETE RESTRICT,
    valid_from DATE NOT NULL,
    valid_to DATE,
    source_reference TEXT NOT NULL,
    is_verified BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (valid_to IS NULL OR valid_to >= valid_from),
    CHECK (unit_code = upper(unit_code) AND unit_code ~ '^[A-Z0-9][A-Z0-9_-]{1,63}$')
);
CREATE INDEX IF NOT EXISTS ix_admin_units_parent_level ON ug_admin_ref.admin_units(parent_admin_unit_id,unit_level);
CREATE INDEX IF NOT EXISTS ix_admin_units_current_name ON ug_admin_ref.admin_units(lower(unit_name)) WHERE valid_to IS NULL;
CREATE INDEX IF NOT EXISTS ix_admin_units_validity ON ug_admin_ref.admin_units(valid_from,valid_to);

CREATE OR REPLACE FUNCTION ug_admin_ref.fn_validate_admin_unit_parent()
RETURNS TRIGGER LANGUAGE plpgsql
SET search_path = pg_catalog, ug_admin_ref
AS $$
DECLARE v_parent_level TEXT;
BEGIN
    IF NEW.parent_admin_unit_id IS NULL THEN
        IF NOT EXISTS (
            SELECT 1 FROM ug_admin_ref.allowed_parent_levels r
            WHERE r.child_level = NEW.unit_level AND r.parent_level = 'ROOT'
        ) THEN
            RAISE EXCEPTION 'Administrative level % requires a parent', NEW.unit_level
                USING ERRCODE = 'check_violation';
        END IF;
    ELSE
        IF NEW.parent_admin_unit_id = NEW.admin_unit_id THEN
            RAISE EXCEPTION 'Administrative unit cannot be its own parent'
                USING ERRCODE = 'check_violation';
        END IF;
        SELECT p.unit_level INTO v_parent_level
        FROM ug_admin_ref.admin_units p
        WHERE p.admin_unit_id = NEW.parent_admin_unit_id
          AND p.valid_to IS NULL;
        IF v_parent_level IS NULL THEN
            RAISE EXCEPTION 'Parent must exist and be current' USING ERRCODE = 'foreign_key_violation';
        END IF;
        IF NOT EXISTS (
            SELECT 1 FROM ug_admin_ref.allowed_parent_levels r
            WHERE r.child_level = NEW.unit_level AND r.parent_level = v_parent_level
        ) THEN
            RAISE EXCEPTION 'Invalid administrative hierarchy: % cannot be child of %',
                NEW.unit_level, v_parent_level USING ERRCODE = 'check_violation';
        END IF;
    END IF;
    NEW.updated_at := clock_timestamp();
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_admin_units_validate_parent ON ug_admin_ref.admin_units;
CREATE TRIGGER trg_admin_units_validate_parent
BEFORE INSERT OR UPDATE OF unit_level,parent_admin_unit_id,unit_code,valid_to
ON ug_admin_ref.admin_units
FOR EACH ROW EXECUTE FUNCTION ug_admin_ref.fn_validate_admin_unit_parent();

CREATE TABLE IF NOT EXISTS ug_admin_ref.admin_unit_changes (
    change_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_unit_id BIGINT NOT NULL REFERENCES ug_admin_ref.admin_units(admin_unit_id) ON DELETE RESTRICT,
    change_kind TEXT NOT NULL CHECK (change_kind IN ('created','renamed','reparented','level_changed','retired','corrected')),
    old_values JSONB,
    new_values JSONB NOT NULL,
    change_reason TEXT NOT NULL CHECK (length(btrim(change_reason)) > 0),
    source_reference TEXT NOT NULL,
    recorded_by TEXT NOT NULL,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_admin_unit_changes_history ON ug_admin_ref.admin_unit_changes(admin_unit_id,recorded_at DESC,change_id DESC);

COMMENT ON SCHEMA ug_admin_ref IS 'Reference-only administrative geography; verify records with authoritative sources before operational use.';
COMMENT ON TABLE ug_admin_ref.admin_units IS 'Synthetic/effective-dated hierarchy; codes are stable internal keys, not asserted official codes.';
COMMENT ON COLUMN ug_admin_ref.admin_units.is_verified IS 'True only after an authorised reviewer confirms the record against an authoritative source.';
