-- Purpose: synthetic municipal waste route, shift, stop, pickup and missed-service monitoring.
-- Engine: PostgreSQL 15+. Use locality and route tokens; do not expose household-level location patterns.
CREATE SCHEMA IF NOT EXISTS ug_waste;

CREATE TABLE IF NOT EXISTS ug_waste.service_areas (
 area_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 area_ref TEXT NOT NULL UNIQUE CHECK (area_ref ~ '^UGWA-[A-Z0-9-]{3,40}$'),
 locality_ref TEXT NOT NULL CHECK (length(btrim(locality_ref))>0),
 area_name TEXT NOT NULL CHECK (length(btrim(area_name))>0),
 is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS ug_waste.routes (
 route_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 route_ref TEXT NOT NULL UNIQUE CHECK (route_ref ~ '^UGWR-[A-Z0-9-]{3,40}$'),
 area_id BIGINT NOT NULL REFERENCES ug_waste.service_areas(area_id) ON DELETE RESTRICT,
 route_name TEXT NOT NULL CHECK (length(btrim(route_name))>0),
 route_type TEXT NOT NULL CHECK (route_type IN ('residential','commercial','market','institutional','mixed')),
 planned_minutes INTEGER NOT NULL CHECK (planned_minutes BETWEEN 5 AND 1440),
 is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS ug_waste.route_stops (
 stop_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 route_id BIGINT NOT NULL REFERENCES ug_waste.routes(route_id) ON DELETE RESTRICT,
 stop_ref TEXT NOT NULL UNIQUE CHECK (stop_ref ~ '^UGWS-[A-Z0-9-]{3,40}$'),
 sequence_no INTEGER NOT NULL CHECK (sequence_no>0),
 locality_ref TEXT NOT NULL CHECK (length(btrim(locality_ref))>0),
 service_point_token TEXT NOT NULL CHECK (length(btrim(service_point_token))>0),
 planned_duration_minutes INTEGER NOT NULL DEFAULT 10 CHECK (planned_duration_minutes BETWEEN 1 AND 240),
 UNIQUE(route_id,sequence_no)
);

CREATE TABLE IF NOT EXISTS ug_waste.shifts (
 shift_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 shift_ref TEXT NOT NULL UNIQUE CHECK (shift_ref ~ '^UGW-SH-[A-Z0-9-]{3,40}$'),
 route_id BIGINT NOT NULL REFERENCES ug_waste.routes(route_id) ON DELETE RESTRICT,
 vehicle_ref TEXT NOT NULL CHECK (length(btrim(vehicle_ref))>0),
 crew_ref TEXT NOT NULL CHECK (length(btrim(crew_ref))>0),
 planned_start TIMESTAMPTZ NOT NULL,
 planned_end TIMESTAMPTZ NOT NULL,
 actual_start TIMESTAMPTZ,
 actual_end TIMESTAMPTZ,
 status TEXT NOT NULL DEFAULT 'planned' CHECK (status IN ('planned','active','completed','cancelled')),
 CHECK(planned_end>planned_start),
 CHECK(actual_end IS NULL OR (actual_start IS NOT NULL AND actual_end>=actual_start))
);

CREATE TABLE IF NOT EXISTS ug_waste.pickup_events (
 pickup_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 pickup_ref TEXT NOT NULL UNIQUE CHECK (pickup_ref ~ '^UGW-PU-[A-Z0-9-]{3,40}$'),
 idempotency_key TEXT NOT NULL UNIQUE CHECK (length(btrim(idempotency_key)) BETWEEN 8 AND 128),
 shift_id BIGINT NOT NULL REFERENCES ug_waste.shifts(shift_id) ON DELETE RESTRICT,
 stop_id BIGINT NOT NULL REFERENCES ug_waste.route_stops(stop_id) ON DELETE RESTRICT,
 outcome TEXT NOT NULL CHECK (outcome IN ('collected','partial','missed','blocked','unsafe_to_collect')),
 volume_estimate NUMERIC(12,3) CHECK (volume_estimate IS NULL OR volume_estimate>=0),
 unit_code TEXT,
 occurred_at TIMESTAMPTZ NOT NULL,
 recorded_by_ref TEXT NOT NULL CHECK (length(btrim(recorded_by_ref))>0),
 evidence_ref TEXT NOT NULL CHECK (length(btrim(evidence_ref))>0),
 exception_reason TEXT,
 CHECK ((outcome IN ('missed','blocked','unsafe_to_collect') AND length(btrim(COALESCE(exception_reason,'')))>0)
     OR outcome IN ('collected','partial')),
 CHECK ((volume_estimate IS NULL) = (unit_code IS NULL))
);

CREATE TABLE IF NOT EXISTS ug_waste.service_incidents (
 incident_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 incident_ref TEXT NOT NULL UNIQUE CHECK (incident_ref ~ '^UGW-INC-[A-Z0-9-]{3,40}$'),
 shift_id BIGINT NOT NULL REFERENCES ug_waste.shifts(shift_id) ON DELETE RESTRICT,
 stop_id BIGINT REFERENCES ug_waste.route_stops(stop_id) ON DELETE RESTRICT,
 category TEXT NOT NULL CHECK (category IN ('missed_pickup','vehicle_breakdown','access_blocked','overflow','safety','other')),
 summary_redacted TEXT NOT NULL CHECK (length(btrim(summary_redacted))>0),
 reported_by_ref TEXT NOT NULL CHECK (length(btrim(reported_by_ref))>0),
 reported_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open','assigned','resolved','closed')),
 resolution_evidence_ref TEXT,
 resolved_at TIMESTAMPTZ,
 CHECK ((status IN ('resolved','closed')) = (resolved_at IS NOT NULL AND resolution_evidence_ref IS NOT NULL))
);

CREATE INDEX IF NOT EXISTS ix_waste_shift_schedule ON ug_waste.shifts(route_id,planned_start,status);
CREATE INDEX IF NOT EXISTS ix_waste_pickup_outcome ON ug_waste.pickup_events(shift_id,outcome,occurred_at);
CREATE INDEX IF NOT EXISTS ix_waste_incident_queue ON ug_waste.service_incidents(status,reported_at);

COMMENT ON SCHEMA ug_waste IS 'Synthetic municipal waste collection reliability example; no household identity records.';
