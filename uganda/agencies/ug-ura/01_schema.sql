-- PostgreSQL 15+; synthetic tax metadata/amounts only.
CREATE SCHEMA IF NOT EXISTS ura_demo;
CREATE TABLE IF NOT EXISTS ura_demo.tax_accounts(
 account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 taxpayer_ref TEXT NOT NULL UNIQUE,account_type TEXT NOT NULL CHECK(account_type IN('individual_demo','business_demo','institution_demo')),
 registered_area_code TEXT NOT NULL,is_active BOOLEAN NOT NULL DEFAULT TRUE,created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS ura_demo.filings(
 filing_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 filing_ref TEXT NOT NULL UNIQUE,account_id BIGINT NOT NULL REFERENCES ura_demo.tax_accounts(account_id) ON DELETE RESTRICT,
 tax_type TEXT NOT NULL CHECK(tax_type IN('vat_demo','income_demo','withholding_demo','customs_demo','other_demo')),
 period_start DATE NOT NULL,period_end DATE NOT NULL,revision_no INTEGER NOT NULL CHECK(revision_no>0),
 filed_at TIMESTAMPTZ NOT NULL,declared_payable NUMERIC(20,2) NOT NULL CHECK(declared_payable>=0),
 assessed_payable NUMERIC(20,2) NOT NULL CHECK(assessed_payable>=0),
 currency CHAR(3) NOT NULL DEFAULT 'UGX',status TEXT NOT NULL DEFAULT 'filed' CHECK(status IN('draft','filed','assessed','amended','closed','disputed')),
 source_document_ref TEXT NOT NULL,created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK(period_end>=period_start),UNIQUE(account_id,tax_type,period_start,period_end,revision_no)
);
CREATE TABLE IF NOT EXISTS ura_demo.payments(
 payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 payment_ref TEXT NOT NULL UNIQUE,filing_id BIGINT NOT NULL REFERENCES ura_demo.filings(filing_id) ON DELETE RESTRICT,
 payment_date DATE NOT NULL,amount NUMERIC(20,2) NOT NULL CHECK(amount>0),
 currency CHAR(3) NOT NULL,channel TEXT NOT NULL CHECK(channel IN('bank_transfer','mobile_money_batch','bank_slip','other')),
 external_reference TEXT NOT NULL,idempotency_key TEXT NOT NULL UNIQUE,created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS ura_demo.filing_events(
 event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 filing_id BIGINT NOT NULL REFERENCES ura_demo.filings(filing_id) ON DELETE RESTRICT,
 previous_status TEXT,new_status TEXT NOT NULL CHECK(new_status IN('draft','filed','assessed','amended','closed','disputed')),
 note TEXT NOT NULL,actor_ref TEXT NOT NULL,happened_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_ura_filing_account_period ON ura_demo.filings(account_id,period_end DESC);
CREATE INDEX IF NOT EXISTS ix_ura_filing_status_period ON ura_demo.filings(status,period_end);
CREATE INDEX IF NOT EXISTS ix_ura_payment_filing_date ON ura_demo.payments(filing_id,payment_date DESC);
CREATE INDEX IF NOT EXISTS ix_ura_filing_event_history ON ura_demo.filing_events(filing_id,happened_at DESC,event_id DESC);
COMMENT ON TABLE ura_demo.tax_accounts IS 'Opaque demo references only; no national tax identifier is stored.';
COMMENT ON TABLE ura_demo.filings IS 'Synthetic amounts supplied as inputs; no legal tax computation is represented.';
