-- PostgreSQL 15+; synthetic logistics data only.
CREATE SCHEMA IF NOT EXISTS nms_demo;
CREATE TABLE IF NOT EXISTS nms_demo.warehouses(
 warehouse_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,warehouse_code TEXT NOT NULL UNIQUE,
 warehouse_label TEXT NOT NULL,locality_code TEXT NOT NULL,is_active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS nms_demo.facilities(
 facility_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,facility_code TEXT NOT NULL UNIQUE,
 facility_label TEXT NOT NULL,facility_level TEXT NOT NULL CHECK(facility_level IN('hospital','health_centre','clinic','other')),
 locality_code TEXT NOT NULL,is_active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS nms_demo.medicines(
 medicine_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,medicine_code TEXT NOT NULL UNIQUE,
 medicine_label TEXT NOT NULL,unit_of_measure TEXT NOT NULL DEFAULT 'unit',is_active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS nms_demo.batches(
 batch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,batch_code TEXT NOT NULL UNIQUE,
 medicine_id BIGINT NOT NULL REFERENCES nms_demo.medicines(medicine_id) ON DELETE RESTRICT,
 expiry_date DATE NOT NULL,batch_status TEXT NOT NULL DEFAULT 'active' CHECK(batch_status IN('active','quarantined','recalled')),
 source_reference TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS nms_demo.dispatches(
 dispatch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,dispatch_ref TEXT NOT NULL UNIQUE,
 warehouse_id BIGINT NOT NULL REFERENCES nms_demo.warehouses(warehouse_id) ON DELETE RESTRICT,
 facility_id BIGINT NOT NULL REFERENCES nms_demo.facilities(facility_id) ON DELETE RESTRICT,
 dispatch_date DATE NOT NULL,status TEXT NOT NULL DEFAULT 'planned' CHECK(status IN('planned','dispatched','received','disputed','cancelled')),
 dispatch_document_ref TEXT NOT NULL,created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS nms_demo.dispatch_lines(
 dispatch_id BIGINT NOT NULL REFERENCES nms_demo.dispatches(dispatch_id) ON DELETE RESTRICT,
 batch_id BIGINT NOT NULL REFERENCES nms_demo.batches(batch_id) ON DELETE RESTRICT,
 quantity_sent INTEGER NOT NULL CHECK(quantity_sent>0),PRIMARY KEY(dispatch_id,batch_id)
);
CREATE TABLE IF NOT EXISTS nms_demo.receipt_entries(
 receipt_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,receipt_ref TEXT NOT NULL UNIQUE,
 dispatch_id BIGINT NOT NULL,batch_id BIGINT NOT NULL,quantity_received INTEGER NOT NULL CHECK(quantity_received>0),
 received_at TIMESTAMPTZ NOT NULL DEFAULT now(),receipt_document_ref TEXT NOT NULL,idempotency_key TEXT NOT NULL UNIQUE,
 FOREIGN KEY(dispatch_id,batch_id) REFERENCES nms_demo.dispatch_lines(dispatch_id,batch_id) ON DELETE RESTRICT
);
CREATE TABLE IF NOT EXISTS nms_demo.dispatch_events(
 event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,dispatch_id BIGINT NOT NULL REFERENCES nms_demo.dispatches(dispatch_id) ON DELETE RESTRICT,
 previous_status TEXT,new_status TEXT NOT NULL CHECK(new_status IN('planned','dispatched','received','disputed','cancelled')),
 note TEXT NOT NULL,actor_ref TEXT NOT NULL,happened_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_nms_dispatch_facility_date ON nms_demo.dispatches(facility_id,dispatch_date DESC);
CREATE INDEX IF NOT EXISTS ix_nms_dispatch_status_date ON nms_demo.dispatches(status,dispatch_date);
CREATE INDEX IF NOT EXISTS ix_nms_receipt_dispatch_batch ON nms_demo.receipt_entries(dispatch_id,batch_id,received_at DESC);
COMMENT ON TABLE nms_demo.receipt_entries IS 'Synthetic receiving records; final-receipt state and total shipped quantity must be reconciled.';