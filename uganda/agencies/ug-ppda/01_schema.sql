-- PostgreSQL 15+; synthetic procurement metadata only.
CREATE SCHEMA IF NOT EXISTS ppda_demo;
CREATE TABLE IF NOT EXISTS ppda_demo.procurement_plans(
 plan_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,plan_ref TEXT NOT NULL UNIQUE,
 entity_ref TEXT NOT NULL,procurement_title TEXT NOT NULL,
 procurement_method TEXT NOT NULL CHECK(procurement_method IN('open','restricted','request_for_quotation','framework','other')),
 estimated_value_ugx NUMERIC(20,2) NOT NULL CHECK(estimated_value_ugx>=0),
 fiscal_year_start INTEGER NOT NULL CHECK(fiscal_year_start BETWEEN 2000 AND 2199),
 status TEXT NOT NULL DEFAULT 'draft' CHECK(status IN('draft','approved','cancelled')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS ppda_demo.tenders(
 tender_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,tender_ref TEXT NOT NULL UNIQUE,
 plan_id BIGINT NOT NULL REFERENCES ppda_demo.procurement_plans(plan_id) ON DELETE RESTRICT,
 advertised_at DATE,closing_at DATE,tender_status TEXT NOT NULL DEFAULT 'draft'
 CHECK(tender_status IN('draft','advertised','closed','evaluation_recorded','cancelled')),
 source_notice_ref TEXT,
 CHECK(closing_at IS NULL OR advertised_at IS NULL OR closing_at>=advertised_at)
);
CREATE TABLE IF NOT EXISTS ppda_demo.contracts(
 contract_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,contract_ref TEXT NOT NULL UNIQUE,
 tender_id BIGINT NOT NULL UNIQUE REFERENCES ppda_demo.tenders(tender_id) ON DELETE RESTRICT,
 supplier_ref TEXT NOT NULL,contract_value_ugx NUMERIC(20,2) NOT NULL CHECK(contract_value_ugx>=0),
 start_date DATE NOT NULL,end_date DATE NOT NULL,
 contract_status TEXT NOT NULL DEFAULT 'active' CHECK(contract_status IN('active','completed','terminated','suspended')),
 CHECK(end_date>=start_date)
);
CREATE TABLE IF NOT EXISTS ppda_demo.contract_milestones(
 milestone_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,milestone_ref TEXT NOT NULL UNIQUE,
 contract_id BIGINT NOT NULL REFERENCES ppda_demo.contracts(contract_id) ON DELETE RESTRICT,
 milestone_title TEXT NOT NULL,due_date DATE NOT NULL,
 planned_value_ugx NUMERIC(20,2) NOT NULL CHECK(planned_value_ugx>=0),
 status TEXT NOT NULL DEFAULT 'planned' CHECK(status IN('planned','submitted','verified','disputed','waived')),
 evidence_ref TEXT,verified_by_ref TEXT,verified_at TIMESTAMPTZ,
 CHECK(status<>'verified' OR (evidence_ref IS NOT NULL AND verified_by_ref IS NOT NULL AND verified_at IS NOT NULL))
);
CREATE TABLE IF NOT EXISTS ppda_demo.milestone_events(
 event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,milestone_id BIGINT NOT NULL REFERENCES ppda_demo.contract_milestones(milestone_id) ON DELETE RESTRICT,
 previous_status TEXT,new_status TEXT NOT NULL CHECK(new_status IN('planned','submitted','verified','disputed','waived')),
 note TEXT NOT NULL,actor_ref TEXT NOT NULL,evidence_ref TEXT,happened_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_ppda_tenders_plan_status ON ppda_demo.tenders(plan_id,tender_status);
CREATE INDEX IF NOT EXISTS ix_ppda_contracts_end_status ON ppda_demo.contracts(end_date,contract_status);
CREATE INDEX IF NOT EXISTS ix_ppda_milestones_due_status ON ppda_demo.contract_milestones(due_date,status);
CREATE INDEX IF NOT EXISTS ix_ppda_event_history ON ppda_demo.milestone_events(milestone_id,happened_at DESC);