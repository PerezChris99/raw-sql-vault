-- Purpose: synthetic public procurement notice, award, contract variation and delivery milestone monitor.
-- Engine: PostgreSQL 15+. Additive bootstrap; no real bid or supplier records.
CREATE SCHEMA IF NOT EXISTS ug_procurement;

CREATE TABLE IF NOT EXISTS ug_procurement.procurement_plans (
 plan_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 plan_ref TEXT NOT NULL UNIQUE CHECK (plan_ref ~ '^UGPP-[A-Z0-9-]{3,40}$'),
 procuring_entity_ref TEXT NOT NULL CHECK (length(btrim(procuring_entity_ref))>0),
 fiscal_year TEXT NOT NULL CHECK (fiscal_year ~ '^[0-9]{4}(/[0-9]{4})?$'),
 title TEXT NOT NULL CHECK (length(btrim(title))>0),
 estimated_value NUMERIC(16,2) NOT NULL CHECK (estimated_value>0),
 currency_code CHAR(3) NOT NULL DEFAULT 'UGX' CHECK (currency_code ~ '^[A-Z]{3}$'),
 status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','approved','published','retired')),
 approved_by_ref TEXT,
 approved_at TIMESTAMPTZ,
 approval_evidence_ref TEXT,
 CHECK ((status IN ('approved','published','retired')) = (approved_at IS NOT NULL)),
 CHECK ((approved_at IS NULL AND approved_by_ref IS NULL AND approval_evidence_ref IS NULL)
    OR (approved_at IS NOT NULL AND length(btrim(COALESCE(approved_by_ref,'')))>0 AND length(btrim(COALESCE(approval_evidence_ref,'')))>0)
 )
);

CREATE TABLE IF NOT EXISTS ug_procurement.notices (
 notice_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 notice_ref TEXT NOT NULL UNIQUE CHECK (notice_ref ~ '^UGPN-[A-Z0-9-]{3,40}$'),
 plan_id BIGINT NOT NULL REFERENCES ug_procurement.procurement_plans(plan_id) ON DELETE RESTRICT,
 notice_title TEXT NOT NULL CHECK (length(btrim(notice_title))>0),
 procurement_method TEXT NOT NULL CHECK (procurement_method IN ('open_competitive','restricted','request_for_quotes','direct_award','other')),
 published_at TIMESTAMPTZ,
 closing_at TIMESTAMPTZ NOT NULL,
 status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','published','closed','cancelled')),
 public_notice_url TEXT,
 CHECK (published_at IS NULL OR closing_at>published_at),
 CHECK (status NOT IN ('published','closed') OR published_at IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS ug_procurement.awards (
 award_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 award_ref TEXT NOT NULL UNIQUE CHECK (award_ref ~ '^UGPA-[A-Z0-9-]{3,40}$'),
 notice_id BIGINT NOT NULL UNIQUE REFERENCES ug_procurement.notices(notice_id) ON DELETE RESTRICT,
 supplier_ref TEXT NOT NULL CHECK (length(btrim(supplier_ref))>0),
 awarded_amount NUMERIC(16,2) NOT NULL CHECK (awarded_amount>0),
 currency_code CHAR(3) NOT NULL CHECK (currency_code ~ '^[A-Z]{3}$'),
 decision_at TIMESTAMPTZ NOT NULL,
 decision_by_ref TEXT NOT NULL CHECK (length(btrim(decision_by_ref))>0),
 decision_evidence_ref TEXT NOT NULL CHECK (length(btrim(decision_evidence_ref))>0),
 disclosure_status TEXT NOT NULL DEFAULT 'pending_review' CHECK (disclosure_status IN ('pending_review','publishable','restricted','withheld')),
 contract_ref TEXT UNIQUE
);

CREATE TABLE IF NOT EXISTS ug_procurement.contract_deliverables (
 deliverable_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 award_id BIGINT NOT NULL REFERENCES ug_procurement.awards(award_id) ON DELETE RESTRICT,
 deliverable_code TEXT NOT NULL CHECK (length(btrim(deliverable_code))>0),
 description TEXT NOT NULL CHECK (length(btrim(description))>0),
 due_on DATE NOT NULL,
 acceptance_criteria_ref TEXT NOT NULL CHECK (length(btrim(acceptance_criteria_ref))>0),
 status TEXT NOT NULL DEFAULT 'planned' CHECK (status IN ('planned','submitted','under_review','accepted','rejected','waived')),
 UNIQUE(award_id,deliverable_code)
);

CREATE TABLE IF NOT EXISTS ug_procurement.contract_variations (
 variation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 variation_ref TEXT NOT NULL UNIQUE CHECK (variation_ref ~ '^UGPV-[A-Z0-9-]{3,40}$'),
 award_id BIGINT NOT NULL REFERENCES ug_procurement.awards(award_id) ON DELETE RESTRICT,
 value_delta NUMERIC(16,2) NOT NULL CHECK (value_delta<>0),
 reason TEXT NOT NULL CHECK (length(btrim(reason))>0),
 evidence_ref TEXT NOT NULL CHECK (length(btrim(evidence_ref))>0),
 requested_by_ref TEXT NOT NULL CHECK (length(btrim(requested_by_ref))>0),
 status TEXT NOT NULL DEFAULT 'requested' CHECK (status IN ('requested','approved','rejected')),
 reviewed_by_ref TEXT,
 reviewed_at TIMESTAMPTZ,
 review_evidence_ref TEXT,
 CHECK ((status='requested') = (reviewed_at IS NULL)),
 CHECK ((reviewed_at IS NULL AND reviewed_by_ref IS NULL AND review_evidence_ref IS NULL)
    OR (reviewed_at IS NOT NULL AND length(btrim(COALESCE(reviewed_by_ref,'')))>0 AND length(btrim(COALESCE(review_evidence_ref,'')))>0))
);

CREATE TABLE IF NOT EXISTS ug_procurement.audit_events (
 event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 entity_type TEXT NOT NULL CHECK (entity_type IN ('plan','notice','award','deliverable','variation')),
 entity_ref TEXT NOT NULL,
 event_type TEXT NOT NULL,
 actor_ref TEXT NOT NULL,
 reason TEXT NOT NULL,
 evidence_ref TEXT,
 occurred_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_procurement_notices_status ON ug_procurement.notices(status,closing_at);
CREATE INDEX IF NOT EXISTS ix_procurement_deliverables_due ON ug_procurement.contract_deliverables(status,due_on);
CREATE INDEX IF NOT EXISTS ix_procurement_variations_review ON ug_procurement.contract_variations(status,variation_id);
CREATE INDEX IF NOT EXISTS ix_procurement_events_entity ON ug_procurement.audit_events(entity_type,entity_ref,occurred_at DESC);

COMMENT ON SCHEMA ug_procurement IS 'Synthetic procurement transparency and contract delivery monitor; not an official procurement system.';
COMMENT ON COLUMN ug_procurement.awards.supplier_ref IS 'Opaque synthetic supplier token. No bid files, bank details or confidential evaluation records are stored.';
