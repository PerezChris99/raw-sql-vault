-- 1. Keyset pagination returns bounded rows from the canonical sales view.
BEGIN;
DO $test$
DECLARE
    v_count BIGINT;
BEGIN
    SELECT COUNT(*) INTO v_count FROM vault_demo.fn_sales_page(NULL, 1000);
    IF v_count <> 4 THEN
        RAISE EXCEPTION 'ASSERT keyset page expected 4 synthetic countable sales, got %', v_count;
    END IF;

    SELECT COUNT(*) INTO v_count FROM vault_demo.fn_sales_page(NULL, -10);
    IF v_count <> 1 THEN
        RAISE EXCEPTION 'ASSERT keyset page-size lower bound expected 1, got %', v_count;
    END IF;
END;
$test$;
ROLLBACK;

-- 2. RLS filters by transaction-local context and fails closed when absent.
BEGIN;
DELETE FROM tenant_demo.invoices WHERE invoice_number LIKE 'TEST-AUTOPILOT-%';
INSERT INTO tenant_demo.invoices(tenant_id, invoice_number, amount, currency) VALUES
    (101, 'TEST-AUTOPILOT-A', 10, 'UGX'),
    (202, 'TEST-AUTOPILOT-B', 20, 'UGX');

SET LOCAL app.current_tenant_id = '101';
SET LOCAL ROLE tenant_demo_reader;
DO $test$
DECLARE v_count BIGINT;
BEGIN
    SELECT COUNT(*) INTO v_count FROM tenant_demo.invoices;
    IF v_count <> 1 THEN
        RAISE EXCEPTION 'ASSERT RLS tenant 101 expected 1 visible invoice, got %', v_count;
    END IF;
    IF EXISTS (SELECT 1 FROM tenant_demo.invoices WHERE tenant_id <> 101) THEN
        RAISE EXCEPTION 'ASSERT RLS exposed a foreign tenant row';
    END IF;
END;
$test$;
RESET ROLE;

SET LOCAL app.current_tenant_id = '';
SET LOCAL ROLE tenant_demo_reader;
DO $test$
DECLARE v_count BIGINT;
BEGIN
    SELECT COUNT(*) INTO v_count FROM tenant_demo.invoices;
    IF v_count <> 0 THEN
        RAISE EXCEPTION 'ASSERT RLS must return zero rows without tenant context, got %', v_count;
    END IF;
END;
$test$;
RESET ROLE;
ROLLBACK;

-- 3. Audit trigger captures INSERT/UPDATE/DELETE snapshots in the transaction.
BEGIN;
CREATE TABLE IF NOT EXISTS audit_demo.test_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label TEXT NOT NULL
);
DROP TRIGGER IF EXISTS trg_test_records_audit ON audit_demo.test_records;
CREATE TRIGGER trg_test_records_audit
AFTER INSERT OR UPDATE OR DELETE ON audit_demo.test_records
FOR EACH ROW EXECUTE FUNCTION audit_demo.fn_capture_row_change();

DO $test$
DECLARE
    v_id BIGINT;
    v_count BIGINT;
BEGIN
    INSERT INTO audit_demo.test_records(label) VALUES ('synthetic-audit-test')
    RETURNING id INTO v_id;
    UPDATE audit_demo.test_records SET label = 'synthetic-audit-updated' WHERE id = v_id;
    DELETE FROM audit_demo.test_records WHERE id = v_id;

    SELECT COUNT(*) INTO v_count
    FROM audit_demo.row_change_log
    WHERE schema_name = 'audit_demo' AND table_name = 'test_records'
      AND row_key = v_id::text
      AND operation IN ('INSERT', 'UPDATE', 'DELETE');
    IF v_count <> 3 THEN
        RAISE EXCEPTION 'ASSERT audit trigger expected 3 event snapshots, got %', v_count;
    END IF;
END;
$test$;
ROLLBACK;

