-- Purpose: isolated schema for correctness-fix regression examples.
-- Engine: PostgreSQL 15+.
-- Prerequisites: run only in a dedicated demo/test database; no production data.
-- Rerun safety: CREATE IF NOT EXISTS; does not reset existing data.
-- Destructive: no. See sql/tests/07_test_fixtures.sql for explicit fixture reset.

CREATE SCHEMA IF NOT EXISTS vault_demo;

CREATE TABLE IF NOT EXISTS vault_demo.customers (
    customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name TEXT NOT NULL,
    score NUMERIC(5,2),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_customers_score_range
        CHECK (score IS NULL OR score BETWEEN 0 AND 100)
);

CREATE TABLE IF NOT EXISTS vault_demo.sales (
    sale_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT REFERENCES vault_demo.customers(customer_id)
        ON DELETE RESTRICT,
    amount NUMERIC(18,2) NOT NULL CHECK (amount >= 0),
    currency CHAR(3) NOT NULL DEFAULT 'UGX',
    status TEXT NOT NULL CHECK (
        status IN ('pending', 'paid', 'shipped', 'delivered', 'cancelled', 'refunded')
    ),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX IF NOT EXISTS ix_sales_customer_id
    ON vault_demo.sales(customer_id);

CREATE INDEX IF NOT EXISTS ix_sales_created_at
    ON vault_demo.sales(created_at);

CREATE INDEX IF NOT EXISTS ix_sales_status_created_at
    ON vault_demo.sales(status, created_at);

CREATE TABLE IF NOT EXISTS vault_demo.users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name TEXT NOT NULL CHECK (length(btrim(display_name)) > 0),
    email TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ux_users_email UNIQUE (email),
    CONSTRAINT ck_users_email_nonempty CHECK (length(btrim(email)) > 2)
);

COMMENT ON SCHEMA vault_demo IS
    'Synthetic-only namespace used to demonstrate SQL correctness patterns.';
COMMENT ON TABLE vault_demo.customers IS
    'Synthetic customer scores for demonstrating explicit NULL semantics.';
COMMENT ON TABLE vault_demo.sales IS
    'Synthetic sales ledger; statuses and countable-sale policy are illustrative.';
COMMENT ON TABLE vault_demo.users IS
    'Synthetic identities used only to test an idempotent batch insertion routine.';