-- Purpose: locate likely duplicate places within a metre-based tolerance.
-- Engine: PostgreSQL 15+ with PostGIS; test image uses a PostGIS-enabled PostgreSQL.
-- Rerun safety: CREATE EXTENSION IF NOT EXISTS, CREATE TABLE/INDEX IF NOT EXISTS,
-- and CREATE OR REPLACE VIEW.
-- Important: a match is a review candidate, not proof that two records are identical.

CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE IF NOT EXISTS vault_demo.places (
    place_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    name_normalized TEXT NOT NULL,
    location GEOGRAPHY(POINT, 4326) NOT NULL,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_places_location_gix
    ON vault_demo.places USING GIST(location)
    WHERE is_deleted = FALSE;

CREATE INDEX IF NOT EXISTS ix_places_name_normalized
    ON vault_demo.places(name_normalized)
    WHERE is_deleted = FALSE;

CREATE OR REPLACE VIEW vault_demo.v_spatial_duplicate_pairs AS
SELECT
    a.place_id AS a_id,
    b.place_id AS b_id,
    a.name_normalized,
    ST_Distance(a.location, b.location) AS metres_apart
FROM vault_demo.places AS a
JOIN vault_demo.places AS b
  ON a.place_id < b.place_id
 AND a.name_normalized = b.name_normalized
 AND ST_DWithin(a.location, b.location, 10.0)
WHERE a.is_deleted = FALSE
  AND b.is_deleted = FALSE;

COMMENT ON VIEW vault_demo.v_spatial_duplicate_pairs IS
    'Canonical unordered candidate pairs of matching normalized names within 10 metres.';