-- Purpose: capture row changes for tables explicitly opted into auditing.
-- Engine: PostgreSQL 15+; isolated scratch database required.
-- Audit logs can contain sensitive before/after values; restrict access/retention.
-- The app.audit_actor_ref setting is trustworthy only when set by trusted middleware.

CREATE SCHEMA IF NOT EXISTS audit_demo;

CREATE TABLE IF NOT EXISTS audit_demo.row_change_log (
    audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schema_name TEXT NOT NULL,
    table_name TEXT NOT NULL,
    operation TEXT NOT NULL CHECK (operation IN ('INSERT', 'UPDATE', 'DELETE')),
    row_key TEXT,
    before_data JSONB,
    after_data JSONB,
    actor_context TEXT,
    transaction_id BIGINT NOT NULL DEFAULT txid_current(),
    changed_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);

CREATE INDEX IF NOT EXISTS ix_row_change_log_row
    ON audit_demo.row_change_log(schema_name, table_name, row_key, changed_at DESC);
CREATE INDEX IF NOT EXISTS ix_row_change_log_changed_at
    ON audit_demo.row_change_log(changed_at DESC);

CREATE OR REPLACE FUNCTION audit_demo.fn_capture_row_change()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, audit_demo
AS $function$
DECLARE
    v_old JSONB;
    v_new JSONB;
    v_key TEXT;
BEGIN
    IF TG_OP IN ('UPDATE', 'DELETE') THEN
        v_old := to_jsonb(OLD);
        v_key := COALESCE(v_old ->> 'id', v_old ->> TG_ARGV[0]);
    END IF;

    IF TG_OP IN ('INSERT', 'UPDATE') THEN
        v_new := to_jsonb(NEW);
        v_key := COALESCE(v_new ->> 'id', v_new ->> TG_ARGV[0], v_key);
    END IF;

    INSERT INTO audit_demo.row_change_log
        (schema_name, table_name, operation, row_key, before_data, after_data, actor_context)
    VALUES (
        TG_TABLE_SCHEMA, TG_TABLE_NAME, TG_OP, v_key, v_old, v_new,
        current_setting('app.audit_actor_ref', TRUE)
    );

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$function$;

REVOKE ALL ON FUNCTION audit_demo.fn_capture_row_change() FROM PUBLIC;

REVOKE ALL ON FUNCTION audit_demo.fn_capture_row_change() FROM PUBLIC;

COMMENT ON TABLE audit_demo.row_change_log IS
    'Restricted row-change evidence; actor_context is trusted only if set by trusted middleware.';