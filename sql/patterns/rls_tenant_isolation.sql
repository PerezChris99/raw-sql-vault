-- Purpose: demonstrate database-enforced tenant isolation.
-- Engine: PostgreSQL 15+.
-- Prerequisites: isolated scratch database; no production data.
-- Set trusted context per transaction using SET LOCAL app.current_tenant_id = '42'.
-- Do not derive tenant authority directly from an unverified request header.

CREATE SCHEMA IF NOT EXISTS tenant_demo;

CREATE TABLE IF NOT EXISTS tenant_demo.invoices (
    invoice_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    invoice_number TEXT NOT NULL,
    amount NUMERIC(18,2) NOT NULL CHECK (amount >= 0),
    currency CHAR(3) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (tenant_id, invoice_number)
);

CREATE INDEX IF NOT EXISTS ix_invoices_tenant_id
    ON tenant_demo.invoices(tenant_id);

ALTER TABLE tenant_demo.invoices ENABLE ROW LEVEL SECURITY;
ALTER TABLE tenant_demo.invoices FORCE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS tenant_invoice_isolation ON tenant_demo.invoices;
CREATE POLICY tenant_invoice_isolation
ON tenant_demo.invoices
USING (
    tenant_id = NULLIF(current_setting('app.current_tenant_id', TRUE), '')::BIGINT
)
WITH CHECK (
    tenant_id = NULLIF(current_setting('app.current_tenant_id', TRUE), '')::BIGINT
);

COMMENT ON POLICY tenant_invoice_isolation ON tenant_demo.invoices IS
    'Rows are invisible and unwritable when trusted transaction-local tenant context is absent.';