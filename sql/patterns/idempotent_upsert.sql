-- Purpose: demonstrate idempotent reference-data import.
-- Engine: PostgreSQL 15+.
-- Rerun safety: ON CONFLICT uses an explicit stable business key.
-- This table holds synthetic records only.

CREATE SCHEMA IF NOT EXISTS upsert_demo;

CREATE TABLE IF NOT EXISTS upsert_demo.product_catalog (
    product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku TEXT NOT NULL UNIQUE,
    display_name TEXT NOT NULL,
    price NUMERIC(18,2) NOT NULL CHECK (price >= 0),
    currency CHAR(3) NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

INSERT INTO upsert_demo.product_catalog (sku, display_name, price, currency)
VALUES ('SYN-001', 'Synthetic reference product', 25000.00, 'UGX')
ON CONFLICT (sku) DO UPDATE
SET display_name = EXCLUDED.display_name,
    price = EXCLUDED.price,
    currency = EXCLUDED.currency,
    updated_at = now();

COMMENT ON TABLE upsert_demo.product_catalog IS
    'Synthetic upsert demonstration; choose DO NOTHING when the source is not authoritative.';